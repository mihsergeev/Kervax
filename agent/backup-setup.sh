# a status file the script writes about its result: STATE=/app/x/data/backup.json
cb_var_state() {
  awk -F'\t' 'toupper($1) ~ /(^|_)(STATE|STATUS|RESULT|MARK|MARKER|REPORT)(_|$)/ && $2 ~ /\.json$/ { print $2 }' <<<"$1" \
    | while IFS= read -r f; do
        [ -f "$f" ] && [ "$(stat -c %s "$f" 2>/dev/null || echo 999999)" -le 65536 ] && { printf '%s' "$f"; break; }
      done
}

# "ok at size" from a small JSON status file: ok 1/0/-1 (unknown), at - unix time (0 unknown)
CB_ST_OK_RE='"(ok|success|succeeded)"[[:space:]]*:[[:space:]]*(true|false|1|0)([^0-9a-z]|$)'
CB_ST_STATUS_RE='"(status|result|state)"[[:space:]]*:[[:space:]]*"(ok|success|succeeded|done|completed|failed|failure|fail|error)"'
CB_ST_AT_RE='"(at|finished_at|finished|ended_at|end|completed_at|time|timestamp|ts|last_run|date)"[[:space:]]*:[[:space:]]*("([^"]+)"|([0-9]{9,13}))'
CB_ST_SIZE_RE='"(size|bytes|size_bytes)"[[:space:]]*:[[:space:]]*([0-9]+)'
cb_state_parse() {
  local raw ok=-1 at=0 size=0 v
  raw="$(head -c 65536 "$1" 2>/dev/null | tr -d '\000' | tr '\n\r' '  ')"
  raw="${raw,,}"
  if [[ "$raw" =~ $CB_ST_OK_RE ]]; then
    case "${BASH_REMATCH[2]}" in true|1) ok=1 ;; *) ok=0 ;; esac
  elif [[ "$raw" =~ $CB_ST_STATUS_RE ]]; then
    case "${BASH_REMATCH[2]}" in ok|success|succeeded|done|completed) ok=1 ;; *) ok=0 ;; esac
  fi
  if [[ "$raw" =~ $CB_ST_AT_RE ]]; then
    if [ -n "${BASH_REMATCH[4]}" ]; then
      v="${BASH_REMATCH[4]}"; [ "${#v}" -ge 13 ] && v=$((v / 1000)); at="$v"
    else
      at="$(date -d "${BASH_REMATCH[3]}" +%s 2>/dev/null || echo 0)"
    fi
  fi
  [[ "$raw" =~ $CB_ST_SIZE_RE ]] && size="${BASH_REMATCH[2]}"
  printf '%s %s %s' "$ok" "${at:-0}" "$size"
}

# "mtime<TAB>repo dir<TAB>repo dirs seen" - the newest restic snapshot saved into restic's cache in
# [$2, $2 + 12h]. A finished `restic backup` writes its snapshot into the cache as well, so a new
# file there is the run's result. $3 - look only into this repository's cache.
cb_restic_saved() {
  local base="$1" st="$2" only="$3"
  [ -d "$base" ] || return 0
  timeout 20 find "$base" -mindepth 3 -maxdepth 4 -path "$base/${only:-*}/snapshots/*" -type f -newermt "@$st" \
      -printf '%T@\t%P\n' 2>/dev/null \
    | awk -F'\t' -v lim=$((st + 43200)) '
        { t = int($1); if (t > lim) next; split($2, p, "/"); if (!(p[1] in seen)) { seen[p[1]] = 1; nd++ }
          if (t > best) { best = t; dir = p[1] } }
        END { if (best) printf "%d\t%s\t%d", best, dir, nd }'
}

# is the script running now: under a shell (sh /x/backup.sh, bash -e /x/backup.sh) or by itself
cb_running() {
  local p
  [ -n "$1" ] || return 1
  p="$(printf '%s' "$1" | sed 's/[][\.*^$+?(){}|]/\\&/g')"
  pgrep -f -- "(^|/)(ba|da|z|k)?sh( [^ ]+)* $p( |$)|^$p( |$)" >/dev/null 2>&1
}

cmd_custom_scan() {
  set +euo pipefail  # a missing file or an empty grep is a normal outcome of a scan, not an error
  local now; now=$(date +%s)
  CB_CONTAINERS=()
  if command -v docker >/dev/null 2>&1; then
    mapfile -t CB_CONTAINERS < <(timeout 10 docker ps --format '{{.Names}}' 2>/dev/null)
  fi
  local -a jobs=()
  local -A mj_json=() mj_names=() mj_lab=() mj_used=()

  # 1. metrics files
  local dir f base parsed line names ts checks bad size dur lab dbs okv dname dok dts dsz
  for dir in "${CB_PROM_DIRS[@]}"; do
    for f in "$dir"/*.prom; do
      [ -f "$f" ] || continue
      base="$(basename "$f" .prom)"
      parsed="$(cb_prom_parse "$f" "$base")"
      [ -n "$parsed" ] || continue
      names=""; ts=0; checks=0; bad=0; size=0; dur=0; lab=""; dbs=""
      while IFS= read -r line; do
        case "$line" in
          NAMES*) names="${line#NAMES}" ;;
          "TS "*) ts="${line#TS }" ;;
          "OK "*) read -r _ checks bad <<<"$line" ;;
          "SIZE "*) size="${line#SIZE }" ;;
          "DUR "*) dur="${line#DUR }" ;;
          LAB*) lab="${line#LAB}" ;;
          DB$'\t'*)
            IFS=$'\t' read -r _ dname dok dts dsz <<<"$line"
            dbs="${dbs:+$dbs,}{\"name\":\"$(json_escape "$(cb_clean "$dname")")\",\"ok\":${dok:--1},\"ts\":${dts:-0},\"size_bytes\":${dsz:-0}}"
            ;;
        esac
      done <<<"$parsed"
      okv=-1; [ "${checks:-0}" -gt 0 ] && { [ "${bad:-0}" -eq 0 ] && okv=1 || okv=0; }
      mj_names[$base]="$names"
      mj_lab[$base]="$lab"
      mj_json[$base]="\"metrics\":\"$(json_escape "$f")\",\"ok\":$okv,\"ok_ts\":${ts:-0},\"size_bytes\":${size:-0},\"duration_sec\":${dur:-0},\"dbs\":[$dbs]"
    done
  done

  # a cron job or a timer that WRITES one of these metrics files takes its status from them
  cb_linked_metrics() {
    local text="$1" id nm pfx
    for id in "${!mj_names[@]}"; do
      [ -n "${mj_used[$id]:-}" ] && continue
      if grep -qF -- "$id.prom" <<<"$text"; then printf '%s' "$id"; return; fi
      for nm in ${mj_names[$id]}; do
        if grep -qF -- "$nm" <<<"$text"; then printf '%s' "$id"; return; fi
      done
      # metric names are often put together from a prefix: pg_backup_ + ok
      pfx="${id%_*}"
      if [ "$pfx" != "$id" ] && [ "${#pfx}" -ge 4 ] && grep -qE "(^|[^A-Za-z0-9])${pfx}_" <<<"$text"; then
        printf '%s' "$id"; return
      fi
    done
  }

  # does the text write one of the found metrics files: its file name or a full metric name in it.
  # Such a job is a backup job whatever it is called (ru-copy.sh: restic copy, metrics in ru_copy.prom)
  cb_writes_metrics() {
    local text="$1" id nm
    for id in "${!mj_names[@]}"; do
      grep -qF -- "$id.prom" <<<"$text" && return 0
      for nm in ${mj_names[$id]}; do grep -qF -- "$nm" <<<"$text" && return 0; done
    done
    return 1
  }

  # $1 id, $2 kind, $3 name, $4 description, $5 schedule, $6 names and commands, $7 script body,
  # $8 the job's own status fields
  cb_emit() {
    local id="$1" kind="$2" name="$3" desc="$4" sched="$5" strong="$6" body="$7" status="$8" m engines files=false
    m="$(cb_linked_metrics "$strong"$'\n'"$body")"
    if [ -n "$m" ]; then
      mj_used[$m]=1
      # the metrics fields go last: they override the guesses from files and log times
      status="$status,${mj_json[$m]}"
      strong="$strong ${mj_names[$m]} ${mj_lab[$m]}"
    fi
    engines="$(cb_engines "$strong" "$body")"
    if [ "$engines" = "[]" ] && { cb_is_files "$strong" || grep -qiE "$CB_FILE_TOOL_RE" <<<"$body"; }; then
      files=true
    fi
    jobs+=("{\"id\":\"$(json_escape "$id")\",\"kind\":\"$kind\",\"name\":\"$(json_escape "$(cb_clean "$name")")\",\"desc\":\"$(json_escape "$(cb_clean "$desc")")\",\"schedule\":\"$(json_escape "$(cb_clean "$sched")")\",\"engines\":$engines,\"files\":$files,\"containers\":$(cb_containers "$strong"$'\n'"$body"),$status}")
  }

  # 2. systemd timers
  local t svc props k v result estatus exit_ts active execs script body desc cal next last_mono last_ts err ok ok_ts
  while IFS= read -r t; do
    [ -n "$t" ] || continue
    [[ "${t,,}" =~ $CB_SKIP_RE ]] && continue
    svc="$(systemctl show "$t" -p Unit --value 2>/dev/null)"; [ -n "$svc" ] || continue
    props="$(systemctl show "$svc" --timestamp=unix -p Result -p ExecMainStatus -p ExecMainExitTimestamp -p ActiveState -p ExecStart -p Description 2>/dev/null)"
    err=$?
    # systemd older than 247 has no --timestamp=unix: monotonic time plus boot time instead
    [ "$err" -eq 0 ] || props="$(systemctl show "$svc" -p Result -p ExecMainStatus -p ExecMainExitTimestampMonotonic -p ActiveState -p ExecStart -p Description 2>/dev/null)"
    result=""; estatus=""; exit_ts=0; active=""; execs=""; desc=""
    while IFS='=' read -r k v; do
      case "$k" in
        Result) result="$v" ;; ExecMainStatus) estatus="$v" ;; ActiveState) active="$v" ;;
        ExecStart) execs="$v" ;; Description) desc="$v" ;;
        ExecMainExitTimestamp) [[ "$v" =~ ^@([0-9]+)$ ]] && exit_ts="${BASH_REMATCH[1]}" ;;
        ExecMainExitTimestampMonotonic) [[ "$v" =~ ^[0-9]+$ ]] && [ "$v" -gt 0 ] && exit_ts=$(( $(cb_boot_ts) + v / 1000000 )) ;;
      esac
    done <<<"$props"
    script="$(cb_script_of "$(printf '%s' "$execs" | sed -n 's/.*argv\[\]=\([^;]*\);.*/\1/p')")"
    body="$(cb_body "$script")"
    if ! [[ "${t,,} ${svc,,}" =~ $CB_NAME_RE ]] && ! grep -qiE "$CB_TOOL_RE" <<<"$body" \
       && ! cb_writes_metrics "$execs"$'\n'"$body"; then continue; fi
    cb_maintenance_only "$t $svc $desc" "$body" && continue
    cb_updater_only "$t $svc $desc $script" && continue
    cal="$(systemctl show "$t" --timestamp=unix -p TimersCalendar --value 2>/dev/null)"
    next="$(printf '%s' "$cal" | sed -n 's/.*next_elapse=@\([0-9]*\).*/\1/p' | head -1)"
    cal="$(printf '%s' "$cal" | sed -n 's/.*OnCalendar=\([^;]*\);.*/\1/p' | sed 's/[[:space:]]*$//' | head -1)"
    last_mono="$(systemctl show "$t" -p LastTriggerUSecMonotonic --value 2>/dev/null)"
    last_ts=0; [[ "$last_mono" =~ ^[0-9]+$ ]] && [ "$last_mono" -gt 0 ] && last_ts=$(( $(cb_boot_ts) + last_mono / 1000000 ))
    ok=-1; ok_ts=0
    if [ "$exit_ts" -gt 0 ]; then
      if [ "$result" = success ] && [ "${estatus:-0}" = 0 ]; then ok=1; ok_ts=$exit_ts; else ok=0; fi
    fi
    cb_emit "systemd:$t" systemd "${t%.timer}" "$desc" "$cal" "$t $svc $script $desc" "$body" \
      "\"unit\":\"$(json_escape "$svc")\",\"script\":\"$(json_escape "$script")\",\"ok\":$ok,\"ok_ts\":$ok_ts,\"run_ts\":$exit_ts,\"result\":\"$(json_escape "$result")\",\"running\":$([ "$active" = activating ] && echo true || echo false),\"next_ts\":${next:-0},\"prev_ts\":$last_ts,\"enabled\":$(systemctl is-enabled "$t" >/dev/null 2>&1 && echo true || echo false)"
  done < <(systemctl list-unit-files --type=timer --no-legend 2>/dev/null | awk '{print $1}')

  # 3. cron: user crontabs, system crontabs, cron.{hourly,daily,weekly,monthly}
  # First the jobs that look like backups, then one pass over the cron journal for all of them.
  local src user sched cmd name logf log_ts id d newest
  local -a cron_rows=()
  local -A cron_seen=() CB_LAST=() CB_RDIR=()
  local jobsf; jobsf="$(mktemp)"
  while IFS=$'\t' read -r src user sched cmd; do
    [ -n "$cmd" ] || continue
    [[ "${cmd,,}" =~ $CB_SKIP_RE ]] && continue
    script="$(cb_script_of "$cmd")"
    body="$(cb_body "$script")"
    if ! [[ "${cmd,,}" =~ $CB_NAME_RE ]] && ! grep -qiE "$CB_TOOL_RE" <<<"$cmd"$'\n'"$body" \
       && ! cb_writes_metrics "$cmd"$'\n'"$body"; then continue; fi
    cb_maintenance_only "$cmd" "$body" && continue
    cb_updater_only "$cmd" && continue
    # the command is hashed, never sent: it may carry a password
    id="cron:$(printf '%s|%s' "$user" "$cmd" | sha1sum | cut -c1-12)"
    [ -n "${cron_seen[$id]:-}" ] && continue
    cron_seen[$id]=1
    case "$src" in
      /etc/cron.hourly|/etc/cron.daily|/etc/cron.weekly|/etc/cron.monthly)
        printf '%s\t\t%s\tparts\n' "$id" "${src#/etc/}" >> "$jobsf" ;;
      *) printf '%s\t%s\t%s\tcmd\n' "$id" "$user" "$(cb_cron_logged "$cmd")" >> "$jobsf" ;;
    esac
    cron_rows+=("$src"$'\t'"$user"$'\t'"$sched"$'\t'"$id"$'\t'"$cmd")
  done < <(cb_cron_lines)

  # starts from the journal, merged with the ones seen by earlier scans
  local k v r runs_since=$((now - CB_RUNS_DAYS * 86400)) starts journal_ok=0
  if [ -f "$CB_RUNS" ]; then
    while IFS=$'\t' read -r k v r; do
      case "$k" in
        '#since') [[ "$v" =~ ^[0-9]+$ ]] && [ "$v" -gt "$runs_since" ] && runs_since=$((v - 900)) ;;
        cron:*) [[ "$v" =~ ^[0-9]+$ ]] && CB_LAST[$k]="$v"; CB_RDIR[$k]="$r" ;;
      esac
    done < "$CB_RUNS"
  fi
  if [ "${#cron_rows[@]}" -gt 0 ] && starts="$(cb_journal_starts "$jobsf" "$runs_since")"; then
    journal_ok=1
    while IFS=$'\t' read -r k v; do
      [ -n "$k" ] && [ "${v:-0}" -gt "${CB_LAST[$k]:-0}" ] && CB_LAST[$k]="$v"
    done <<<"$starts"
  fi
  rm -f "$jobsf"

  local row home pvars st run_ts run_src ok ok_ts size evidence fail dur statef running rcache learned hit rts rdir rnd sok sat ssz
  for row in "${cron_rows[@]}"; do
    IFS=$'\t' read -r src user sched id cmd <<<"$row"
    script="$(cb_script_of "$cmd")"
    body="$(cb_body "$script")"
    if [ -n "$script" ]; then
      name="$(basename "$script")"
    else
      name="$(printf '%s' "$cmd" | sed -E 's/^([A-Za-z_][A-Za-z0-9_]*=[^ ]* +)*//' | awk '{print $1}')"; name="$(basename "$name")"
    fi
    home="$(getent passwd "$user" 2>/dev/null | cut -d: -f6)"; [ -n "$home" ] || home=/root
    pvars=""; [ -n "$script" ] && pvars="$(cb_path_vars "$script" "$home")"
    running=false; [ -n "$script" ] && cb_running "$script" && running=true

    # when it ran: the logged start; without it - when its log file was last written
    st="${CB_LAST[$id]:-0}"; run_ts=0; run_src=""
    [ "$st" -gt 0 ] && { run_ts="$st"; run_src=journal; }
    logf="$(printf '%s' "$cmd" | grep -oE '(>>?|tee( -a)?)[[:space:]]*/[A-Za-z0-9._/@+-]+' | grep -oE '/[A-Za-z0-9._/@+-]+' | grep -v '^/dev/' | tail -1)"
    log_ts=0; [ -n "$logf" ] && [ -f "$logf" ] && log_ts=$(stat -c %Y "$logf" 2>/dev/null || echo 0)
    [ "$run_ts" -eq 0 ] && [ "$log_ts" -gt 0 ] && { run_ts="$log_ts"; run_src=log; }

    # what it left: the newest file in its output directory...
    ok=-1; ok_ts=0; size=0; evidence=""; fail=""; dur=0
    d="$(cb_var_dir "$pvars")"; [ -n "$d" ] || d="$(cb_dirs "$cmd"$'\n'"$body" | head -1)"
    if [ -n "$d" ]; then
      newest="$(cb_newest "$d")"
      [ -n "$newest" ] && { ok_ts="${newest%% *}"; size="${newest##* }"; evidence=files; }
    fi
    # ...the status file it writes about itself (takes precedence over a file's mtime)...
    statef="$(cb_var_state "$pvars")"
    if [ -n "$statef" ]; then
      read -r sok sat ssz <<<"$(cb_state_parse "$statef")"
      if [ "$sok" != "-1" ]; then
        evidence=state
        [ "${ssz:-0}" -gt 0 ] && size="$ssz"
        if [ "$sok" = 0 ]; then
          ok=0; fail=state
        elif [ "$st" -gt 0 ] && [ "${sat:-0}" -gt 0 ] && [ "$sat" -lt $((st - 120)) ] && [ "$running" = false ] \
             && [ $((now - st)) -ge 1800 ]; then
          # the job ran after the last mark and finished without writing a new one: it died on the way
          ok=0; fail=state_old
        else
          ok=1; [ "${sat:-0}" -gt 0 ] && ok_ts="$sat"
        fi
        [ "$run_ts" -eq 0 ] && [ "${sat:-0}" -gt 0 ] && { run_ts="$sat"; run_src=state; }
      fi
    fi
    # ...and the snapshot restic saved into its cache after the start
    rcache=""
    if grep -qiE 'restic[[:space:]]+([^|;&]*[[:space:]])?backup([[:space:]]|$)' <<<"$cmd"$'\n'"$body" \
       && ! grep -qF -- '--no-cache' <<<"$cmd"$'\n'"$body"; then
      rcache="$(awk -F'\t' '$1 == "RESTIC_CACHE_DIR" { c = $2 } $1 == "XDG_CACHE_HOME" { x = $2 "/restic" } END { print (c != "" ? c : x) }' <<<"$pvars")"
      [ -n "$rcache" ] || rcache="$home/.cache/restic"
    fi
    if [ -n "$rcache" ] && [ "$st" -gt 0 ] && [ "$running" = false ] && [ "$ok" != 0 ]; then
      learned="${CB_RDIR[$id]:-}"
      hit="$(cb_restic_saved "$rcache" "$((st - 5))" "$learned")"
      if [ -n "$hit" ]; then
        IFS=$'\t' read -r rts rdir rnd <<<"$hit"
        # until the job's repository is known, a snapshot counts only if a single repository got one
        if [ -n "$learned" ] || [ "$rnd" = 1 ]; then
          ok=1; ok_ts="$rts"; evidence=restic; dur=$((rts - st)); CB_RDIR[$id]="$rdir"
        fi
      elif [ -n "$learned" ] && [ -n "$script" ] && [ -d "$rcache/$learned/snapshots" ] && [ $((now - st)) -ge 1800 ]; then
        # it ran, has finished, and its repository got no new snapshot
        ok=0; fail=restic; evidence=restic
      fi
    fi

    cb_emit "$id" cron "$name" "" "$sched" "$name $cmd" "$body" \
      "\"user\":\"$(json_escape "$user")\",\"source\":\"$(json_escape "$src")\",\"script\":\"$(json_escape "$script")\",\"ok\":$ok,\"ok_ts\":${ok_ts:-0},\"size_bytes\":${size:-0},\"dir\":\"$(json_escape "$d")\",\"log\":\"$(json_escape "$logf")\",\"run_ts\":${run_ts:-0},\"run_src\":\"$run_src\",\"state\":\"$(json_escape "$statef")\",\"evidence\":\"$evidence\",\"fail\":\"$fail\",\"duration_sec\":${dur:-0},\"running\":$running"
  done

  # the starts and learned repositories survive to the next scan; the journal position moves on
  # only when the journal was actually read
  if [ "${#cron_rows[@]}" -gt 0 ]; then
    local since_out=$(( journal_ok == 1 ? now : (runs_since > now - CB_RUNS_DAYS * 86400 ? runs_since + 900 : 0) ))
    {
      [ "$since_out" -gt 0 ] && printf '#since\t%s\n' "$since_out"
      for k in "${!cron_seen[@]}"; do printf '%s\t%s\t%s\n' "$k" "${CB_LAST[$k]:-0}" "${CB_RDIR[$k]:-}"; done
    } > "$CB_RUNS.tmp" 2>/dev/null && mv -f "$CB_RUNS.tmp" "$CB_RUNS" 2>/dev/null
  fi

  # metrics nobody above claimed: a standalone job (written by something we did not recognise)
  local mid
  for mid in "${!mj_json[@]}"; do
    [ -n "${mj_used[$mid]:-}" ] && continue
    jobs+=("{\"id\":\"metrics:$(json_escape "$mid")\",\"kind\":\"metrics\",\"name\":\"$(json_escape "$mid")\",\"desc\":\"\",\"schedule\":\"\",\"engines\":$(cb_engines "$mid ${mj_names[$mid]}" ""),\"files\":false,\"containers\":$(cb_containers "${mj_lab[$mid]}"),${mj_json[$mid]}}")
  done

  local out="" n=0 j
  for j in "${jobs[@]}"; do
    n=$((n + 1)); [ "$n" -le "$CUSTOM_MAX_JOBS" ] || break
    out="${out:+$out,}$j"
  done
  printf '{"v":1,"ts":%s,"jobs":[%s]}\n' "$now" "$out"
}

# ------- the nightly growth of the backup: restic's summary of every run, from the journal -------
RUNS_JSON="$CUSTOM_DIR/backup-runs.json"
RUNS_MAX=40     # runs kept: more than a month of nightly backups
RUNS_DAYS=45    # how far back the journal is read for the history

# restic summary lines of the backup unit's journal (-o short-unix) -> {"v":1,...,"runs":[...]}.
# A run is recorded at its "processed N files, X in M:SS" line, with the "Files:" and "Added to the
# repository" lines that come before it. mawk-safe: no gawk extensions, big numbers through %.0f.
backup_runs_parse() {
  # the failure goes through the environment: awk -v would eat the backslashes of its JSON escapes
  KV_FAIL="${2:-}" awk -v now="$(date +%s)" -v unit="$1" -v max="$RUNS_MAX" '
    function bytes(v, u,   m) {
      m = 1
      if (u == "KiB") m = 1024
      else if (u == "MiB") m = 1048576
      else if (u == "GiB") m = 1073741824
      else if (u == "TiB") m = 1099511627776
      return v * m
    }
    function secs(x,   a, n) {
      n = split(x, a, ":")
      if (n == 3) return a[1] * 3600 + a[2] * 60 + a[3]
      if (n == 2) return a[1] * 60 + a[2]
      return x + 0
    }
    {
      ts = $1; sub(/\..*/, "", ts)
      msg = $0; sub(/^[^ ]+ [^ ]+ [^ ]+ /, "", msg)
    }
    msg ~ /^Files: / { split(msg, f, /[ ,]+/); fnew = f[2]; fchg = f[4]; next }
    msg ~ /^Added to the repository: / {
      split(msg, f, / +/); st = f[7]; sub(/^\(/, "", st)
      add = bytes(f[5], f[6]); st = bytes(st, f[8]); have = 1; next
    }
    msg ~ /^processed [0-9]+ files, / {
      split(msg, f, / +/)
      if (have) {
        n++
        R[n] = sprintf("{\"ts\":%s,\"add\":%.0f,\"st\":%.0f,\"proc\":%.0f,\"files\":%.0f,\"fnew\":%.0f,\"fchg\":%.0f,\"dur\":%.0f}", \
          ts, add, st, bytes(f[4], f[5]), f[2], fnew, fchg, secs(f[7]))
      }
      have = 0; fnew = 0; fchg = 0; next
    }
    END {
      printf "{\"v\":1,\"ts\":%s,\"unit\":\"%s\",%s\"runs\":[", now, unit, (ENVIRON["KV_FAIL"] != "" ? "\"fail\":" ENVIRON["KV_FAIL"] "," : "")
      for (i = (n > max ? n - max + 1 : 1); i <= n; i++) printf "%s%s", (k++ ? "," : ""), R[i]
      print "]}"
    }'
}

# Why the last run of the backup service failed: {"ts":<end>,"msg":"<restic error>"} or nothing.
# The first restic error line of that run (Fatal: ... / unable to ...), credentials in a repository
# URL masked, control characters dropped - it goes to the panel as is.
backup_last_fail() {
  local svc="$1" inv end msg
  [ "$(systemctl show -p Result --value "$svc" 2>/dev/null)" = success ] && return 0
  inv="$(systemctl show -p InvocationID --value "$svc" 2>/dev/null)"
  [ -n "$inv" ] || return 0
  # restic retries a failing request for minutes ("... returned error, retrying after 1.3s: ...")
  # before it gives up: those lines are the same error again and again, the Fatal line says it once
  local lines
  lines="$(journalctl -u "$svc" _SYSTEMD_INVOCATION_ID="$inv" -o cat -q --no-pager 2>/dev/null \
    | grep -a -E '^Fatal: |unable to |[Ee]rror: |wrong password|connection refused|no such host|certificate' \
    | grep -a -v 'retrying after' || true)"
  msg="$( { printf '%s\n' "$lines" | grep -a -m1 '^Fatal: ' || printf '%s\n' "$lines" | head -n 2; } \
    | tr '\n\t' '  ' | tr -d '\000-\037' | sed -E 's#//[^/@ ]*@#//***@#g; s/ +$//' | cut -c1-300)"
  [ -n "$msg" ] || msg="the backup service ended with $(systemctl show -p Result --value "$svc" 2>/dev/null)"
  end="$(date -d "$(systemctl show -p ExecMainExitTimestamp --value "$svc" 2>/dev/null)" +%s 2>/dev/null || date +%s)"
  printf '{"ts":%s,"msg":"%s"}' "$end" "$(json_escape "$msg")"
}

cmd_backup_runs() {
  local timer svc
  timer="$(find_timer)" || true
  [ -n "$timer" ] || { echo "timer not found" >&2; return 2; }
  svc="${timer%.timer}.service"
  journalctl -u "$svc" --since "-${RUNS_DAYS} days" -o short-unix -q --no-pager 2>/dev/null \
    | grep -a -E ': (Files: |Added to the repository: |processed [0-9]+ files, )' \
    | backup_runs_parse "$svc" "$(backup_last_fail "$svc")"
}

# Rebuilt once per finished run of the backup service (its InvocationID changes), not every minute:
# the journal of 45 days is read only then. A run in progress is left alone until it ends.
backup_runs_maybe() {
  local timer svc inv
  timer="$(find_timer)" || true
  [ -n "$timer" ] || return 0
  svc="${timer%.timer}.service"
  [ "$(systemctl show -p ActiveState --value "$svc" 2>/dev/null)" = activating ] && return 0
  inv="$(systemctl show -p InvocationID --value "$svc" 2>/dev/null)"
  if [ -f "$RUNS_JSON" ] && [ "$inv" = "$(cat "$RUNS_JSON.inv" 2>/dev/null)" ]; then return 0; fi
  install -d -m 0755 "$CUSTOM_DIR"
  (
    flock -n 9 || exit 0
    if nice -n 10 timeout 150 "$0" backup-runs > "$RUNS_JSON.tmp" 2>/dev/null && [ -s "$RUNS_JSON.tmp" ]; then
      mv -f "$RUNS_JSON.tmp" "$RUNS_JSON"; chmod 0644 "$RUNS_JSON"; printf '%s' "$inv" > "$RUNS_JSON.inv"
    else
      rm -f "$RUNS_JSON.tmp"
    fi
  ) 9>/run/kervax-backup-runs.lock
}

# the scan runs from the minute cron, but not more often than CUSTOM_EVERY and never twice at once
custom_scan_maybe() {
  local age="$CUSTOM_EVERY"
  [ -f "$CUSTOM_JSON" ] && age=$(( $(date +%s) - $(stat -c %Y "$CUSTOM_JSON" 2>/dev/null || echo 0) ))
  [ "$age" -ge "$CUSTOM_EVERY" ] || return 0
  install -d -m 0755 "$CUSTOM_DIR"
  (
    flock -n 9 || exit 0
    if nice -n 10 timeout 150 "$0" custom-scan > "$CUSTOM_JSON.tmp" 2>/dev/null && [ -s "$CUSTOM_JSON.tmp" ]; then
      mv -f "$CUSTOM_JSON.tmp" "$CUSTOM_JSON"; chmod 0644 "$CUSTOM_JSON"
    else
      rm -f "$CUSTOM_JSON.tmp"
    fi
  ) 9>/run/kervax-custom-scan.lock
}

# ------- the restore check: restore a few files and the dumps from the latest snapshot -------
VERIFY_JSON="$CUSTOM_DIR/backup-verify.json"
VERIFY_EVERY=$((7 * 86400))  # once a week is enough to catch a repository that went bad
VERIFY_FILES=8               # files compared per check
VERIFY_MAX_SIZE=5M           # small files only: the check must not pull gigabytes

# restic as the backup user, with its cache (root would build a cache of its own, and on a big
# repository that alone is hundreds of megabytes). The env file is root-only, as for the backup
# service (systemd reads it as root): root reads it and hands the variables over the environment.
# The binary is the one the backup runs with: the panel's own copy or, on nodes backed up before
# the panel took over, the system restic (PATH, then the usual places: a timer's PATH can be short).
verify_bin() {
  local b
  for b in "$RESTIC_BIN" "$(command -v restic 2>/dev/null || true)" /usr/local/bin/restic /usr/bin/restic; do
    [ -n "$b" ] && [ -x "$b" ] && { echo "$b"; return 0; }
  done
  return 1
}

# What the backup really runs with, from its systemd unit: the env file (EnvironmentFile=) and the
# user (User=). On nodes backed up before the panel took over, the panel's file names mean
# something else: /etc/systemd-resta.conf there is a notification script with curl, and reading
# it with "." sent a false "backup failed" message on every check. Sets VENV VUSER VHOME VSCRIPT.
verify_ctx() {
  local timer svc f u
  VENV=""; VUSER=""; VHOME=""; VSCRIPT=""
  timer="$(find_timer)" || true
  svc=""; [ -n "$timer" ] && svc="${timer%.timer}.service"
  for f in $( [ -n "$svc" ] && systemctl show -p EnvironmentFiles --value "$svc" 2>/dev/null \
                | sed 's/ *([a-z_]*=[a-z]*)//g' ) "$PROV_ENV"; do
    [ -f "$f" ] && grep -qE '^(export )?RESTIC_REPOSITORY(_FILE)?=' "$f" && { VENV=$f; break; }
  done
  [ -n "$VENV" ] || return 1
  u=""; [ -n "$svc" ] && u=$(systemctl show -p User --value "$svc" 2>/dev/null)
  u=${u:-root}
  id "$u" >/dev/null 2>&1 || return 1
  VUSER=$u
  if [ "$u" = "$PROV_USER" ]; then VHOME=$PROV_HOME; else VHOME=$(getent passwd "$u" | cut -d: -f6); fi
  VHOME=${VHOME:-/root}
  for f in "$PROV_SCRIPT" "$(find_script)"; do
    [ -n "$f" ] && [ -f "$f" ] && grep -q '^INCLUDE_MODE=' "$f" && { VSCRIPT=$f; break; }
  done
  return 0
}

# The env file as data: KEY=VALUE lines for restic and the storage backends only. Never sourced -
# whatever else is in the file must not run.
verify_env() {
  local line k v
  while IFS= read -r line || [ -n "$line" ]; do
    line=${line#export }
    k=${line%%=*}; v=${line#*=}
    [ "$k" != "$line" ] || continue
    case "$k" in
      RESTIC_*|AWS_*|B2_*|AZURE_*|GOOGLE_*|OS_*|ST_*|RCLONE_*|HTTP_PROXY|HTTPS_PROXY|NO_PROXY) ;;
      *) continue ;;
    esac
    case "$k" in *[!A-Z0-9_]*) continue ;; esac
    case "$v" in \"*\") v=${v#\"}; v=${v%\"} ;; \'*\') v=${v#\'}; v=${v%\'} ;; esac
    export "$k=$v"
  done < "$VENV"
}

verify_restic() {
  local bin restic
  bin="$(verify_bin)" || { echo "restic not found: neither $RESTIC_BIN nor in PATH" >&2; return 127; }
  restic="$bin"; [ -f "$PROV_CACERT" ] && restic="$bin --cacert $PROV_CACERT"
  (
    verify_env
    export HOME="$VHOME"
    # shellcheck disable=SC2086 - $restic is the binary plus an optional --cacert, split on purpose
    [ "$VUSER" = root ] && exec $restic "$@"
    exec runuser -p -u "$VUSER" -- $restic "$@"
  )
}

verify_json_str() { printf '%s' "$1" | tr -d '\000-\037' | cut -c1-200 | sed 's/\\/\\\\/g; s/"/\\"/g'; }

# The locks in the repository, one line each: "<kind> <id>". mine - left by a restic of this check
# that is gone (this host, the backup user, shared, not refreshed for 30 minutes); stale - one
# restic itself counts as stale (older than 30 minutes, or of this host with its process gone), not
# ours; excl - a live exclusive lock (the prune or check of the backup server); live - the rest.
verify_locks() {
  local out id j host user pid t ts now me alive
  now=$(date +%s); me=$(hostname)
  # read to the end, never through head: a restic cut off by SIGPIPE is what leaves a lock behind
  out=$(verify_restic list locks --no-lock 2>/dev/null) || return 1
  for id in $(printf '%s\n' "$out" | grep -E '^[0-9a-f]{64}$' || true); do
    j=$(verify_restic cat lock --no-lock "$id" 2>/dev/null | tr -d '\n') || continue  # released meanwhile
    host=$(sed -n 's/.*"hostname": *"\([^"]*\)".*/\1/p' <<<"$j")
    user=$(sed -n 's/.*"username": *"\([^"]*\)".*/\1/p' <<<"$j")
    pid=$(sed -n 's/.*"pid": *\([0-9]*\).*/\1/p' <<<"$j")
    t=$(sed -n 's/.*"time": *"\([^"]*\)".*/\1/p' <<<"$j")
    ts=$(date -d "$t" +%s 2>/dev/null || echo 0)
    alive=0
    [ "$host" = "$me" ] && [ -n "$pid" ] && [ "$(cat "/proc/$pid/comm" 2>/dev/null)" = restic ] && alive=1
    if [ "$host" = "$me" ] && [ "$alive" = 0 ] && [ "$user" = "$VUSER" ] && [ $((now - ts)) -gt 1800 ] \
       && [[ "$j" == *'"exclusive": false'* || "$j" == *'"exclusive":false'* ]]; then
      echo "mine $id"
    elif [ $((now - ts)) -gt 1800 ] || { [ "$host" = "$me" ] && [ "$alive" = 0 ]; }; then
      echo "stale $id"
    elif [[ "$j" == *'"exclusive": true'* || "$j" == *'"exclusive":true'* ]]; then
      echo "excl $id"
    else
      echo "live $id"
    fi
  done
}

# Before 0.46 the dump check below read restic through head: restic died of SIGPIPE and its lock
# stayed in the repository, and a client's own prune (without unlock) failed on it every week.
# Those locks are removed here, and only those: "restic unlock" removes every stale lock, so it
# runs only when each stale lock is ours. Live locks it never touches. Echoes how many went.
verify_locks_clear() {
  local l before after
  l=$(verify_locks) || { echo 0; return 0; }
  before=$(grep -c '^mine ' <<<"$l" || true)
  if [ "$before" -eq 0 ] || grep -q '^stale ' <<<"$l"; then echo 0; return 0; fi
  verify_restic unlock >/dev/null 2>&1 || { echo 0; return 0; }
  after=$(verify_locks | grep -c '^mine ' || true)
  echo $((before - ${after:-0} > 0 ? before - ${after:-0} : 0))
}

cmd_verify() {
  local now t0 err="" errf tmpf snapj snapid stime sts lock="--no-lock" mode incs excs dirs=() d f live got rc
  local ok=0 skipped=0 bad="" checked=0 dumps="" e dir newest head kind cleared=0 w
  now=$(date +%s); t0=$now
  if ! verify_ctx; then
    printf '{"v":1,"ts":%s,"skip":"no restic backup with an env file"}\n' "$now"; return 0
  fi
  errf=$(mktemp); tmpf=$(mktemp)
  cleared=$(verify_locks_clear)
  # Every read here is --no-lock: a lock is a file written into the repository, and a restic killed
  # mid-read (head below, the timeout around the check) leaves it there. Without a lock nothing
  # stops the server's prune from repacking under the check, so an exclusive lock is waited out
  # first, as --retry-lock did (it means nothing next to --no-lock).
  for w in $(seq 40); do
    grep -q '^excl ' <<<"$(verify_locks 2>/dev/null)" || break
    [ "$w" -lt 40 ] && sleep 30 || err="the repository is locked exclusively (prune or check) for 20 minutes"
  done
  # shellcheck disable=SC2086
  [ -n "$err" ] || snapj=$(verify_restic snapshots --json --latest 1 --host "$(hostname)" $lock 2>"$errf") || err="snapshots: $(tail -c 300 "$errf")"
  # (|| true: under pipefail a grep without a match would stop the whole helper)
  snapid=$(printf '%s' "$snapj" | grep -o '"id":"[0-9a-f]\{64\}"' | head -1 | cut -d'"' -f4 || true)
  stime=$(printf '%s' "$snapj" | grep -o '"time":"[^"]*"' | head -1 | cut -d'"' -f4 || true)
  sts=$(date -d "$stime" +%s 2>/dev/null || echo 0)
  [ -z "$err" ] && [ -z "$snapid" ] && err="no snapshots of this host in the repository"
  if [ -z "$err" ]; then
    mode=""; incs=""; excs=""
    if [ -n "$VSCRIPT" ]; then
      mode=$(sed -n 's/^INCLUDE_MODE="\(.*\)"$/\1/p' "$VSCRIPT" | head -1)
      incs=$(sed -n 's/^INCLUDES_STR="\(.*\)"$/\1/p' "$VSCRIPT" | head -1)
      excs=$(sed -n 's/^EXCLUDES_STR="\(.*\)"$/\1/p' "$VSCRIPT" | head -1)
    fi
    if [ "$mode" = include ]; then
      for d in $incs; do d=${d//\"/}; [ -e "$d" ] && dirs+=("$d"); done
    else
      for d in /etc /root /home /opt /srv /app /var/www /usr/local/etc; do [ -d "$d" ] && dirs+=("$d"); done
    fi
    # unchanged since the snapshot (5 minutes before it started) and not under an exclude
    while IFS= read -r f; do
      [ "$checked" -lt "$VERIFY_FILES" ] || break
      case " $excs " in *" --exclude=$f "*) continue ;; esac
      for d in $excs; do d=${d#--exclude=}; case "$f" in "$d"/*) continue 2 ;; esac; done
      live=$(sha256sum < "$f" 2>/dev/null | cut -c1-64) || continue
      [ -n "$live" ] || continue
      # shellcheck disable=SC2086
      rc=0; verify_restic dump $lock "$snapid" "$f" > "$tmpf" 2>"$errf" || rc=$?
      got=$(sha256sum < "$tmpf" | cut -c1-64)
      if [ "$rc" -ne 0 ]; then
        # not in the snapshot: an exclude pattern or a cache directory - not a fault
        if grep -qiE 'not found|no such|cannot find|path .* not' "$errf"; then skipped=$((skipped + 1)); continue; fi
        err="dump: $(tail -c 300 "$errf")"; break
      fi
      checked=$((checked + 1))
      if [ "$got" = "$live" ]; then ok=$((ok + 1))
      else bad="${bad:+$bad,}\"$(verify_json_str "$f")\""; fi
    done < <(find "${dirs[@]}" -xdev -type f -size +0 -size "-$VERIFY_MAX_SIZE" ! -newermt "@$((sts - 300))" \
               2>/dev/null | grep -v -E '/(\.cache|cache|tmp|\.git)/' | head -n 20000 | shuf -n 300 2>/dev/null)
  fi
  # the newest dump of every engine, read back from the snapshot: the first megabytes must
  # decompress into a dump of that engine
  if [ -z "$err" ]; then
    for f in "$DUMPS_D"/*.sh; do
      [ -f "$f" ] || continue
      e=$(basename "$f" .sh); dir="$DUMP_DIR_BASE/$e"
      newest=$(find "$dir" -maxdepth 1 -type f -name '*.gz' ! -newermt "@$sts" -printf '%T@ %p\n' 2>/dev/null \
               | sort -rn | head -1 | cut -d' ' -f2- || true)
      [ -n "$newest" ] || continue
      # head cuts restic off after 8 MB (SIGPIPE): a dump is gigabytes, and the signature is in the
      # first kilobytes. Harmless with --no-lock: a restic that holds no lock leaves nothing behind
      # shellcheck disable=SC2086
      head=$(verify_restic dump $lock "$snapid" "$newest" 2>/dev/null | head -c 8388608 | gzip -dc 2>/dev/null | head -c 4096 | tr -d '\000' || true)
      kind=bad
      case "$head" in
        *"PostgreSQL database"*|*"MySQL dump"*|*"MariaDB dump"*|*"CREATE TABLE"*|*"CREATE DATABASE"*|*"SET "*) kind=ok ;;
        "") kind=bad ;;
        *) kind=data ;;  # redis, rabbitmq, k8s: no text signature, but it decompresses
      esac
      dumps="${dumps:+$dumps,}{\"engine\":\"$(verify_json_str "$e")\",\"file\":\"$(verify_json_str "$newest")\",\"ok\":$([ "$kind" = bad ] && echo false || echo true)}"
    done
  fi
  rm -f "$errf" "$tmpf"
  printf '{"v":1,"ts":%s,"secs":%s,"snap":"%s","snap_ts":%s,"files":{"ok":%s,"skipped":%s,"bad":[%s]},"dumps":[%s],"locks_cleared":%s,"err":"%s"}\n' \
    "$now" "$(( $(date +%s) - t0 ))" "${snapid:0:8}" "$sts" "$ok" "$skipped" "$bad" "$dumps" "${cleared:-0}" \
    "$(verify_json_str "$err")"
}

# Once a week after a successful backup, in the background: the per-minute refresh must not wait
verify_maybe() {
  local age=$VERIFY_EVERY timer svc res last
  verify_ctx || return 0
  [ "$VUSER" = root ] || command -v runuser >/dev/null 2>&1 || return 0
  # a check by a helper before 0.46 (no locks_cleared) may have left its lock: the next one goes now
  [ -f "$VERIFY_JSON" ] && grep -q '"locks_cleared":' "$VERIFY_JSON" \
    && age=$(( $(date +%s) - $(stat -c %Y "$VERIFY_JSON" 2>/dev/null || echo 0) ))
  [ "$age" -ge "$VERIFY_EVERY" ] || return 0
  # a check that keeps dying (timeout, no runuser) is retried every 6 hours, not every minute
  [ -f "$VERIFY_JSON.try" ] && [ $(( $(date +%s) - $(stat -c %Y "$VERIFY_JSON.try" 2>/dev/null || echo 0) )) -lt 21600 ] && return 0
  timer="$(find_timer)" || true
  [ -n "$timer" ] || return 0
  svc="${timer%.timer}.service"
  [ "$(systemctl show -p ActiveState --value "$svc" 2>/dev/null)" = activating ] && return 0
  res=$(systemctl show -p Result --value "$svc" 2>/dev/null)
  last=$(systemctl show -p ExecMainExitTimestampMonotonic --value "$svc" 2>/dev/null)
  [ "$res" = success ] && [ "${last:-0}" != 0 ] || return 0
  install -d -m 0755 "$CUSTOM_DIR"
  (
    flock -n 9 || exit 0
    touch "$VERIFY_JSON.try"
    if nice -n 10 timeout 1800 "$0" verify > "$VERIFY_JSON.tmp" 2>/dev/null && [ -s "$VERIFY_JSON.tmp" ]; then
      mv -f "$VERIFY_JSON.tmp" "$VERIFY_JSON"; chmod 0644 "$VERIFY_JSON"
      # could not reach the repository (a lock, the network): try again in 6 hours, not in a week
      grep -q '"err":"[^"]' "$VERIFY_JSON" && touch -d "@$(( $(date +%s) - VERIFY_EVERY + 21600 ))" "$VERIFY_JSON"
    else
      rm -f "$VERIFY_JSON.tmp"
    fi
  ) 9>/run/kervax-backup-verify.lock > /dev/null 2>&1 &
}

