# ---- provisioning a backup from scratch (restic plus env, script, service and timer) ----
ensure_restic() {
  local tmp
  [ -x "$RESTIC_BIN" ] && return 0
  install -d -o root -g root -m 0755 "$RESTIC_BIN_DIR"
  # restic is already in the system - a copy is placed into our directory (as the ansible role does)
  if command -v restic >/dev/null 2>&1; then
    install -o root -g root -m 0755 "$(command -v restic)" "$RESTIC_BIN"; return 0
  fi
  # RESTIC_TARGET_VER from a private mktemp directory, checked against the baked sha256. 0.42 and
  # older downloaded into fixed names in /tmp, and the sum was optional and came from the same host
  tmp="$(restic_fetch)" || return 2
  install -o root -g root -m 0755 "$tmp/restic" "$RESTIC_BIN"
  rm -rf "$tmp"
}

# apt without questions and without needrestart: from a terminal its apt hook (debconf window
# "Pending kernel upgrade") waited for Enter until the timeout, and it would also restart services
# left over from earlier upgrades - not our business
apt_q() {
  DEBIAN_FRONTEND=noninteractive NEEDRESTART_SUSPEND=1 NEEDRESTART_MODE=l timeout -k 10 "${APT_TIMEOUT:-120}" \
    apt-get -q -y -o DPkg::Lock::Timeout=60 -o Dpkg::Options::=--force-confdef \
    -o Dpkg::Options::=--force-confold "$@" </dev/null >/dev/null 2>&1
}

# restic_fetch downloads RESTIC_TARGET_VER into a fresh mktemp -d, checks the .bz2 against the sha256
# BAKED into the helper (not only against github's SHA256SUMS) and prints the directory; the binary
# is <dir>/restic and has been run once
restic_fetch() {
  local arch want base f tmp got
  case "$(uname -m)" in
    x86_64) arch=amd64; want="$RESTIC_SHA_amd64";;
    aarch64|arm64) arch=arm64; want="$RESTIC_SHA_arm64";;
    *) echo "unknown architecture: $(uname -m)" >&2; return 2;;
  esac
  command -v bunzip2 >/dev/null 2>&1 || { apt_q update || true; apt_q install bzip2 || true; }
  base="https://github.com/restic/restic/releases/download/v$RESTIC_TARGET_VER"
  f="restic_${RESTIC_TARGET_VER}_linux_${arch}.bz2"
  tmp="$(mktemp -d /tmp/kv-restic.XXXXXX)" || return 2
  curl -fsSL --connect-timeout 20 "$base/$f" -o "$tmp/$f" || { rm -rf "$tmp"; echo "could not download restic $RESTIC_TARGET_VER" >&2; return 2; }
  got="$(sha256sum "$tmp/$f" | awk '{print $1}')"
  if [ "$got" != "$want" ]; then
    rm -rf "$tmp"; echo "the sha256 did not match (expected $want, got $got) - restic was not installed" >&2; return 2
  fi
  bunzip2 -c "$tmp/$f" > "$tmp/restic" || { rm -rf "$tmp"; echo "bunzip2 fail" >&2; return 2; }
  chmod 0755 "$tmp/restic"
  "$tmp/restic" version >/dev/null 2>&1 || { rm -rf "$tmp"; echo "the downloaded restic does not run" >&2; return 2; }
  printf '%s' "$tmp"
}

# The target restic version for the whole fleet plus its sha256 (verification is MANDATORY).
# Older nodes (0.13/0.14/0.15) are updated to it. Repository formats are backward compatible -
# 0.19 reads and writes repositories created by older versions, so the update is safe.
RESTIC_TARGET_VER="0.19.1"
RESTIC_SHA_amd64="f415415624dcc452f2a02b8c33641791a8c6d6d3b65bbb3543fcf9a25151585c"
RESTIC_SHA_arm64="a5f64aaab53d51e311fa3829124c5b703f2d14cf187d8640b6be3b2b49376465"

# cmd_restic_update updates the restic binary (or binaries) to RESTIC_TARGET_VER. It updates
# both the panel's own ($RESTIC_BIN) and the system one (from PATH) if that is actually in use.
# It downloads from github, VERIFIES the sha256 against the baked-in value (we do not rely on
# SHA256SUMS from the same host alone) and replaces atomically. The backup configuration is not
# touched - only the binary.
cmd_restic_update() {
  # which binaries to update: the panel one plus the system one (they may be the same - dedup below)
  local targets=() b
  [ -x "$RESTIC_BIN" ] && targets+=("$RESTIC_BIN")
  b="$(command -v restic 2>/dev/null || true)"; [ -n "$b" ] && targets+=("$b")
  if [ "${#targets[@]}" -eq 0 ]; then
    echo "no restic found on the node (neither $RESTIC_BIN nor in PATH)" >&2; return 2
  fi
  # already at the target? checked on the first binary so nothing is downloaded in vain
  local cur; cur="$("${targets[0]}" version 2>/dev/null | grep -oE 'restic [0-9.]+' | awk '{print $2}')"
  if [ "$cur" = "$RESTIC_TARGET_VER" ]; then
    echo "restic is already $RESTIC_TARGET_VER - no update needed"; return 0
  fi
  local tmp newbin
  tmp="$(restic_fetch)" || { echo "the update was cancelled" >&2; return 2; }
  newbin="$tmp/restic"
  # atomic replacement of each unique binary: a mktemp copy next to it plus mv (same filesystem)
  local done="" out="" nb
  for b in "${targets[@]}"; do
    case " $done " in *" $b "*) continue;; esac   # dedup (the panel binary may be the system one)
    done="$done $b"
    if nb="$(mktemp "$(dirname "$b")/.restic-new.XXXXXX")" && cp -f "$newbin" "$nb" \
       && chown root:root "$nb" && chmod 0755 "$nb" && mv -fT "$nb" "$b"; then
      out="$out $b"
    else
      [ -n "$nb" ] && rm -f "$nb"; echo "could not replace $b" >&2
    fi
  done
  rm -rf "$tmp"
  echo "restic updated to $RESTIC_TARGET_VER (was ${cur:-?}):$out"
}

write_runner() {
  local mode="$1"; shift
  local paths=("$@") p exc="" inc=""
  # ONLY the list of the active mode is filled in: both used to be written, and get-config
  # handed the panel paths in includes and excludes at once (it did not affect the backup - the
  # runner picks the right one - but the UI showed the wrong list and could save it on a mode
  # change)
  for p in "${paths[@]}"; do
    if [ "$mode" = include ]; then
      inc="${inc:+$inc }\"$p\""
    else
      exc="${exc:+$exc }--exclude=$p"
    fi
  done
  local restic="$RESTIC_BIN"; [ -f "$PROV_CACERT" ] && restic="$RESTIC_BIN --cacert $PROV_CACERT"
  {
    printf '#!/usr/bin/env bash\nset -euo pipefail\n'
    printf 'RESTIC=%q\n' "$restic"
    printf 'ENV_FILE=%q\n' "$PROV_ENV"
    printf 'LOCKFILE=%q\n' "$PROV_HOME/rk.lock"
    printf 'METRICS_DIR=%q\n' "$PROV_METRICS_DIR"
    printf 'METRICS_FILE=%q\n' "$PROV_METRICS_DIR/$PROV_METRICS_FILE"
    printf 'HOST=%q\n' "$(hostname)"
    printf 'INCLUDE_MODE="%s"\n' "$mode"
    printf 'EXCLUDES_STR="%s"\n' "$exc"
    printf 'INCLUDES_STR="%s"\n' "$inc"
    cat <<'RUNNER_BODY'
mkdir -p "$(dirname "$LOCKFILE")" "$METRICS_DIR"
prev_val(){ local n="$1" d="$2" v=""; [ -f "$METRICS_FILE" ] && v="$(awk -v m="$n" 'index($0,m"{")==1{print $NF}' "$METRICS_FILE"|tail -n1)"; [ -n "$v" ]&&echo "$v"||echo "$d"; }
write_metrics(){ local s="$1" sk="$2" du="$3" ts tmp; ts="$(date +%s)"; tmp="${METRICS_FILE}.$$.tmp"
  { echo "restic_last_backup_success{host=\"${HOST}\"} ${s}"; echo "restic_last_backup_timestamp{host=\"${HOST}\"} ${ts}"
    echo "restic_last_backup_skipped{host=\"${HOST}\"} ${sk}"; echo "restic_last_backup_duration_seconds{host=\"${HOST}\"} ${du}"; } > "$tmp"; mv -f "$tmp" "$METRICS_FILE"; }
exec 9>"$LOCKFILE"
if ! flock -n 9; then
  ps="$(prev_val restic_last_backup_success 0)"; pt="$(prev_val restic_last_backup_timestamp "$(date +%s)")"; pd="$(prev_val restic_last_backup_duration_seconds 0)"
  tmp="${METRICS_FILE}.$$.tmp"
  { echo "restic_last_backup_success{host=\"${HOST}\"} ${ps}"; echo "restic_last_backup_timestamp{host=\"${HOST}\"} ${pt}"
    echo "restic_last_backup_skipped{host=\"${HOST}\"} 1"; echo "restic_last_backup_duration_seconds{host=\"${HOST}\"} ${pd}"; } > "$tmp"; mv -f "$tmp" "$METRICS_FILE"; exit 0
fi
source "$ENV_FILE"
$RESTIC unlock >/dev/null 2>&1 || true
if [ "$INCLUDE_MODE" = include ]; then
  [ -n "$INCLUDES_STR" ] || { echo "include mode without paths" >&2; exit 2; }
  BACKUP_CMD="$RESTIC backup ${INCLUDES_STR}"
else
  BACKUP_CMD="$RESTIC backup / --exclude-caches${EXCLUDES_STR:+ $EXCLUDES_STR}"
fi
# kervax-retry-lock: 1
# The server cleanup (prune) locks the repository exclusively: wait for it instead of failing
# (restic 0.16+; an older restic does not know the flag and runs as before).
KV_RETRY_LOCK=""
case "$(${BACKUP_CMD%% *} --help 2>/dev/null)" in *--retry-lock*) KV_RETRY_LOCK=" --retry-lock 2h" ;; esac
ts_start=$(date +%s); set +e
RUNNER_BODY
    # the duration covers all the attempts
    net_retry_block
    cat <<'RUNNER_BODY'
set -e; dur=$(( $(date +%s) - ts_start ))
if [ $RC -eq 0 ] || [ $RC -eq 3 ]; then write_metrics 1 0 "$dur"; else write_metrics 0 0 "$dur"; fi
RUNNER_BODY
    vanished_ok_block
    echo 'exit $RC'
  } > "$PROV_SCRIPT"
  chmod 0700 "$PROV_SCRIPT"; chown "$PROV_USER:$PROV_USER" "$PROV_SCRIPT" 2>/dev/null || true
}

cmd_provision() {
  # provision <repo_url> <repopass> <mode> <schedule> <delay> <restic_ver> <cacert_b64|-> <path...>
  local repo_url="$1" repopass="$2" mode="$3" sched="$4" delay="$5" ver="$6" cacert_b64="$7"; shift 7
  local paths=("$@")
  # both values go into the env file, which systemd and the runner (bash) read: see secret_ok
  repo_url_ok "$repo_url" || { echo "bad repo url: rest:http(s)://login:password@host:port/name is expected, letters, digits and . _ - only" >&2; return 2; }
  [ -n "$repopass" ] || { echo "no repopass" >&2; return 2; }
  secret_ok "$repopass" || { echo "the repository password has characters the env file cannot hold safely (quotes, \$, \\, ;, spaces, ~) or is shorter than 8 - set the backup up by hand" >&2; return 2; }
  repo_host_ok "$(repo_host "$repo_url")" "${KV_REPO_LOCAL:+local}" || return 2
  [ "$mode" = include ] || [ "$mode" = exclude ] || { echo "bad mode" >&2; return 2; }
  [[ "$sched" =~ ^([01][0-9]|2[0-3]):[0-5][0-9]$ ]] || { echo "bad time" >&2; return 2; }
  [ "${#paths[@]}" -gt 0 ] || { echo "no paths" >&2; return 2; }
  local p; for p in "${paths[@]}"; do valid_path "$p" || { echo "bad path: $p" >&2; return 2; }; done
  [[ "$delay" =~ ^[0-9]+[smh]?$ ]] || delay=1h
  # ONLY the helper decides the restic version. It used to be sent by the panel (with the agent
  # substituting its own default), both numbers drifted away from RESTIC_TARGET_VER, and a fresh
  # node got 0.18.1 - after which the panel immediately offered to "update to 0.19.1". The value
  # sent in is ignored deliberately: that way the fix works with older agents too, without
  # updating them.
  ver="$RESTIC_TARGET_VER"
  # 1) the backup user
  id -u "$PROV_USER" >/dev/null 2>&1 || useradd --system --home-dir "$PROV_HOME" --create-home --shell /usr/sbin/nologin "$PROV_USER"
  # 2) restic
  ensure_restic "$ver" || return 2
  # the directory and the binary stay root's: bx231 only runs restic, root runs it too
  backup_perms_maybe
  # 3) cacert (for a self-signed backup server), if supplied
  if [ "$cacert_b64" != "-" ] && [ -n "$cacert_b64" ]; then
    local ca; ca="$(mktemp "$RESTIC_BIN_DIR/.backup-ca.XXXXXX")" || { echo "mktemp failed" >&2; return 2; }
    if printf '%s' "$cacert_b64" | base64 -d > "$ca" 2>/dev/null && grep -q 'BEGIN CERTIFICATE' "$ca"; then
      chmod 0644 "$ca"; mv -fT "$ca" "$PROV_CACERT"
    else
      rm -f "$ca"; echo "bad cacert" >&2; return 2
    fi
  else
    rm -f "$PROV_CACERT" 2>/dev/null || true
  fi
  # 4) the env file (0600 root)
  umask 077
  { printf 'RESTIC_PASSWORD=%s\n' "$repopass"; printf 'RESTIC_REPOSITORY=%s\n' "$repo_url"; } > "$PROV_ENV"
  chown root:root "$PROV_ENV"; chmod 0600 "$PROV_ENV"; umask 022
  # 5) the metrics directory: the backup user writes its own file there (root:bx231 1775, see
  # backup_perms_maybe); 0.42 and older gave bx231 the whole directory
  metrics_dir_prepare 1 || true
  # 6) the backup script
  write_runner "$mode" "${paths[@]}"
  # 7) service + timer
  cat > "/etc/systemd/system/$PROV_SERVICE" <<UNIT
[Unit]
Description=Kervax restic backup
Wants=network-online.target
After=network-online.target
[Service]
Type=oneshot
User=$PROV_USER
EnvironmentFile=$PROV_ENV
ExecStart=$PROV_SCRIPT
AmbientCapabilities=CAP_DAC_READ_SEARCH
Nice=10
IOSchedulingClass=best-effort
IOSchedulingPriority=7
TimeoutStartSec=infinity
[Install]
WantedBy=multi-user.target
UNIT
  cat > "/etc/systemd/system/$PROV_TIMER" <<UNIT
[Unit]
Description=Kervax restic backup timer
[Timer]
OnCalendar=*-*-* ${sched}:00
AccuracySec=1m
RandomizedDelaySec=$delay
Persistent=true
[Install]
WantedBy=timers.target
UNIT
  systemctl daemon-reload
  systemctl enable --now "$PROV_TIMER" >/dev/null 2>&1 || { echo "could not enable the timer" >&2; return 2; }
  refresh_config
  echo "OK provisioned ($mode, $sched)"
}

# cmd_deprovision takes off the client exactly what cmd_provision puts there (the panel's "remove
# the setup" button for a half-finished setup or the traces of an old backup). The repository on
# the backup server stays as it is. Enabled dumps are kept: the refresh moves them to their own
# timer once the backup service is gone. The panel refuses this for a working backup.
cmd_deprovision() {
  local f removed=""
  systemctl disable --now "$PROV_TIMER" >/dev/null 2>&1 || true
  systemctl stop "$PROV_SERVICE" >/dev/null 2>&1 || true
  for f in "/etc/systemd/system/$PROV_TIMER" "/etc/systemd/system/$PROV_SERVICE"; do
    [ -e "$f" ] && { rm -f "$f"; removed="$removed $(basename "$f")"; }
  done
  [ -d "/etc/systemd/system/$PROV_SERVICE.d" ] && { rm -rf "/etc/systemd/system/$PROV_SERVICE.d"; removed="$removed $PROV_SERVICE.d"; }
  systemctl daemon-reload
  systemctl reset-failed "$PROV_SERVICE" >/dev/null 2>&1 || true
  for f in "$PROV_ENV" "$PROV_SCRIPT"; do
    [ -e "$f" ] && { rm -f "$f"; removed="$removed $f"; }
  done
  [ -d "$RESTIC_BIN_DIR" ] && { rm -rf "$RESTIC_BIN_DIR"; removed="$removed $RESTIC_BIN_DIR"; }
  [ -d "$PROV_HOME" ] && { rm -rf "$PROV_HOME"; removed="$removed $PROV_HOME"; }
  # metrics of this layout: ours and rk.prom of the ansible role it replaced. Only files that are
  # really restic backup metrics - other exporters' files in the same directory stay
  for f in "$PROV_METRICS_DIR/$PROV_METRICS_FILE" "$PROV_METRICS_DIR/rk.prom"; do
    [ -f "$f" ] && grep -q '^restic_last_backup_' "$f" 2>/dev/null && { rm -f "$f"; removed="$removed $f"; }
  done
  rm -f "$RUNS_JSON" "$RUNS_JSON.inv"
  refresh_config
  echo "OK the backup setup is removed from the node:${removed:- nothing was there} (the repository on the backup server is kept)"
}

# cmd_adopt migrates an OLD (ansible) backup layout under the panel. It reads the URL and
# password, the excludes/mode and the schedule from the existing systemd units and switches them
# to the panel runner (which writes restic-backup.prom, so the panel sees metrics and can manage
# it). The repository stays the same - NO restic init, we simply keep appending. The password
# never leaves the node (it is read locally). Custom ExecStopPost hooks of the old unit
# (heartbeat, telegram) are not carried over - by the operator's decision alerting is taken over
# by the panel.
cmd_adopt() {
  local ver="${1:-0.19.1}"   # which restic version to raise to during the migration
  # 1) find the backup service
  local svc="" s
  for s in systemd-rest.service restic-backup.service restic.service; do
    systemctl cat "$s" >/dev/null 2>&1 && { svc="$s"; break; }
  done
  [ -n "$svc" ] || { echo "no systemd backup service found to migrate" >&2; return 2; }
  local unit; unit="$(systemctl cat "$svc" 2>/dev/null)"
  # already the panel layout? (runner in /etc/systemd-rest.conf, env in resta.conf) - no-op
  if printf '%s\n' "$unit" | grep -q "ExecStart=$PROV_SCRIPT" && [ -f "$PROV_ENV" ]; then
    echo "already managed by the panel - no migration needed"; return 0
  fi
  # 2) the env file with the old credentials (EnvironmentFile=, possibly prefixed with '-')
  local envf; envf="$(printf '%s\n' "$unit" | sed -nE 's/^EnvironmentFile=-?(.+)$/\1/p' | head -1)"
  [ -n "$envf" ] && [ -f "$envf" ] || { echo "no EnvironmentFile with the old credentials found" >&2; return 2; }
  # 3) extract the URL and password (never written to the log)
  local repo_url repopass
  repo_url="$(sed -nE 's/^(export )?RESTIC_REPOSITORY=(.*)$/\2/p' "$envf" | head -1 | sed -E 's/^["'\'']//; s/["'\'']$//')"
  repopass="$(sed -nE 's/^(export )?RESTIC_PASSWORD=(.*)$/\2/p' "$envf" | head -1 | sed -E 's/^["'\'']//; s/["'\'']$//')"
  case "$repo_url" in rest:*) ;; *) echo "the old RESTIC_REPOSITORY is not a rest: URL - refusing to migrate blindly" >&2; return 2;; esac
  [ -n "$repopass" ] || { echo "RESTIC_PASSWORD is empty in the old env" >&2; return 2; }
  # 0.42 and older cut the quotes off and wrote the rest as is: a password with a space or a $ in it
  # no longer read back the same from the new env. Such a backup stays as it was
  secret_ok "$repopass" || { echo "the old RESTIC_PASSWORD has characters the panel env cannot hold safely (quotes, \$, \\, ;, spaces, ~) - leaving the old backup as it is" >&2; return 2; }
  repo_url_ok "$repo_url" || { echo "the old RESTIC_REPOSITORY is not a plain rest: address - leaving the old backup as it is" >&2; return 2; }
  # 4) mode and paths from ExecStart (or from the wrapper script it points to): the same parser
  # the panel's report uses (continuation lines, sh -c, --exclude-file and --files-from lists)
  local mode="exclude" paths=() e line k v root=0 inc=() exc=() lists=()
  while IFS= read -r line; do
    k="${line%% *}"; v="${line#* }"
    case "$k" in i) [ "$v" = / ] && root=1 || inc+=("${v%/}") ;; e) exc+=("${v%/}") ;; ef|ff) lists+=("$k $v") ;; esac
  done < <(unit_paths "$svc")
  for e in "${lists[@]+"${lists[@]}"}"; do
    while IFS= read -r v; do
      case "${e%% *}" in ff) case "$v" in /*) inc+=("${v%/}") ;; esac ;; *) exc+=("${v%/}") ;; esac
    done < <(list_file "${e#* }")
  done
  if [ "$root" = 0 ] && [ "${#inc[@]}" -gt 0 ]; then
    mode="include"
    for e in "${inc[@]}"; do [ -n "$e" ] && valid_path "$e" && paths+=("$e"); done
    [ "${#exc[@]}" -gt 0 ] && echo "note: the exclusions inside the included paths are not carried over (${#exc[@]})" >&2
  else
    for e in "${exc[@]+"${exc[@]}"}"; do [ -n "$e" ] && valid_path "$e" && paths+=("$e"); done
  fi
  # could not parse -> a safe default: back up / with the usual excludes (no data is lost)
  if [ "${#paths[@]}" -eq 0 ]; then
    echo "could not parse the paths from ExecStart - falling back to the default excludes" >&2
    mode="exclude"; paths=(/proc /sys /run /dev /usr /var/lib/lxcfs /tmp /var/tmp /boot /var/cache /snap /lib/modules /lib/firmware /lost+found /swapfile)
  fi
  # 5) the schedule from the timer
  local sched="23:00" tmr="" t
  for t in "${svc%.service}.timer" systemd-rest.timer restic-backup.timer restic.timer; do
    systemctl cat "$t" >/dev/null 2>&1 && { tmr="$t"; break; }
  done
  if [ -n "$tmr" ]; then
    local oc; oc="$(systemctl cat "$tmr" 2>/dev/null | sed -nE 's/^OnCalendar=.*[ *]([0-9]{1,2}:[0-9]{2}).*$/\1/p' | head -1)"
    [ -n "$oc" ] && sched="$oc"
  fi
  sched="$(printf '%s' "$sched" | awk -F: '{printf "%02d:%02d", $1, $2}')"
  # 6) the panel provisioning with the same credentials, paths and schedule, WITHOUT restic init (delay=0, as before)
  echo "adopt: repository $(printf '%s' "$repo_url" | sed -E 's#//[^@]*@#//***@#'), mode=$mode, paths=${#paths[@]}, time=$sched, restic->$ver"
  # dry-run: show what was parsed and leave the node untouched (a check before the real migration)
  if [ -n "${KV_ADOPT_DRYRUN:-}" ]; then
    printf 'DRY-RUN. env=%s paths:\n' "$envf"; printf '  - %s\n' "${paths[@]}"; return 0
  fi
  # the address was read on the node itself: its server is recorded in backup-allow, not refused
  KV_REPO_LOCAL=1 cmd_provision "$repo_url" "$repopass" "$mode" "$sched" 0 "$ver" - "${paths[@]}" || { echo "provisioning failed" >&2; return 2; }
  echo "OK adopted -> the panel layout ($mode, $sched)"
}

# The answer goes into a 0750 directory the agent cannot write to, through a fresh mktemp name;
# answers nobody picked up are removed after 10 minutes (the agent cannot delete them any more).
res_write() {  # $1 id, $2 ok, $3 output
  local tmp
  tmp="$(mktemp "$RES_DIR/.res.XXXXXX")" || return 1
  printf 'ok=%s\noutput=%s\n' "$2" "$3" > "$tmp" && chmod 0644 "$tmp" && mv -fT "$tmp" "$RES_DIR/$1.res" || rm -f "$tmp"
}
res_cleanup() { find "$RES_DIR" -maxdepth 1 -type f -name '*.res' -mmin +10 -delete 2>/dev/null || true; }

cmd_process_spool() {
  local req id action mode schedule paths out ok k v line repo_url repopass delay ver cacert_b64 engine container port
  local dump_dir dump_keep dump_minfree
  res_cleanup
  for req in "$REQ_DIR"/*.req; do
    [ -e "$req" ] || [ -L "$req" ] || continue
    id="$(basename "$req" .req)"
    # the agent names requests <command id>-<nanoseconds>; a symlink or anything else is not a request
    if [ -L "$req" ] || [ ! -f "$req" ] || [[ ! "$id" =~ ^[0-9A-Za-z_-]{1,64}$ ]]; then rm -f "$req"; continue; fi
    action=""; mode="exclude"; schedule=""; paths=(); repo_url=""; repopass=""; delay="1h"; ver="$RESTIC_TARGET_VER"; cacert_b64="-"; engine=""; container=""; port=""
    dump_dir=""; dump_keep=""; dump_minfree=""
    # IMPORTANT: not `IFS='=' read -r k v` - that trims a trailing '=' (base64 padding of cacert).
    # The line is read whole and split on the first '=' with parameter expansion.
    while IFS= read -r line; do
      k="${line%%=*}"; v="${line#*=}"
      case "$k" in
        action) action="$v";; mode) mode="$v";; schedule) schedule="$v";; path) paths+=("$v");;
        repo_url) repo_url="$v";; repopass) repopass="$v";; delay) delay="$v";;
        restic_version) ver="$v";; cacert_b64) cacert_b64="$v";;
        engine) engine="$v";; container) container="$v";; port) port="$v";;
        dump_dir) dump_dir="$v";; dump_keep) dump_keep="$v";; dump_minfree) dump_minfree="$v";;
      esac
    done < <(head -c 65536 "$req")
    rm -f "$req"  # secrets (repopass) do not linger on disk
    out=""; ok=false
    case "$action" in
      set_schedule) if out="$(cmd_set_schedule "$schedule" 2>&1)"; then ok=true; fi ;;
      set_paths)    if out="$(cmd_set_paths "$mode" "${paths[@]}" 2>&1)"; then ok=true; fi ;;
      run_now)      if out="$(cmd_run_now 2>&1)"; then ok=true; fi ;;
      restic_update) if out="$(cmd_restic_update 2>&1)"; then ok=true; fi ;;
      provision)    if out="$(cmd_provision "$repo_url" "$repopass" "$mode" "$schedule" "$delay" "$ver" "$cacert_b64" "${paths[@]}" 2>&1)"; then ok=true; fi ;;
      adopt)        if out="$(cmd_adopt "$ver" 2>&1)"; then ok=true; fi ;;
      get_creds)    if out="$(cmd_get_creds 2>&1)"; then ok=true; fi ;;
      to_https)     if out="$(cmd_to_https "$port" "$cacert_b64" 2>&1)"; then ok=true; fi ;;
      # the settings of THIS request only: exported, they used to carry over to the next one
      dump_setup)   if out="$(KV_DUMP_DIR="$dump_dir" KV_DUMP_KEEP="$dump_keep" KV_DUMP_MINFREE="$dump_minfree" cmd_dump_setup "$engine" "$container" 2>&1)"; then ok=true; fi ;;
      dump_remove)  if out="$(cmd_dump_remove "$engine" "$container" 2>&1)"; then ok=true; fi ;;
      deprovision)  if out="$(cmd_deprovision 2>&1)"; then ok=true; fi ;;
      *) out="unknown action" ;;
    esac
    res_write "$id" "$ok" "$(printf '%s' "$out" | tr '\n' ' ')" || true
  done
  refresh_config  # refresh the config file for the panel after the changes
}

# ------- the node's OWN backups, set up without the panel -------
# A node usually arrives with its backups already in place: a cron job with pg_dump, a systemd
# timer, a script writing node_exporter metrics. Redoing them the panel's way is pointless, so
# the panel only WATCHES them. Nothing on the node is changed, and no command line or script
# body leaves it (they hold passwords and tokens): only names, schedules, times, sizes, paths
# and the names of the containers a job refers to.
CUSTOM_DIR=/var/lib/kervax/report.d
CUSTOM_JSON="$CUSTOM_DIR/custom-backups.json"
CUSTOM_EVERY=300  # seconds between scans: cron and timers rarely change
CUSTOM_MAX_JOBS=40
CB_PROM_DIRS=(/var/lib/node_exporter/textfile_collector /var/lib/prometheus/node-exporter)
# a job LOOKS like a backup by its name or command line...
CB_NAME_RE='backup|dump|bkp|snapshot|restic|borg|rsync|rclone|duplicity|kopia|pgbackrest|barman|wal-g|xtrabackup|mariabackup|mongodump'
# ...or by what its script actually runs, whatever the script is called
# "restic ... backup" only as the SUBCOMMAND: a prune script mentions .../backup in its repository path
CB_FILE_TOOL_RE='restic[[:space:]]+([^|;&]*[[:space:]])?backup([[:space:]]|$)|borg[[:space:]]+([^|;&]*[[:space:]])?create([[:space:]]|$)|borgmatic|rsync[[:space:]]|rclone[[:space:]]+([^|;&]*[[:space:]])?(copy|sync)([[:space:]]|$)|duplicity[[:space:]]|kopia[[:space:]]+([^|;&]*[[:space:]])?snapshot'
CB_TOOL_RE='pg_dump|pg_basebackup|pgbackrest|barman|wal-g|mysqldump|mariadb-dump|mariabackup|xtrabackup|mongodump|neo4j-admin|clickhouse-backup|etcdctl.*snapshot|redis-cli.*(--rdb|bgsave)|gitlab-backup[[:space:]]+create|gitlab:backup:create|'"$CB_FILE_TOOL_RE"
# Repository upkeep (prune, forget, rotation, checks) is not a backup: nothing is saved, and on a
# backup server the panel already watches rotation itself. Skipped unless the same job also backs up.
CB_MAINT_RE='prune|forget|cleanup|clean-up|rotate|rotation|purge|verify|check'
# An updater backs up only on the way: gitlab-autoupgrade runs gitlab-backup and rsyncs a snapshot
# for its own rollback before every upgrade step. It runs when there is something to upgrade, so it
# is no backup to watch. The name decides (update/upgrade and no backup word), not the body: the
# body of such a script is full of backup tools.
CB_UPDATER_RE='upgrade|update|unattended'
CB_BACKUP_WORD_RE='backup|dump|bkp|snapshot'
# look-alikes that are not backups, and the panel's own jobs (it already watches those)
# dpkg-db-backup is the distribution's own copy of the package database, not a data backup
CB_SKIP_RE='tcpdump|coredump|dumpe2fs|xfsdump|dumpcap|kervax|systemd-rest|restic-backup\.(timer|service)|^restic\.(timer|service)$|dpkg-db-backup'

cb_clean() { printf '%s' "$1" | tr -d '\000-\037' | cut -c1-200; }
cb_boot_ts() { awk '/^btime/{print $2; exit}' /proc/stat; }

# JSON array of engines. $1 - names, command lines, unit descriptions, metric names and labels:
# any mention counts. $2 - a script body: only a real invocation of a dump tool counts, because
# a file-backup script easily MENTIONS mysql in its excludes without dumping anything.
cb_engines() {
  local s="${1,,}" b="${2,,}" out="" p rest re eng bre
  local -a rules=(
    'pg_dump|pg_basebackup|pgbackrest|barman|wal-g|postgres|psql|pg_backup|pgbackup|pgdump=PostgreSQL=pg_dump|pg_basebackup|pgbackrest|wal-g '
    'mysqldump|mariadb-dump|mariabackup|xtrabackup|mysql|mariadb=MySQL/MariaDB=mysqldump|mariadb-dump|mariabackup|xtrabackup'
    'mongodump|mongo=MongoDB=mongodump'
    'neo4j=Neo4j=neo4j-admin'
    'clickhouse=ClickHouse=clickhouse-backup'
    'redis=Redis=redis-cli.*(bgsave|--rdb)'
    'etcd=etcd=etcdctl.*snapshot'
    'elasticsearch|opensearch=Elasticsearch=_snapshot/'
    'influx=InfluxDB=influxd? backup'
    'sqlite=SQLite=sqlite3.*\.backup'
  )
  for p in "${rules[@]}"; do
    re="${p%%=*}"; rest="${p#*=}"; eng="${rest%%=*}"; bre="${rest#*=}"
    if [[ "$s" =~ $re ]] || { [ -n "$b" ] && [[ "$b" =~ $bre ]]; }; then
      out="${out:+$out,}\"$eng\""
    fi
  done
  printf '[%s]' "$out"
}

