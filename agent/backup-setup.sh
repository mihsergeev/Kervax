#!/usr/bin/env bash
# Kervax: enable restic backup CONTROL from the panel (phase 2).
#
# Running as the unprivileged `kervax` with NoNewPrivileges, the agent cannot use sudo and
# cannot edit the backup configuration (a 0700 script, a root timer). So:
#  * a root cron job writes the current configuration (mode, schedule, paths) into
#    /var/lib/kervax/backup-config.json - the agent reads that file and shows "Control" in the
#    panel, without secrets;
#  * commands go THROUGH A SPOOL: the agent drops a request into /var/lib/kervax/backup-req and
#    a root path unit runs a narrow helper, writing the answer to /var/lib/kervax/backup-res.
# The agent stays fully isolated (no privilege escalation anywhere). Actions come from a strict
# allowlist, names and times are validated. Run as root on the client node.
set -euo pipefail

HELPER_DIR=/lib65/kervax
HELPER="$HELPER_DIR/kervax-backup-helper"
STATE_DIR=/var/lib/kervax
CONF_JSON="$STATE_DIR/backup-config.json"
REQ_DIR="$STATE_DIR/backup-req"
RES_DIR="$STATE_DIR/backup-res"
CRON=/etc/cron.d/kervax-backup
AGENT_USER=kervax

# v2: paths are written and read only for the active mode (include OR exclude) - get-config
# used to hand the panel the same list in both fields
# v3: dump-setup - local database dumps into /backup/<engine> before the file backup
# v4: redis, rabbitmq and k8s engines (backing up a k0s/k3s cluster together with etcd)
# v5: get-config reports the state of enabled dumps (the panel shows status, not a one-off
#     "enabled")
# v6: dump-remove - disable the dump of ONE engine without touching the others
# v7: pg_dumpall takes the role from the container's POSTGRES_USER; mysqldump takes the password
#     from its environment
# v8: dumps are PER CONTAINER (engine@container): two postgres instances do not interfere
# HISTORY (the version is the edit date, YYYYMMDD; see KERVAX_SETUP_VERSION below)
# v9: atomic writes (.partial plus gzip -t): a truncated dump is never left looking complete
# v10: configurable dir/keep/minfree plus overflow protection (skip when space runs short)
# v11: enabling runs a light availability probe instead of a full dump; enabled_ts for the grace
#      period
# v12: pg - each database into its own file plus globals.sql.gz; rotation per run
# v13: restic-update - updating restic to 0.19.1 (sha256 verification, atomic replacement)
# v14: dumps WITHOUT a file backup - their own kervax-dumps.timer (a local copy on the node that
#      can be restored from); the helper is installed EVERYWHERE (ALWAYS): it is the panel's
#      transport for dump control, and without restic it simply did not exist before
# 0.24: the node's own backups (cron, systemd timers, node_exporter metrics) are found and their
#       state is written to /var/lib/kervax/report.d/custom-backups.json - the panel watches
#       them without changing anything
# 0.25: repository upkeep (prune/forget/rotation) is not counted as a backup; DST_DIR-style
#       output directories are recognised
# 0.26: an own cron job no longer reads "cannot see": its starts come from the cron journal; the
#       script's variables and the config it sources are resolved (DEST="${X:-$APP/backups}"); the
#       outcome comes from the status file the script writes or from the snapshot restic saved
#       into its cache - still without changing anything on the node
# 0.27: databases in Kubernetes pods are dumped like those in docker containers, with one button:
#       kubectl exec through the node's own admin access, the pod found anew on every run from its
#       StatefulSet/Deployment/DaemonSet. Replaces the CronJob manifest the panel used to print.
#       report.d/kube-dumps.json tells the panel whether the node can do this
# 0.28: the ClickHouse dump (the schema) is read from the server's metadata files instead of
#       logging in as default - no password is needed, whatever the users are (in a pod, in docker
#       and on the host alike)
# 0.29: enabled dumps always have something to run them: the refresh checks every minute that
#       they hang on the backup service where there is one and on their own timer where there is
#       not, and rebuilds the trigger when the node changed under them
# 0.30: dumps are compressed with gzip --rsyncable: restic then finds the unchanged parts of
#       yesterday's dump instead of storing all of it again (on feed-a a nightly 78 GB
#       pg_dumpall went into the repository whole every time). Scripts generated by an older
#       helper are patched in place by the refresh, once, keeping their format
# 0.31: restic exit 3 ("snapshot saved, some files could not be read") no longer fails the backup
#       unit when every such file simply vanished during the backup (temp files, ClickHouse parts
#       after a merge, lock files): the script already counted it as a success, but exited with 3,
#       and the panel alerted on a failed unit every night on feed-a, stats-a and
#       k8s-b. Any other read error (permissions, a failing disk) still fails the unit.
#       Existing backup scripts, the helper's and the ansible role's, are patched in place once
# 0.32: how much every backup run added to the repository: restic prints its summary at the end
#       ("Added to the repository: 221.756 GiB (96.562 GiB stored)", "processed ... in 46:12"), the
#       refresh picks it up from the journal of each finished run and keeps the last 40 runs in
#       report.d/backup-runs.json. The first refresh fills the history from what the journal has.
#       The panel draws the nightly growth, shows who inflates a backup server and warns when a
#       node suddenly adds much more than usual (feed-a and stats-a added 200-300 GB a
#       night, and nobody saw it until the backup server filled up)
# 0.33: a backup that starts while the server prunes the repository waits for the lock
#       (--retry-lock 2h on restic 0.16+) instead of failing; existing scripts are patched once
# 0.34: a restore check once a week after a successful backup: a few unchanged files are restored
#       from the latest snapshot and compared with the disk by sha256, and the newest dump of every
#       engine is read from the snapshot (its first megabytes decompress into a real dump).
#       Result in report.d/backup-verify.json. A backup that runs every night but cannot be
#       restored is the worst kind of backup, and nothing else shows it
# 0.37: a metrics file of the node's own backup is read whole: every metric named after the file
#       counts (ru_copy.prom -> ru_copy_*), not only the ones that say backup/dump/snapshot, and the
#       last success is taken from *_last_success*/*_last_backup* first, then *_last_run*/*finish*,
#       then any other timestamp. A cron job or a timer that writes such a file is a backup job even
#       if nothing in its name says so, and the job gets its schedule. Before, a copy job that runs
#       twice a week showed the time of the copied snapshot as its last success and no schedule,
#       and the panel called it stale
# 0.38: a failed dump probe always says why. Most checks sent their error to /dev/null, and the
#       panel showed "the probe failed" with an empty reason. MySQL/MariaDB on the host logs in the
#       way dbstat-setup does: /etc/mysql/debian.cnf, /root/.my.cnf, then root over the socket.
#       MySQL 8 from Ubuntu refuses root without a password, so enabling the dump there always
#       failed (db-a). The probe runs before anything is written: a failed try leaves no dump
#       directory and no drop-in, and a working dump keeps its settings when a change fails
# 0.39: "remove the setup" (deprovision) takes off the client what the panel's "set up backup"
#       put there - units, the env file with the password, the script, the panel's restic and its
#       cache, the metrics - so a half-finished setup can be cleared instead of left behind. The
#       repository on the backup server is not touched. A failed backup run says why: the restic
#       error from the journal of that run goes into report.d/backup-runs.json (fail), and the
#       panel shows it next to "the backup failed" instead of the bare fact
# 0.40: to-https - the backup moves from rest:http to the TLS rest-server of the same backup server
#       (login, host and repository from the node's own env, the port and the certificate from the
#       panel). The repository is read over https first; a failed check changes nothing
# 0.41: an updater that takes a backup only on the way (gitlab-autoupgrade: gitlab-backup and an
#       rsync snapshot for its own rollback before every upgrade step) is not an own backup: it runs
#       when there is something to upgrade, and the panel called it "the timer is off" and
#       "cannot see when it ran". A job whose name says update/upgrade and nothing about a backup
#       is skipped. A wrapper script that runs gitlab-backup create is an own backup now
# 0.42: to-https puts RESTIC_CACERT into the env: 0.40 gave --cacert only to a runner with a RESTIC=
#       line, the ansible runner (restic in BACKUP_CMD) stayed without it, the switch said OK and the
#       night run failed on x509. After the switch restic is run the way the backup service runs it
#       (its User and EnvironmentFile, no --cacert of its own); a failure puts everything back on
#       http. Nodes already switched that way get the line on the next refresh. The reason of a
#       failed run is the Fatal line, not the "retrying after" repeats
# 0.43: the root side keeps its boundary against the agent and against bx231:
#       * the answer directory is 0750: the agent only reads answers, root writes them through
#         mktemp and removes them after 10 minutes (a symlink planted there by the agent used to
#         turn the write and the chmod 0644 onto any root file); a request that is a symlink or
#         larger than 64 KiB is dropped;
#       * repopass and repo_url are checked before they reach the env file, which systemd and the
#         runner (source, as bash) both read: a value with a quote, $ or ; ran as bx231 there;
#       * provisioning goes only to the backup server the node already uses or to one listed in
#         /etc/kervax/backup-allow (root writes it; the first provisioning records its server):
#         the panel can no longer send the node's disk to a server of its choice;
#       * /usr/local/lib/.restic and the restic in it belong to root (bx231 could swap the binary
#         that root runs too), the metrics directory is root:bx231 1775;
#       * dumps go into <dir>/kervax-dumps/<engine> for a directory other than /backup, system
#         directories are refused, the dump directory itself is never chmod'ed, and dump-remove
#         removes only a directory the helper made; KV_DUMP_* no longer leak into the next
#         request of the same pass;
#       * restic is downloaded into mktemp -d and checked against the baked sha256 only
# 0.45: the old runner - restic straight in the ExecStart of the backup unit (or in a wrapper script
#       of its own), not in the script get-config reads. The panel showed "exclude" with empty lists
#       there and offered to edit paths that never applied. The unit is parsed (continuation lines,
#       sh -c, --exclude, --exclude-file, --files-from) into report.d/backup-unit.json, only paths
#       and file names. set-paths refuses such a runner (adopt first), a dump warns when its
#       directory is outside the unit's paths, and adopt takes the paths from the same parser
# 0.47: a network failure on the way to the backup server (a stalled or dropped connection, exit 1
#       with timeout / connection reset / 502-504 and the like in the output) is retried in the same
#       run: up to 3 attempts 5 minutes apart, the metrics once after the last one. Other exit codes
#       end at once. The panel runner has the loop, older scripts get it on the next refresh
KERVAX_SETUP_VERSION=0.47  # MAJOR.MINOR; compared component-wise (0.13 > 0.2!)
KERVAX_SETUP_ALWAYS=1  # safe on any node: installs only its own helper and spool and does not
                       # touch the backup configuration until the panel sends a command
install -d -m 0755 "$HELPER_DIR" "$STATE_DIR" /var/lib/kervax/versions
echo "$KERVAX_SETUP_VERSION" > /var/lib/kervax/versions/backup-setup.ver
chmod 0644 /var/lib/kervax/versions/backup-setup.ver  # explicit: the agent (kervax) must read it
# the file and spool scheme needs no sudo - drop the old sudoers rule (if any)
rm -f /etc/sudoers.d/kervax-backup 2>/dev/null || true
# spool: the agent (kervax) drops requests (needs -wx) and reads answers (needs r-x)
install -d -o root -g "$AGENT_USER" -m 0730 "$REQ_DIR"
# 0750: the agent only reads answers. With write access it could plant a symlink under the name
# root writes the answer to and turn that write (and the chmod after it) onto any file. Root
# removes old answers itself (res_cleanup); the agent's attempt to delete one simply fails.
install -d -o root -g "$AGENT_USER" -m 0750 "$RES_DIR"
# under ProtectSystem=strict the agent may write only to its own bin directory, so the spool is
# allowed explicitly; otherwise /var/lib/kervax is read-only and the spool does not work.
# A drop-in plus an agent restart.
if systemctl cat kervax-agent >/dev/null 2>&1; then
  install -d -m 0755 /etc/systemd/system/kervax-agent.service.d
  cat > /etc/systemd/system/kervax-agent.service.d/kervax-spool.conf <<'DROPIN'
[Service]
ReadWritePaths=/var/lib/kervax
DROPIN
  systemctl daemon-reload 2>/dev/null || true
  systemctl try-restart kervax-agent 2>/dev/null || true
fi

# Written next to the old one and swapped in with mv: bash reads a running script as it goes,
# and rewriting it in place (cat >) made a run that was in progress continue from the same
# byte offset in the new text - a syntax error in the middle of a line and a failed unit.
cat > "$HELPER.new" <<'HELPER_EOF'
#!/usr/bin/env bash
# Kervax backup helper (root) - narrow operations on the restic backup. get-config (read),
# set-paths/set-schedule/run-now (write), process-spool (execute requests from the spool).
set -euo pipefail
# cron runs this with PATH=/usr/bin:/bin: runuser (in /usr/sbin) was not found and the weekly
# restore check never started from cron, only while the installer ran
export PATH="/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin${PATH:+:$PATH}"

HELPER_VER=1  # backup-helper version; the panel flags nodes with an old helper (reinstall it)
REQ_DIR=/var/lib/kervax/backup-req
RES_DIR=/var/lib/kervax/backup-res
CONF_JSON=/var/lib/kervax/backup-config.json
SCRIPT_CANDS=("/etc/systemd-rest.conf")
TIMER_CANDS=("systemd-rest.timer" "restic-backup.timer" "restic.timer")
# provisioning (creating a backup from scratch) - the target artefacts are EXACTLY those the agent detects
RESTIC_BIN_DIR=/usr/local/lib/.restic
RESTIC_BIN="$RESTIC_BIN_DIR/restic"
PROV_ENV=/etc/systemd-resta.conf
PROV_SCRIPT=/etc/systemd-rest.conf
PROV_SERVICE=systemd-rest.service
PROV_TIMER=systemd-rest.timer
PROV_USER=bx231
PROV_HOME=/var/cache/bx231
PROV_METRICS_DIR=/var/lib/node_exporter/textfile_collector
PROV_METRICS_FILE=restic-backup.prom
PROV_CACERT="$RESTIC_BIN_DIR/backup-ca.pem"

find_script() { for f in "${SCRIPT_CANDS[@]}"; do [ -f "$f" ] && { echo "$f"; return; }; done; }
find_timer()  { for t in "${TIMER_CANDS[@]}"; do
  [ -e "/etc/systemd/system/$t" ] && { echo "$t"; return; }
  systemctl cat "$t" >/dev/null 2>&1 && { echo "$t"; return; }
done; }
valid_path() { case "$1" in
  /*[!A-Za-z0-9._/+-]*) return 1 ;; *..*) return 1 ;; /*) return 0 ;; *) return 1 ;;
esac; }
json_escape() { printf '%s' "$1" | sed 's/\\/\\\\/g; s/"/\\"/g'; }

# The env file is read twice: by systemd (EnvironmentFile=) and by the runner (source, as bash).
# No quoting means the same to both, so a value goes in only when it holds nothing either of
# them would interpret: no quotes, $, `, \, ;, spaces or ~. The panel generates letters and
# digits; the wider set covers passwords of older layouts.
secret_ok() { [[ "$1" =~ ^[A-Za-z0-9+/=_.,:@%-]{8,256}$ ]]; }
REPO_URL_RE='^rest:https?://([A-Za-z0-9._-]+:[A-Za-z0-9._%+=-]+@)?([A-Za-z0-9.-]+|\[[0-9A-Fa-f:.]+\])(:[0-9]{1,5})?(/[A-Za-z0-9._-]+)*/?$'
repo_url_ok() { [ "${#1}" -le 512 ] && [[ "$1" =~ $REPO_URL_RE ]]; }
# the host of rest:http(s)://[user:pass@]host[:port]/repo, without brackets for IPv6
repo_host() {
  local r="${1#rest:}" hp
  r="${r#http://}"; r="${r#https://}"; hp="${r%%/*}"; hp="${hp##*@}"
  case "$hp" in \[*) hp="${hp%%]*}"; printf '%s' "${hp#[}" ;; *) printf '%s' "${hp%%:*}" ;; esac
}

# Backup servers this node may send its data to. Root writes the file (by hand or with ansible);
# the first provisioning records its server there, and so does the refresh for a node that
# already backs up. A provisioning to any other server is refused: the panel (or whoever took it
# over) cannot point the node's backup at a server of its own and get the whole disk the next
# night. Moving a node to another backup server is one line here, as root on the node.
BACKUP_ALLOW=/etc/kervax/backup-allow
allow_hosts() { [ -f "$BACKUP_ALLOW" ] && sed -e 's/#.*//' -e 's/[[:space:]]//g' "$BACKUP_ALLOW" | grep -v '^$' || true; }
allow_add() {
  [ -L "$BACKUP_ALLOW" ] && return 1
  [ -d /etc/kervax ] || install -d -m 0755 /etc/kervax
  if [ ! -f "$BACKUP_ALLOW" ]; then
    printf '# backup servers this node may send its backup to (one host or IP per line)\n' > "$BACKUP_ALLOW"
  fi
  allow_hosts | grep -qxF "$1" || printf '%s\n' "$1" >> "$BACKUP_ALLOW"
  chown root:root "$BACKUP_ALLOW"; chmod 0644 "$BACKUP_ALLOW"
}
# $1 the host of the new repository, $2 "local" when the address was read on the node itself (adopt)
repo_host_ok() {
  local h="$1" cur=""
  [ -n "$h" ] || { echo "no host in the repository address" >&2; return 1; }
  if [ -f "$BACKUP_ALLOW" ]; then
    allow_hosts | grep -qxF "$h" && return 0
    [ "${2:-}" = local ] && { allow_add "$h"; return 0; }
    echo "the backup server $h is not in $BACKUP_ALLOW - the node sends its backup only to the servers listed there. To allow it, add the line as root on the node: echo $h >> $BACKUP_ALLOW" >&2
    return 1
  fi
  [ -f "$PROV_ENV" ] && cur="$(sed -n 's/^RESTIC_REPOSITORY=//p' "$PROV_ENV" | head -1)"
  if [ -n "$cur" ] && [ "${2:-}" != local ] && [ "$(repo_host "$cur")" != "$h" ]; then
    echo "the node backs up to $(repo_host "$cur"), not to $h - a backup is moved to another server only by root on the node: echo $h >> $BACKUP_ALLOW" >&2
    return 1
  fi
  allow_add "$h"
}
# a node that already backs up gets its current server recorded
allow_seed_maybe() {
  if [ -f "$BACKUP_ALLOW" ] || [ -L "$BACKUP_ALLOW" ] || [ ! -f "$PROV_ENV" ]; then return 0; fi
  local cur; cur="$(sed -n 's/^RESTIC_REPOSITORY=//p' "$PROV_ENV" | head -1)"
  case "$cur" in rest:*) allow_add "$(repo_host "$cur")" ;; esac
}

# bx231 runs restic and writes its own metrics file, nothing more. 0.42 and older gave it the
# restic directory with the binary in it (root runs that binary too: restic-update, to-https)
# and the whole node_exporter directory (root writes there on a backup server). Now the restic
# directory and the binary belong to root, and the metrics directory is root:bx231 1775: bx231
# still creates and renames its own files there (the runner writes through a temporary file and
# mv), but cannot touch anyone else's.
backup_perms_maybe() {
  local f
  if [ -d "$RESTIC_BIN_DIR" ] && [ ! -L "$RESTIC_BIN_DIR" ]; then
    for f in "$RESTIC_BIN_DIR" "$RESTIC_BIN" "$PROV_CACERT"; do
      [ -e "$f" ] && [ ! -L "$f" ] || continue
      [ "$(stat -c %u "$f")" = 0 ] || chown root:root "$f"
      chmod go-w "$f"
    done
  fi
  metrics_dir_prepare 0
}
# $1 1 - create the directory (provisioning), 0 - only repair one that bx231 owns
metrics_dir_prepare() {
  local d="$PROV_METRICS_DIR" f
  id -u "$PROV_USER" >/dev/null 2>&1 || return 0
  [ -L "$d" ] && return 0
  if [ ! -d "$d" ]; then
    [ "$1" = 1 ] || return 0
    # install -d creates missing parents itself and leaves existing ones as they are
    install -d -o root -g "$PROV_USER" -m 1775 "$d"
    return 0
  fi
  case "$(stat -c '%U %a' "$d")" in
    "$PROV_USER "*) ;;                      # 0.42 and older: bx231 owned it
    "root 1775") return 0 ;;
    root\ *) [ "$1" = 1 ] || return 0 ;;    # bx231 cannot write there yet: provisioning only
    *) return 0 ;;
  esac
  # bx231 must keep replacing its own metrics: a file root owns could not be renamed over in a
  # sticky directory, and the backup run would fail on writing its metrics
  for f in "$d/$PROV_METRICS_FILE" "$d/rk.prom"; do
    [ -f "$f" ] && [ ! -L "$f" ] && [ "$(stat -c %U "$f")" = root ] && chown "$PROV_USER:$PROV_USER" "$f"
  done
  chown root:"$PROV_USER" "$d" && chmod 1775 "$d"
}

# ------- local database dumps: restic picks them up with the ordinary file backup -------
# A file snapshot of a live database may fail to restore, so a proper dump is placed next to it.
# Passwords are NOT needed and NOT stored: containers are entered with `docker exec` as a
# service user, native engines with `sudo -u <user>`, always over a local socket with peer
# authentication. MySQL on the host reads the options file the node already has
# (/etc/mysql/debian.cnf or /root/.my.cnf): only its path goes into the dump script.
DUMP_DIR_BASE=/backup
# paths are written LITERALLY: this is the helper body inside a quoted heredoc, so installer
# variables (HELPER_DIR and friends) are not substituted here and do not exist at runtime
DUMPS_D=/lib65/kervax/dumps.d
RUN_DUMPS=/lib65/kervax/run-dumps.sh
DUMP_KEEP=2  # keep the last 2: restic holds the history, there is no point duplicating it on disk
DUMP_HOUR=3  # the hour of the dumps' own timer (when the node has no file backup)

# The dump directory comes from the panel, and root creates directories under it, rotates the
# dumps and removes them. A system directory is refused outright (/var/lib as the directory made
# root chmod /var/lib 0700 and later rm -rf /var/lib/mysql).
dump_sys_dir() {  # $1 an absolute path without ..
  case "$1/" in
    /|/var/|/home/) return 0 ;;
    /bin/*|/boot/*|/dev/*|/etc/*|/lib*/*|/proc/*|/root/*|/run/*|/sbin/*|/snap/*|/sys/*|/tmp/*|/usr/*) return 0 ;;
    /var/tmp/*|/var/lib/*|/var/log/*|/var/cache/*|/var/spool/*|/var/run/*|/var/lock/*|/var/mail/*) return 0 ;;
  esac
  return 1
}
# Every existing part of the path belongs to root, and nobody else may write to it (a sticky
# directory is fine): otherwise a user swaps a directory of theirs for a symlink, and root
# rotates dumps somewhere else.
dump_path_safe() {
  local p="$1" st m
  while :; do
    if [ -e "$p" ]; then
      st="$(stat -c '%u %a' "$p")" || return 1; m="${st##* }"
      [ "${st%% *}" = 0 ] || return 1
      if (( (8#$m & 8#022) != 0 && (8#$m & 8#1000) == 0 )); then return 1; fi
    fi
    [ "$p" = / ] && return 0
    p="$(dirname "$p")"
  done
}
# Where the dumps of a directory chosen in the panel go. /backup is the helper's own and keeps its
# layout (/backup/<engine>). Any other directory gets a kervax-dumps subdirectory, so nothing that
# was there before is ever chmod'ed, rotated or removed. A slot that already lives in the old
# layout (<dir>/<engine>) stays there, so its dumps do not move.
dump_root_of() {  # $1 directory, $2 engine, $3 container
  local d="$1" old="$1/$2" cur=""
  [ -n "$3" ] && old="$old/$3"
  [ "$d" = "$DUMP_DIR_BASE" ] && { printf '%s' "$d"; return; }
  case "$d" in */kervax-dumps) printf '%s' "$d"; return ;; esac
  local slot="$2"; [ -n "$3" ] && slot="$2@$3"
  [ -f "$DUMPS_D/$slot.meta" ] && cur="$(sed -n 's/^dir=//p' "$DUMPS_D/$slot.meta" | head -1)"
  if [ "$cur" = "$old" ]; then printf '%s' "$d"; else printf '%s' "$d/kervax-dumps"; fi
}

# run-dumps.sh runs every enabled dump. It is attached to the backup service as
# ExecStartPre=- (note the minus): a failed dump must NOT cancel the file backup.
write_run_dumps() {
  install -d -m 0755 "$DUMPS_D"
  cat > "$RUN_DUMPS.new" <<'RD_EOF'
#!/usr/bin/env bash
# Kervax: run the enabled database dumps before the file backup. A failure of one engine is not
# fatal - the others, and the backup itself, must still run.
set -u
for d in /lib65/kervax/dumps.d/*.sh; do
  [ -x "$d" ] || continue
  "$d" || echo "kervax-dump: $(basename "$d") finished with an error" >&2
done
exit 0
RD_EOF
  # swapped in with mv, not rewritten in place: a dump run in progress keeps reading the old file
  chmod 0755 "$RUN_DUMPS.new"; chown root:root "$RUN_DUMPS.new"; mv -f "$RUN_DUMPS.new" "$RUN_DUMPS"
  # WHAT TRIGGERS IT. If a file backup exists, we hook onto it (the dump runs right before
  # restic so it picks up a fresh one). If there is no backup, the dumps are still needed: a
  # local copy on the node itself that can be restored from. In that case we bring up
  # OUR OWN timer. The second case used to be ignored: the drop-in was written for a service
  # that did not exist, the dump never ran, and the panel still showed "enabled".
  if systemctl cat "$PROV_SERVICE" >/dev/null 2>&1; then
    local dir="/etc/systemd/system/$PROV_SERVICE.d"
    install -d -m 0755 "$dir"
    # prefixes: "+" means run WITH FULL PRIVILEGES (the backup service runs unprivileged while
    # the dump scripts are root:0700 - without "+" the loop silently found nothing and exited
    # with 0); "-" means a failed dump does NOT cancel the file backup.
    cat > "$dir/kervax-dumps.conf" <<EOF
[Service]
ExecStartPre=-+$RUN_DUMPS
EOF
    chmod 0644 "$dir/kervax-dumps.conf"
    # our own timer is no longer needed: the dumps ride along with the backup, otherwise they would run twice
    systemctl disable --now kervax-dumps.timer >/dev/null 2>&1 || true
    rm -f /etc/systemd/system/kervax-dumps.timer /etc/systemd/system/kervax-dumps.service
  else
    # a drop-in left from a backup service that no longer exists: if the service came back, the
    # dumps would run twice - from it and from our timer
    rm -f "/etc/systemd/system/$PROV_SERVICE.d/kervax-dumps.conf"
    cat > /etc/systemd/system/kervax-dumps.service <<EOF
[Unit]
Description=Kervax: local database dumps (this node has no file backup)
[Service]
Type=oneshot
ExecStart=$RUN_DUMPS
EOF
    cat > /etc/systemd/system/kervax-dumps.timer <<EOF
[Unit]
Description=Kervax: daily local database dumps
[Timer]
OnCalendar=*-*-* ${DUMP_HOUR}:00
RandomizedDelaySec=15min
Persistent=true
[Install]
WantedBy=timers.target
EOF
    chmod 0644 /etc/systemd/system/kervax-dumps.service /etc/systemd/system/kervax-dumps.timer
    systemctl daemon-reload 2>/dev/null || true
    systemctl enable --now kervax-dumps.timer >/dev/null 2>&1 || true
  fi
  systemctl daemon-reload 2>/dev/null || true
}

# What runs the dumps is chosen once, when a dump is enabled: the file backup service if the node
# has one, our own timer otherwise. When the backup service disappears later, the dumps stay
# attached to a unit that no longer exists and nothing runs them. On demo-node-a the dump of the
# panel's own database stood still from 22.07 to 17.09.2026, and nobody knew. A backup set up
# after the dumps is the mirror case. So the trigger is checked on every refresh and rebuilt when
# it no longer matches the node.
dumps_trigger_maybe() {
  ls "$DUMPS_D"/*.sh >/dev/null 2>&1 || return 0
  local want=timer ok=false
  systemctl cat "$PROV_SERVICE" >/dev/null 2>&1 && want=backup
  if [ "$want" = backup ]; then
    [ -f "/etc/systemd/system/$PROV_SERVICE.d/kervax-dumps.conf" ] \
      && ! systemctl is-enabled kervax-dumps.timer >/dev/null 2>&1 && ok=true
  else
    systemctl is-enabled kervax-dumps.timer >/dev/null 2>&1 && ok=true
  fi
  "$ok" && return 0
  write_run_dumps
  logger -t kervax-backup "enabled dumps had nothing to run them - attached to the $([ "$want" = backup ] && echo "backup service $PROV_SERVICE" || echo "own kervax-dumps.timer")" 2>/dev/null || true
}

# A quick availability probe before enabling, instead of a full trial dump. On a large database
# a full dump takes minutes: the panel timed out and reported an "error" while the dump was
# still running. Here only availability and permissions are checked (schema-only/ping): it
# catches the main silent failures (role, password, access) without pulling data. The real dump
# runs on the backup schedule. k8s is not probed: a cluster snapshot is heavy and there is no
# light equivalent.
# Grafana: its state is the SQLite file grafana.db. We look both on the host and in volumes:
# under kubernetes the database lives in a PVC (local-path puts it straight onto the node's
# disk), so "a process on the host" does not mean "installed from a package".
grafana_db_path() {
  local p
  for p in /var/lib/grafana/grafana.db /var/lib/grafana/data/grafana.db; do
    [ -f "$p" ] && { echo "$p"; return 0; }
  done
  # PVCs and volumes: the depth and the usual roots are limited so as not to scan the whole disk
  p=$(find /data /var/lib/k0s /var/lib/rancher /opt/local-path-provisioner /var/lib/docker/volumes \
        -maxdepth 4 -name grafana.db -type f 2>/dev/null | head -1)
  [ -n "$p" ] && { echo "$p"; return 0; }
  return 1
}

# How to take a CONSISTENT copy of a live SQLite database. A plain cp will not do: the database
# is being written and the file may come out torn. sqlite3 is usually absent from the system (it
# was on the Grafana node), while python3 is almost always there and its sqlite3 module can do
# an online backup.
grafana_dumper() {
  if command -v sqlite3 >/dev/null 2>&1; then echo sqlite3; return 0; fi
  if command -v python3 >/dev/null 2>&1 && python3 -c 'import sqlite3' 2>/dev/null; then echo python3; return 0; fi
  return 1
}

# ------- databases in Kubernetes pods -------
# A database in a pod is dumped the same way as one in a docker container; only the way in is
# `kubectl exec` with the node's own admin access (k0s/k3s/microk8s on a controller, kubeadm's
# admin.conf). The target is the WORKLOAD, never a pod: "k8s.<namespace>.<sts|deploy|ds>.<name>".
# The pod is looked up anew on every run through the workload's selector: pods come back under
# new names (a Deployment's hash changes with every rollout), and a dump pinned to a pod name
# would stop working after the first restart.

# how root on this node reaches the cluster ("" - it does not: a worker, or no Kubernetes here)
kube_ctl() {
  local cfg
  if command -v k0s >/dev/null 2>&1 && [ -e /var/lib/k0s/pki/admin.conf ]; then echo "k0s kubectl"; return 0; fi
  if command -v k3s >/dev/null 2>&1 && [ -e /etc/rancher/k3s/k3s.yaml ]; then echo "k3s kubectl"; return 0; fi
  if command -v microk8s >/dev/null 2>&1; then echo "microk8s kubectl"; return 0; fi
  for cfg in /etc/kubernetes/admin.conf /root/.kube/config; do
    if command -v kubectl >/dev/null 2>&1 && [ -e "$cfg" ]; then echo "kubectl --kubeconfig $cfg"; return 0; fi
  done
  return 1
}

kube_target_ok() {
  [[ "$1" =~ ^k8s\.[a-z0-9]([-a-z0-9]*[a-z0-9])?\.(sts|deploy|ds)\.[a-z0-9]([-a-z0-9.]*[a-z0-9])?$ ]]
}

# the running pod of a workload: "$1" namespace, "$2" sts|deploy|ds, "$3" name. A StatefulSet's
# first replica (-0) is preferred: in primary/replica setups it is usually the primary.
kube_pod() {
  local ns="$1" kind="$2" name="$3" kc sel pods p
  kc="$(kube_ctl)" || { echo "no access to the Kubernetes cluster from this node" >&2; return 1; }
  case "$kind" in sts) kind=statefulset ;; deploy) kind=deployment ;; ds) kind=daemonset ;; esac
  sel="$($kc get "$kind" -n "$ns" "$name" -o jsonpath='{.spec.selector.matchLabels}' 2>/dev/null \
    | sed -E 's/[{}" ]//g; s/:/=/g')"
  [ -n "$sel" ] || { echo "no $kind $name in namespace $ns" >&2; return 1; }
  pods="$($kc get pods -n "$ns" -l "$sel" --field-selector=status.phase=Running \
    -o jsonpath='{range .items[*]}{.metadata.name}{"\n"}{end}' 2>/dev/null)"
  [ -n "$pods" ] || { echo "no running pod of $kind $name in namespace $ns" >&2; return 1; }
  for p in $pods; do [ "$p" = "$name-0" ] && { echo "$p"; return 0; }; done
  printf '%s\n' "$pods" | head -1
}

# the database container of the pod: the first one whose image looks like the engine (a pod
# often carries an exporter or a backup sidecar next to the database)
kube_container() {
  local ns="$1" pod="$2" engine="$3" kc re line
  kc="$(kube_ctl)" || return 1
  case "$engine" in
    pg) re='postgres|postgis|timescale|pgvector|spilo|cloudnative-pg' ;;
    mysql) re='mysql|mariadb|percona' ;;
    ch) re='clickhouse' ;;
    redis) re='redis|valkey|keydb|dragonfly' ;;
    rabbitmq) re='rabbitmq' ;;
    *) re='.' ;;
  esac
  local all
  all="$($kc get pod -n "$ns" "$pod" -o jsonpath='{range .spec.containers[*]}{.name}{"|"}{.image}{"\n"}{end}' 2>/dev/null)"
  line="$(printf '%s\n' "$all" | grep -iE "\|.*($re)" | grep -viE '\|.*(exporter|operator|backup|postgrest|pgbouncer)' | head -1)"
  [ -n "$line" ] || line="$(printf '%s\n' "$all" | head -1)"
  [ -n "$line" ] || return 1
  printf '%s' "${line%%|*}"
}

# the command runner inside the workload's database container: sets KEX for the caller
kube_enter() {  # $1 target k8s.<ns>.<kind>.<name>, $2 engine
  local rest ns kind name pod cont kc
  rest="${1#k8s.}"; ns="${rest%%.*}"; rest="${rest#*.}"; kind="${rest%%.*}"; name="${rest#*.}"
  kc="$(kube_ctl)" || { echo "no access to the Kubernetes cluster from this node" >&2; return 1; }
  pod="$(kube_pod "$ns" "$kind" "$name")" || return 1
  cont="$(kube_container "$ns" "$pod" "$2")" || { echo "no containers in pod $ns/$pod" >&2; return 1; }
  # without -i: nothing is fed to the database, and an idle stdin under systemd is only a risk
  KEX_CMD="$kc exec -n $ns $pod -c $cont --"
}
KEX() { $KEX_CMD "$@"; }

# Whether this node can dump databases from pods - the panel offers the button only then. Written
# for the panel next to the node's other extras, at most every 5 minutes.
KUBE_EXTRA=/var/lib/kervax/report.d/kube-dumps.json
kube_access_maybe() {
  local kc can=false
  if [ -f "$KUBE_EXTRA" ] && [ $(( $(date +%s) - $(stat -c %Y "$KUBE_EXTRA" 2>/dev/null || echo 0) )) -lt 300 ]; then
    return 0
  fi
  kc="$(kube_ctl)" || { rm -f "$KUBE_EXTRA"; return 0; }
  [ "$(timeout 15 $kc auth can-i create pods --subresource=exec -A 2>/dev/null)" = yes ] && can=true
  install -d -m 0755 "$(dirname "$KUBE_EXTRA")"
  printf '{"v":1,"ts":%s,"ctl":"%s","exec":%s}\n' "$(date +%s)" "$(json_escape "${kc%% *}")" "$can" > "$KUBE_EXTRA.tmp" \
    && mv -f "$KUBE_EXTRA.tmp" "$KUBE_EXTRA" && chmod 0644 "$KUBE_EXTRA"
}

# ClickHouse: the dump is the schema - every database and table as a CREATE statement (the data
# is not dumped). The server keeps exactly that on disk: an .sql file per database and per table
# under <path>/metadata, written as ATTACH statements (for an Atomic database metadata/<db> is a
# symlink into store/). Reading the files needs no login, so the dump works whatever the users
# and passwords are. Up to 0.27 the dump logged in as default, and it failed wherever default has
# a password the database's environment does not carry (k8s-c, 15.09.2026).
# Unlike SHOW CREATE, the files are not masked: credentials written into a table engine (MySQL,
# S3, a dictionary source) reach the dump as they are. The dump is root-only 0600, like the files.
# $@ - the runner: KEX (a pod), docker exec <container>, or nothing (ClickHouse on the host). The
# runner needs only sh and cat: names are decoded and statements rewritten here, on the node.
ch_schema() {
  # inside the runner every database and table file goes out behind a header line "<RS>D db" or
  # "<RS>T db table", with the names escaped the way ClickHouse writes them into file names
  "$@" sh -c '
    p=""
    for c in /etc/clickhouse-server/config.xml /etc/clickhouse-server/config.yaml /opt/bitnami/clickhouse/etc/config.xml; do
      [ -f "$c" ] || continue
      v=$(clickhouse extract-from-config --config-file "$c" --key path 2>/dev/null) && [ -n "$v" ] && { p=$v; break; }
    done
    [ -n "$p" ] || p=/var/lib/clickhouse
    cd "$p/metadata" 2>/dev/null || { echo "no ClickHouse metadata directory at ${p%/}/metadata" >&2; exit 3; }
    printf "\036S\n"
    for e in *; do
      case "$e" in
        *.sql) [ -f "$e" ] || continue; db=${e%.sql} ;;
        *) [ -d "$e" ] && [ ! -f "$e.sql" ] || continue; db=$e ;;
      esac
      case "$db" in system|INFORMATION_SCHEMA|information_schema) continue ;; esac
      printf "\n\036D %s\n" "$db"
      [ -f "$db.sql" ] && cat "$db.sql"
      [ -d "$db" ] || continue
      for t in "$db"/*.sql; do
        [ -f "$t" ] || continue
        t=${t#"$db"/}
        printf "\n\036T %s %s\n" "$db" "${t%.sql}"
        cat "$db/$t"
      done
    done' | LC_ALL=C awk '
    # ClickHouse keeps [A-Za-z0-9_] in file names and writes every other byte as %XX
    function unesc(s,   o, i, c, h) {
      o = ""
      for (i = 1; i <= length(s); i++) {
        c = substr(s, i, 1)
        if (c == "%" && i + 2 <= length(s)) {
          h = (index(X, toupper(substr(s, i + 1, 1))) - 1) * 16 + index(X, toupper(substr(s, i + 2, 1))) - 1
          if (h > 0) { o = o sprintf("%c", h); i += 2; continue }
        }
        o = o c
      }
      return o
    }
    function q(s,   o, i, c) {
      o = ""
      for (i = 1; i <= length(s); i++) {
        c = substr(s, i, 1)
        if (c == "\\" || c == "`") o = o "\\"
        o = o c
      }
      return "`" o "`"
    }
    # how long the name after "ATTACH <kind> " is: "_", a bare name or a quoted one
    function namelen(s,   c, i) {
      c = substr(s, 1, 1)
      if (c == "`" || c == "\"") {
        for (i = 2; i <= length(s); i++) {
          if (substr(s, i, 1) == "\\") { i++; continue }
          if (substr(s, i, 1) == c) return i
        }
        return length(s)
      }
      for (i = 1; i <= length(s); i++) {
        c = substr(s, i, 1)
        if (c == " " || c == "\t" || c == "(") return i - 1
      }
      return length(s)
    }
    # Output lines go into an array per group and are printed at the end: databases first, then
    # tables, dictionaries and views (a view needs its tables to exist). Gluing everything into
    # one string would copy it again on every line - quadratic on a schema of thousands of tables.
    function add(ph, line) { O[ph, ++N[ph]] = line }
    # one file: "ATTACH <kind> <name>" on its first line becomes "CREATE <kind> db.table". A
    # dictionary is kept as "CREATE DICTIONARY _" already (checked on 26.7), so both verbs count.
    function flush(   i, j, k, l, pre, rest, ph, title) {
      if (typ == "") return
      while (nl > 0 && L[nl] ~ /^[ \t\r]*$/) nl--
      for (i = 1; i <= nl && L[i] ~ /^[ \t\r]*$/; i++) ;
      title = "-- " dn ((typ == "T") ? "." tn : "")
      if (i > nl) {
        # a database directory without its .sql (an old default): the engine is the default one
        if (typ == "D") { add(0, title); add(0, "CREATE DATABASE IF NOT EXISTS " q(dn) ";"); add(0, "") }
        typ = ""; nl = 0; return
      }
      l = L[i]; ph = -1
      for (k = 1; k <= NK; k++) {
        pre = "ATTACH " K[k] " "
        if (substr(l, 1, length(pre)) != pre) {
          pre = "CREATE " K[k] " "
          if (substr(l, 1, length(pre)) != pre) continue
        }
        rest = substr(l, length(pre) + 1)
        rest = substr(rest, namelen(rest) + 1)
        if (K[k] == "DATABASE") { l = "CREATE DATABASE IF NOT EXISTS " q(dn) rest; ph = 0 }
        else { l = "CREATE " K[k] " " q(dn) "." q(tn) rest; ph = (K[k] == "TABLE") ? 1 : ((K[k] == "DICTIONARY") ? 2 : 3) }
        break
      }
      if (ph < 0) {
        add(3, "-- not an ATTACH or CREATE statement, kept as a comment: " substr(title, 4))
        for (j = i; j <= nl; j++) add(3, "-- " L[j])
      } else {
        add(ph, title)
        if (i == nl) add(ph, l ";")
        else {
          add(ph, l)
          for (j = i + 1; j < nl; j++) add(ph, L[j])
          add(ph, L[nl] ";")
        }
      }
      add((ph < 0) ? 3 : ph, "")
      typ = ""; nl = 0
    }
    BEGIN { H = sprintf("%c", 30); X = "0123456789ABCDEF"; NK = split("MATERIALIZED VIEW|LIVE VIEW|WINDOW VIEW|DICTIONARY|DATABASE|TABLE|VIEW", K, "|") }
    substr($0, 1, 1) == H {
      flush()
      split(substr($0, 2), f, " ")
      # S: the metadata directory was found. Without it the runner has already said what failed
      if (f[1] == "S") { started = 1; next }
      typ = f[1]; dn = unesc(f[2]); tn = (typ == "T") ? unesc(f[3]) : ""; seen++
      # the inner table of a materialized view is created again by the view itself
      if (typ == "T" && substr(tn, 1, 6) == ".inner") typ = ""
      next
    }
    typ != "" { L[++nl] = $0 }
    END {
      flush()
      if (!started) exit 3
      if (!seen) { print "no databases found in the ClickHouse metadata" > "/dev/stderr"; exit 4 }
      print "-- ClickHouse schema, read by kervax from the server metadata files"
      print ""
      for (k = 0; k <= 3; k++) for (j = 1; j <= N[k]; j++) print O[k, j]
    }'
}

# MySQL/MariaDB on the host: which client dumps and how it logs in. A MySQL 8 package from Ubuntu
# gives root a password and no socket login, so a plain mysqldump as root is refused ("Access
# denied for user 'root'@'localhost' (using password: NO)"), while the maintenance user from
# /etc/mysql/debian.cnf gets in. Up to 0.37 the helper tried root only and threw the error away,
# and the panel said "the probe failed" with an empty reason (db-a, October 2026). The order is the
# one dbstat-setup uses: the options files first, then root over the socket (MariaDB packages).
# MY_BIN and MY_DEF are what let the probe in; the generated dump script uses the same.
MY_BIN=""
MY_DEF=""
MY_CNFS=(/etc/mysql/debian.cnf /root/.my.cnf)
my_host_dump_bin() {
  local b order="mysqldump mariadb-dump"
  # MariaDB 11 packages may come without the mysqldump name, and with it the client warns that the
  # name is deprecated
  command -v mariadbd >/dev/null 2>&1 && order="mariadb-dump mysqldump"
  for b in $order; do command -v "$b" >/dev/null 2>&1 && { echo "$b"; return 0; }; done
  return 1
}
my_host_probe() {
  local bin f e errs=""
  bin="$(my_host_dump_bin)" || {
    echo "no mysqldump or mariadb-dump on the host: the MySQL/MariaDB client is not installed" >&2; return 1; }
  for f in "${MY_CNFS[@]}" ""; do
    [ -z "$f" ] || [ -r "$f" ] || continue
    # --defaults-file has to be the first option. --single-transaction: no table locks on a live
    # server, and the same privileges the real dump needs
    if e="$("$bin" ${f:+"--defaults-file=$f"} --no-data --all-databases --single-transaction 2>&1 >/dev/null)"; then
      MY_BIN="$bin"; MY_DEF="$f"; return 0
    fi
    e="$(printf '%s\n' "$e" | sed '/^[[:space:]]*$/d' | tail -n 2 | tr '\n' ' ' | sed 's/ *$//')"
    errs="${errs:+$errs; }${f:-root over the socket} - ${e:-no error text}"
  done
  echo "MySQL did not let the helper in: $errs" >&2
  return 1
}

# Every failed check says why: its error goes to the caller (cmd_dump_setup hands it to the
# panel). Up to 0.37 most branches sent stderr to /dev/null with the output, and the panel showed
# an empty reason.
dump_probe() {
  local engine="$1" container="${2:-}" r
  if kube_target_ok "$container"; then
    kube_enter "$container" "$engine" || return 1
    case "$engine" in
      pg) KEX sh -c 'PGPASSWORD="${POSTGRES_PASSWORD:-${PGPASSWORD:-}}"; export PGPASSWORD; pg_dumpall -U "${POSTGRES_USER:-postgres}" --schema-only' >/dev/null ;;
      mysql) KEX sh -c 'MYSQL_PWD="${MYSQL_ROOT_PASSWORD:-${MARIADB_ROOT_PASSWORD:-}}"; export MYSQL_PWD; if command -v mariadb-dump >/dev/null 2>&1; then mariadb-dump -u root --no-data --all-databases; else mysqldump -u root --no-data --all-databases; fi' >/dev/null ;;
      ch) ch_schema KEX >/dev/null ;;
      redis) [ "$(KEX sh -c 'p="${REDISCLI_AUTH:-${REDIS_PASSWORD:-}}"; [ -n "$p" ] && export REDISCLI_AUTH="$p"; redis-cli ping' 2>&1)" = PONG ] \
               || { echo "redis did not answer PONG (a password it does not have in its environment?)" >&2; return 1; } ;;
      rabbitmq) KEX rabbitmqctl -q list_vhosts >/dev/null ;;
      *) echo "dumps from pods are not supported for $engine" >&2; return 1 ;;
    esac
    return
  fi
  case "$engine" in
    pg)
      if [ -n "$container" ]; then
        local pgu; pgu=$(docker inspect -f '{{range .Config.Env}}{{println .}}{{end}}' "$container" 2>/dev/null | sed -n 's/^POSTGRES_USER=//p' | head -1)
        [ -n "$pgu" ] || pgu=postgres
        # the first try is quiet: an image without the postgres user (bitnami) is not an error
        docker exec -u postgres "$container" pg_dumpall -U "$pgu" --schema-only >/dev/null 2>&1 \
          || docker exec "$container" pg_dumpall -U "$pgu" --schema-only >/dev/null
      else sudo -u postgres pg_dumpall --schema-only >/dev/null; fi ;;
    mysql)
      # mariadb:11 has no mysqldump name, the generated script already prefers mariadb-dump
      if [ -n "$container" ]; then
        docker exec "$container" sh -c 'MYSQL_PWD="${MYSQL_ROOT_PASSWORD:-${MARIADB_ROOT_PASSWORD:-}}"; export MYSQL_PWD; if command -v mariadb-dump >/dev/null 2>&1; then mariadb-dump -u root --no-data --all-databases; else mysqldump -u root --no-data --all-databases; fi' >/dev/null
      else my_host_probe; fi ;;
    ch)
      if [ -n "$container" ]; then ch_schema docker exec "$container" >/dev/null
      else ch_schema >/dev/null; fi ;;
    redis)
      if [ -n "$container" ]; then r="$(docker exec "$container" redis-cli ping 2>&1)"
      else r="$(redis-cli ping 2>&1)"; fi
      [ "$r" = PONG ] || { echo "redis did not answer PONG: $(printf '%s' "$r" | tr '\n' ' ' | cut -c1-200)" >&2; return 1; } ;;
    rabbitmq)
      if [ -n "$container" ]; then docker exec "$container" rabbitmqctl list_vhosts >/dev/null
      else rabbitmqctl list_vhosts >/dev/null; fi ;;
    k8s) return 0 ;;
    neo4j)
      # The dump is taken with the database STOPPED (see the generator), so we probe not the
      # dump itself but the presence of the tool: neo4j-admin in the container image or on the
      # host.
      if [ -n "$container" ]; then
        local img; img=$(docker inspect -f '{{.Config.Image}}' "$container" 2>/dev/null)
        [ -n "$img" ] || { echo "docker does not know the container $container" >&2; return 1; }
        docker run --rm --entrypoint neo4j-admin "$img" --version >/dev/null
      else command -v neo4j-admin >/dev/null 2>&1 || { echo "no neo4j-admin on the host" >&2; return 1; }; fi ;;
    grafana)
      [ -n "$(grafana_db_path)" ] || { echo "grafana.db not found on the host or in volumes" >&2; return 1; }
      grafana_dumper >/dev/null || { echo "neither sqlite3 nor python3 with sqlite3 on the host" >&2; return 1; } ;;
  esac
}

# Compression of the dumps (0.30). gzip --rsyncable restarts its blocks at content-defined points,
# so a table that did not change compresses into the same bytes every night and restic
# deduplicates it; plain gzip shifts everything after the first change. Falls back to plain gzip
# where gzip has no --rsyncable (very old or busybox). The marker line tells the refresh that the
# script is already done.
DUMP_GZ_MARK='# kervax-dump-format: 2 (gzip --rsyncable)'
dump_gz_header() {
  printf '%s\n' "$DUMP_GZ_MARK" 'GZ="gzip -c"; GZF="gzip -f"' \
    'if gzip --rsyncable -c </dev/null >/dev/null 2>&1; then GZ="gzip --rsyncable -c"; GZF="gzip --rsyncable -f"; fi'
}

# restic exit 3 means the snapshot is saved but some files could not be read. When every such file
# just vanished between restic listing and reading it (a temp file, a ClickHouse part merged away,
# a lock file), nothing that still exists was lost, so the unit ends as a success. Any other error
# (permission denied, an I/O error) keeps the 3 and the unit fails as before. The errors are taken
# from the journal of this very run (INVOCATION_ID, set by systemd for the service).
VANISHED_MARK='# kervax-vanished-ok: 1'
vanished_ok_block() {
  printf '%s\n' "$VANISHED_MARK" \
    'if [ "$RC" -eq 3 ] && [ -n "${INVOCATION_ID:-}" ]; then' \
    '  sleep 2  # journald writes asynchronously: the last error line may not be in yet' \
    '  ERRS=$(journalctl -q -o cat _SYSTEMD_INVOCATION_ID="$INVOCATION_ID" 2>/dev/null | grep -a "^error:" || true)' \
    '  if [ -n "$ERRS" ] && ! printf "%s\n" "$ERRS" | grep -a -v -q -i "no such file or directory"; then' \
    '    echo "kervax: restic exit 3 only because $(printf "%s\n" "$ERRS" | wc -l) file(s) vanished during the backup, treated as success"' \
    '    RC=0' \
    '  fi' \
    'fi'
}

# Backup scripts made earlier, by the helper or by the ansible role, get the block once, right
# before their last line "exit $RC". A script without exactly one such line, or already patched, is
# left alone; the result is checked with bash -n before it replaces the original, and the original
# stays next to it as .kervax-pre-vanished.bak.
vanished_ok_maybe() {
  local f; f="$(find_script)" || return 0
  [ -n "$f" ] && [ -f "$f" ] || return 0
  grep -qF "$VANISHED_MARK" "$f" && return 0
  [ "$(grep -c '^exit \$RC$' "$f")" = 1 ] || return 0
  vanished_ok_block > "$f.blk"
  awk -v bf="$f.blk" '/^exit \$RC$/ { while ((getline l < bf) > 0) print l; close(bf) } { print }' "$f" > "$f.tmp"
  rm -f "$f.blk"
  if bash -n "$f.tmp" 2>/dev/null && grep -qF "$VANISHED_MARK" "$f.tmp"; then
    cp -a "$f" "$f.kervax-pre-vanished.bak"
    chmod --reference="$f" "$f.tmp"; chown --reference="$f" "$f.tmp"; mv -f "$f.tmp" "$f"
  else
    rm -f "$f.tmp"
  fi
}

# A backup that starts while the backup server prunes the repository fails: prune holds an
# exclusive lock, and restic does not wait for it unless told to. Backup scripts made earlier,
# by the helper or by the ansible role, get the wait once: a block right before the single
# `eval "$BACKUP_CMD"` line, and that line puts " --retry-lock 2h" right after the "backup" word
# (not at the end: a hand-edited command may end with "--" or a redirection). The flag goes in only
# when the restic there knows it (0.16+). Same safety as above: one such line or nothing, bash -n
# before replacing, the original kept as .kervax-pre-retry.bak.
RETRY_MARK='# kervax-retry-lock: 1'
RETRY_EVAL='eval "${BACKUP_CMD/ backup / backup$KV_RETRY_LOCK }"'
retry_lock_block() {
  printf '%s\n' "$RETRY_MARK" \
    '# The server cleanup (prune) locks the repository exclusively: wait for it instead of failing' \
    '# (restic 0.16+; an older restic does not know the flag and runs as before).' \
    'KV_RETRY_LOCK=""' \
    'case "$(${BACKUP_CMD%% *} --help 2>/dev/null)" in *--retry-lock*) KV_RETRY_LOCK=" --retry-lock 2h" ;; esac'
}
retry_lock_maybe() {
  local f; f="$(find_script)" || return 0
  [ -n "$f" ] && [ -f "$f" ] || return 0
  grep -qF "$RETRY_MARK" "$f" && return 0
  [ "$(grep -cF 'eval "$BACKUP_CMD"' "$f")" = 1 ] || return 0
  retry_lock_block > "$f.blk"
  awk -v bf="$f.blk" -v new="$RETRY_EVAL" '
    BEGIN { old = "eval \"$BACKUP_CMD\"" }
    (i = index($0, old)) && !done {
      while ((getline l < bf) > 0) print l
      close(bf)
      $0 = substr($0, 1, i - 1) new substr($0, i + length(old))
      done = 1
    }
    { print }' "$f" > "$f.tmp"
  rm -f "$f.blk"
  if bash -n "$f.tmp" 2>/dev/null && grep -qF "$RETRY_MARK" "$f.tmp" && grep -qF "$RETRY_EVAL" "$f.tmp"; then
    cp -a "$f" "$f.kervax-pre-retry.bak"
    chmod --reference="$f" "$f.tmp"; chown --reference="$f" "$f.tmp"; mv -f "$f.tmp" "$f"
  else
    rm -f "$f.tmp"
  fi
}

# A connection to the backup server that stalls or drops on the way (request timeout, connection
# timed out) fails the night backup with exit 1, though the server is fine and the next run passes.
# Such a failure is retried in the same run: up to 3 attempts 5 minutes apart, only for exit 1 with
# a network error in the output. Exit 10/11/12 (no repository, lock, password) and everything else
# end at once; no unlock between attempts (the runner did it once before the first one). RC is the
# result of the last attempt, the metrics are written once after the block.
NET_RETRY_MARK='# kervax-net-retry: 1'
net_retry_block() {
  printf '%s\n' "$NET_RETRY_MARK" \
    '# A network failure on the way to the backup server is retried: up to 3 attempts 5 minutes apart' \
    '# (exit 1 with a network error only; a wrong password, a missing repository or a lock end at once).' \
    'BK_TRIES=3' \
    'BK_PAUSE=300' \
    'BK_OUT="$(mktemp 2>/dev/null)" || BK_OUT=/dev/null' \
    'BK_TRY=1' \
    'while :; do' \
    '  echo "restic backup: attempt $BK_TRY of $BK_TRIES"' \
    "  $RETRY_EVAL"' 2>&1 | tee "$BK_OUT"' \
    '  RC=${PIPESTATUS[0]}' \
    '  [ "$RC" -eq 1 ] && [ "$BK_TRY" -lt "$BK_TRIES" ] || break' \
    "  grep -aqiE 'timeout|timed out|connection reset|connection refused|broken pipe|unexpected EOF|no route to host|network is unreachable|TLS handshake|502 Bad Gateway|503 Service Unavailable|504 Gateway' \"\$BK_OUT\" || break" \
    '  echo "restic backup: attempt $BK_TRY failed on the network (exit $RC), next one in $BK_PAUSE s"' \
    '  sleep "$BK_PAUSE"' \
    '  BK_TRY=$((BK_TRY + 1))' \
    'done' \
    '[ "$BK_OUT" = /dev/null ] || rm -f "$BK_OUT"'
}
# Scripts made earlier (the ansible role, an older helper) get the block once, after retry_lock_maybe
# gave them RETRY_EVAL: the single RETRY_EVAL line with "RC=$?" right after it (same line after ";" -
# the helper's runner - or the next line - the ansible role) is replaced by the block; what stood
# before and after it on that line stays on lines of its own. A script that already retries (the
# marker, or a block put in by hand: BK_TRIES / "попытка") is left alone. Same safety as above: bash -n
# before replacing, the original kept as .kervax-pre-netretry.bak.
net_retry_maybe() {
  local f; f="$(find_script)" || return 0
  [ -n "$f" ] && [ -f "$f" ] || return 0
  grep -qF "$NET_RETRY_MARK" "$f" && return 0
  grep -qE 'BK_TRIES=|попытка' "$f" && return 0
  [ "$(grep -cF "$RETRY_EVAL" "$f")" = 1 ] || return 0
  net_retry_block > "$f.blk"
  awk -v bf="$f.blk" -v ev="$RETRY_EVAL" '
    function flush_block(ind,   l) { while ((getline l < bf) > 0) print ind l; close(bf) }
    function trim(s) { sub(/^[ \t;]+/, "", s); sub(/[ \t;]+$/, "", s); return s }
    wait_rc {
      wait_rc = 0
      if ($0 ~ /^[ \t]*RC=\$\?[ \t]*$/) { if (pre != "") print ind pre; flush_block(ind); done = 1; next }
      bad = 1; print held
    }
    (i = index($0, ev)) && !done && !bad {
      ind = $0; sub(/[^ \t].*$/, "", ind)
      pre = trim(substr($0, 1, i - 1)); post = substr($0, i + length(ev))
      if (post ~ /^[ \t]*;[ \t]*RC=\$\?([ \t;]|$)/) {
        sub(/^[ \t]*;[ \t]*RC=\$\?/, "", post); post = trim(post)
        if (pre != "") print ind pre
        flush_block(ind)
        if (post != "") print ind post
        done = 1; next
      }
      if (post ~ /^[ \t]*$/) { held = $0; wait_rc = 1; next }
      bad = 1
    }
    { print }
    END { if (wait_rc) print held; if (!done || bad) exit 1 }' "$f" > "$f.tmp"
  local rc=$?
  rm -f "$f.blk"
  if [ "$rc" = 0 ] && bash -n "$f.tmp" 2>/dev/null && grep -qF "$NET_RETRY_MARK" "$f.tmp" \
     && [ "$(grep -cF "$RETRY_EVAL" "$f.tmp")" = 1 ]; then
    cp -a "$f" "$f.kervax-pre-netretry.bak"
    chmod --reference="$f" "$f.tmp"; chown --reference="$f" "$f.tmp"; mv -f "$f.tmp" "$f"
  else
    rm -f "$f.tmp"
  fi
}

# Scripts generated by an older helper are patched in place, once: the header goes in after
# "set -uo pipefail", "| gzip -c >" becomes "| $GZ >", "gzip -f" becomes "$GZF". Everything else -
# the format, the paths, the rotation - stays as it was generated. The result is checked with
# bash -n before it replaces the original; a script that does not look like ours is left alone.
dumps_rsyncable_maybe() {
  local f
  for f in "$DUMPS_D"/*.sh; do
    [ -f "$f" ] || continue
    grep -qF "$DUMP_GZ_MARK" "$f" && continue
    grep -q '^set -uo pipefail$' "$f" || continue
    {
      sed -n '1,/^set -uo pipefail$/p' "$f"
      dump_gz_header
      sed '1,/^set -uo pipefail$/d' "$f" | sed -e 's/| gzip -c >/| $GZ >/g' -e 's/^gzip -f "\$F"/$GZF "$F"/'
    } > "$f.tmp"
    if bash -n "$f.tmp" 2>/dev/null; then
      chmod 0700 "$f.tmp"; chown root:root "$f.tmp"; mv -f "$f.tmp" "$f"
    else
      rm -f "$f.tmp"
    fi
  done
}

cmd_dump_setup() {
  local engine="$1" container="${2:-}"
  case "$engine" in
    pg|mysql|ch|redis|rabbitmq|k8s|grafana|neo4j) ;;
    *) echo "unknown engine: $engine (supported: pg, mysql, ch, redis, rabbitmq, k8s, grafana, neo4j)" >&2; return 2 ;;
  esac
  case "$container" in ''|*[!A-Za-z0-9._-]*) container="" ;; esac
  # a database in a pod: the "container" is the workload, entered with kubectl exec (see kube_enter)
  local kt="" dcont="$container"
  case "$container" in
    k8s.*)
      kube_target_ok "$container" || { echo "invalid Kubernetes workload: $container" >&2; return 2; }
      case "$engine" in
        pg|mysql|ch|redis|rabbitmq) ;;
        *) echo "dumps from pods are not supported for $engine" >&2; return 2 ;;
      esac
      kube_ctl >/dev/null || { echo "no access to the Kubernetes cluster from this node" >&2; return 2; }
      kt="$container"; dcont="" ;;
  esac
  # Settings come from the env (the agent places them through the spool; from the CLI the
  # defaults apply). They are validated HERE rather than trusted from the panel: dir ends up in
  # rm/mkdir as root, and keep drives the rotation.
  local dir_base="${KV_DUMP_DIR:-$DUMP_DIR_BASE}"
  local keep="${KV_DUMP_KEEP:-$DUMP_KEEP}"
  local minfree="${KV_DUMP_MINFREE:-10}"
  case "$dir_base" in
    /*) : ;; *) echo "the dump directory must be an absolute path: $dir_base" >&2; return 2 ;;
  esac
  case "$dir_base" in
    *..*|*[!A-Za-z0-9._/-]*|*//*) echo "invalid dump directory: $dir_base" >&2; return 2 ;;
    /) echo "the root / cannot be used for dumps" >&2; return 2 ;;
  esac
  dir_base="${dir_base%/}"
  # a directory sent by the panel; the helper's own /backup keeps its layout and is not second-guessed
  if [ "$dir_base" != "$DUMP_DIR_BASE" ]; then
    local dir_real; dir_real="$(realpath -m -- "$dir_base")"
    if dump_sys_dir "$dir_base" || dump_sys_dir "$dir_real"; then
      echo "$dir_base is a system directory - dumps go to /backup or to a directory of their own (/data/dumps, /mnt/backup)" >&2; return 2
    fi
    if ! dump_path_safe "$dir_real"; then
      echo "$dir_base cannot hold dumps: a part of the path belongs to another user or others may write to it, and root would follow whatever they put there" >&2; return 2
    fi
  fi
  local dir_req="$dir_base"
  dir_base="$(dump_root_of "$dir_base" "$engine" "$container")"
  case "$keep" in ''|*[!0-9]*) keep=2 ;; esac
  [ "$keep" -lt 1 ] && keep=1; [ "$keep" -gt 30 ] && keep=30
  case "$minfree" in ''|*[!0-9]*) minfree=10 ;; esac
  [ "$minfree" -gt 50 ] && minfree=50   # above 50% it is no longer a reserve but half the disk wasted
  # A node can carry several engines of the same type (kervax-db-1 and zabbix-postgres). Each
  # gets ITS OWN script and ITS OWN directory: otherwise the second would overwrite the first,
  # and a "keep the last N" cleanup would delete someone else's dumps. Without a container (a
  # native installation) it works as before.
  local slot="$engine" out="$dir_base/$engine"
  if [ -n "$container" ]; then
    slot="$engine@$container"
    out="$dir_base/$engine/$container"
  fi
  local skipf="$DUMPS_D/$slot.skip"   # marker: "the last run was skipped for lack of space"
  # A FAST availability probe instead of a full trial dump (see dump_probe). It catches silent
  # failures (role, password, access) in seconds without pulling data. The full dump runs on the
  # backup schedule. This used to run the whole dump: minutes on a large database, the panel
  # timed out and showed an "error" while the dump was still running.
  # The probe goes FIRST (0.38): a dump that cannot log in leaves nothing behind (before, every
  # failed try left the dump directory and a drop-in on the backup service), changing the
  # settings of a working dump keeps it as it was when the probe fails, and the host MySQL dump is
  # generated with the login the probe found.
  local perr prc=0
  perr="$(mktemp /tmp/kv-dump.XXXXXX)" || { echo "mktemp failed" >&2; return 2; }
  dump_probe "$engine" "$container" >"$perr" 2>&1 || prc=$?
  if [ "$prc" -ne 0 ]; then
    local err; err="$(tr '\n' ' ' <"$perr" | sed 's/  */ /g; s/^ //; s/ $//' | tail -c 1000)"; rm -f "$perr"
    # never an empty reason: the panel has nothing to show then
    [ -n "$err" ] || err="the check of $slot exited with code $prc and printed nothing"
    echo "the dump probe failed, dumps were NOT enabled: $err" >&2; return 2
  fi
  rm -f "$perr"
  # the chosen directory is created when missing and never chmod'ed: it may hold other things
  [ -d "$dir_req" ] || install -d -m 0755 "$dir_req"
  install -d -m 0700 "$dir_base" "$dir_base/$engine" "$out"
  write_run_dumps
  local f="$DUMPS_D/$slot.sh"
  {
    printf '#!/usr/bin/env bash\n# generated by kervax - dump of %s before the file backup\nset -uo pipefail\n' "$engine"
    dump_gz_header
    printf 'OUT=%q\nKEEP=%s\nCONT=%q\nKT=%q\nMINFREE=%s\nSKIPF=%q\n' "$out" "$keep" "$dcont" "$kt" "$minfree" "$skipf"
    printf 'TS=$(date +%%Y%%m%%d-%%H%%M%%S)\n'
    printf 'FINAL="$OUT"\nMULTI=""\n'
    # OVERFLOW PROTECTION: the dump does not start if less than MINFREE% would be left on the
    # filesystem afterwards. The size of the upcoming dump is estimated from the last successful
    # one times 1.2 (for growth). The first dump (no estimate yet) is allowed - filling the disk
    # to zero is prevented by the atomic write into .partial (it fails with "No space" and the
    # fragment is removed). On a skip we write the SKIPF marker and exit 0: this is a DELIBERATE
    # skip, not a failure (otherwise run-dumps would treat it as an error).
    printf 'if [ "$MINFREE" -gt 0 ]; then\n'
    printf '  read -r AVAIL TOTAL <<<"$(df -kP "$FINAL" | awk %s)"\n' "'NR==2{print \$4, \$2}'"
    printf '  LAST=$(ls -1t "$FINAL"/* 2>/dev/null | head -1)\n'
    printf '  EST=0; [ -n "$LAST" ] && EST=$(du -sk "$LAST" 2>/dev/null | cut -f1)\n'
    printf '  NEED=$(( EST * 12 / 10 )); MIN=$(( TOTAL * MINFREE / 100 ))\n'
    printf '  if [ "$TOTAL" -gt 0 ] && [ $(( AVAIL - NEED )) -lt "$MIN" ]; then\n'
    printf '    printf %s "$(date +%%s)" "$(( AVAIL * 100 / TOTAL ))" "$(( NEED / 1024 ))" > "$SKIPF"\n' "'%s|%s|%s\\n'"
    printf '    echo "kervax-dump: %s SKIPPED - free space on the filesystem is $(( AVAIL*100/TOTAL ))%%, threshold ${MINFREE}%% (needs about $(( NEED/1024 )) MB)" >&2\n' "$slot"
    printf '    exit 0\n  fi\nfi\n'
    printf 'rm -f "$SKIPF"\n'   # there was enough space - clear the previous skip marker
    # a pod is found anew on every run (its name changes with every restart and rollout)
    if [ -n "$kt" ]; then
      declare -f kube_ctl kube_pod kube_container kube_enter KEX
      printf 'kube_enter "$KT" %q || { echo "kervax-dump: %s - the pod was not found" >&2; exit 1; }\n' "$engine" "$slot"
    fi
    # ATOMICITY: we write into a temporary subdirectory and move the finished result. A dump
    # interrupted halfway (a reboot, an OOM kill, a killed session) would otherwise leave a
    # truncated .gz next to the real ones - the panel would count it as a dump file and restic
    # would carry a corrupt archive into the backup. Verified in practice: an interrupted
    # pg_dumpall does not pass `gzip -t`.
    printf 'OUT="$OUT/.partial"\nrm -rf "$OUT"; mkdir -p "$OUT"\n'
    case "$engine" in
      pg)
           # EACH database into its own file (pg_dump), plus globals.sql.gz with roles and
           # grants (pg_dumpall --globals-only) - a per-database pg_dump does NOT include them,
           # and without them a restore onto a clean server would give tables with no users and
           # no GRANTs. A run goes into a timestamped subdirectory ($OUT/<TS>) and rotation is
           # per run (MULTI=1). The role is read from the container's POSTGRES_USER (see v7);
           # -u postgres, or the default user where that does not exist (bitnami).
           # In a pod the role and the password come from the environment of the database container
           # itself (POSTGRES_USER/POSTGRES_PASSWORD), expanded inside it.
           pg_body='MULTI=1
if [ -n "$KT" ]; then
  PGU=$(KEX sh -c "printf %s \"\${POSTGRES_USER:-postgres}\"" 2>/dev/null); [ -n "$PGU" ] || PGU=postgres
  DEX() { KEX sh -c "PGPASSWORD=\"\${POSTGRES_PASSWORD:-\${PGPASSWORD:-}}\"; export PGPASSWORD; exec \"\$@\"" sh "$@"; }
elif [ -n "$CONT" ]; then
  PGU=$(docker inspect -f "{{range .Config.Env}}{{println .}}{{end}}" "$CONT" 2>/dev/null | sed -n "s/^POSTGRES_USER=//p" | head -1)
  [ -n "$PGU" ] || PGU=postgres
  DEX() { docker exec -u postgres "$CONT" "$@" 2>/dev/null || docker exec "$CONT" "$@"; }
else PGU=""; DEX() { sudo -u postgres "$@"; }; fi
RUN="$FINAL/.partial-$TS"; rm -rf "$RUN"; mkdir -p "$RUN"
DEX pg_dumpall ${PGU:+-U "$PGU"} --globals-only | $GZ > "$RUN/globals.sql.gz"
DBS=$(DEX psql ${PGU:+-U "$PGU"} -Atc "SELECT datname FROM pg_database WHERE datallowconn AND NOT datistemplate ORDER BY datname")
for db in $DBS; do
  safe=$(printf "%s" "$db" | tr -c "A-Za-z0-9._-" "_")
  DEX pg_dump ${PGU:+-U "$PGU"} "$db" | $GZ > "$RUN/$safe.sql.gz"
done
'
           printf '%s' "$pg_body" ;;
      mysql) printf 'F="$OUT/mysqldump-all-$TS.sql.gz"\n'
           # --single-transaction: a snapshot without locking the tables (InnoDB).
           # The root password is expanded INSIDE the container (sh -c) rather than passed in
           # the docker exec arguments - otherwise it would show up in ps on the host. MYSQL_PWD
           # rather than -p: a password in argv is visible even inside the container.
           # mariadb:11 no longer ships the mysqldump symlink - mariadb-dump first
           my_sh="'MYSQL_PWD=\"\${MYSQL_ROOT_PASSWORD:-\${MARIADB_ROOT_PASSWORD:-}}\"; export MYSQL_PWD; if command -v mariadb-dump >/dev/null 2>&1; then exec mariadb-dump -u root --all-databases --single-transaction --quick; else exec mysqldump -u root --all-databases --single-transaction --quick; fi'"
           printf 'if [ -n "$KT" ]; then KEX sh -c %s | $GZ > "$F"\n' "$my_sh"
           printf 'elif [ -n "$CONT" ]; then docker exec "$CONT" sh -c %s | $GZ > "$F"\n' "$my_sh"
           # on the host: the client and the options file the probe got in with (my_host_probe)
           printf 'else MYBIN=%q; MYDEF=%q\n' "${MY_BIN:-mysqldump}" "$MY_DEF"
           printf '%s\n' '  "$MYBIN" ${MYDEF:+"--defaults-file=$MYDEF"} --all-databases --single-transaction --quick | $GZ > "$F"; fi' ;;
      redis) printf 'F="$OUT/redis-$TS.rdb"\n'
           # --rdb performs a full sync into a file; from a container we extract it with
           # docker cp because redis-cli writes a FILE (streaming to stdout is not supported
           # everywhere)
           # in a pod: kubectl cp needs tar in the image, so the file is read back with cat. It is
           # written into the first writable data directory - the root filesystem of a pod is
           # often read-only.
           printf 'if [ -n "$KT" ]; then KEX sh -c %s > "$F"\n' \
                  "'p=\"\${REDISCLI_AUTH:-\${REDIS_PASSWORD:-}}\"; [ -n \"\$p\" ] && export REDISCLI_AUTH=\"\$p\"; for d in /data /bitnami/redis/data /var/lib/redis /tmp; do if [ -d \"\$d\" ] && [ -w \"\$d\" ]; then f=\"\$d/.kervax-dump.rdb\"; redis-cli --rdb \"\$f\" >/dev/null 2>&1 && cat \"\$f\"; rc=\$?; rm -f \"\$f\"; exit \$rc; fi; done; exit 1'"
           printf 'elif [ -n "$CONT" ]; then docker exec "$CONT" redis-cli --rdb /tmp/kervax.rdb >/dev/null 2>&1 && docker cp "$CONT":/tmp/kervax.rdb "$F" >/dev/null && docker exec "$CONT" rm -f /tmp/kervax.rdb\n'
           printf 'else redis-cli --rdb "$F" >/dev/null 2>&1; fi\n'
           printf '$GZF "$F" 2>/dev/null; F="$F.gz"\n' ;;
      rabbitmq) printf 'F="$OUT/rabbitmq-defs-$TS.json"\n'
           # export_definitions covers users, vhosts, queues and policies (MESSAGES are not included)
           # in a pod straight to stdout ("-"): its root filesystem is often read-only (erofs on /tmp)
           printf 'if [ -n "$KT" ]; then KEX rabbitmqctl -q export_definitions - > "$F" 2>/dev/null\n'
           printf 'elif [ -n "$CONT" ]; then docker exec "$CONT" rabbitmqctl export_definitions /tmp/kervax.json >/dev/null 2>&1 && docker cp "$CONT":/tmp/kervax.json "$F" >/dev/null && docker exec "$CONT" rm -f /tmp/kervax.json\n'
           printf 'else rabbitmqctl export_definitions "$F" >/dev/null 2>&1; fi\n'
           printf '$GZF "$F" 2>/dev/null; F="$F.gz"\n' ;;
      k8s) printf 'F="$OUT/cluster-$TS"\n'
           # A cluster backup TOGETHER with etcd, using the distribution's own command, on the
           # controller as root. No kubectl exec: k0s and k3s can do this themselves.
           printf 'if command -v k0s >/dev/null 2>&1; then mkdir -p "$F" && k0s backup --save-path "$F" >/dev/null 2>&1\n'
           printf 'elif command -v k3s >/dev/null 2>&1; then mkdir -p "$F" && k3s etcd-snapshot save --dir "$F" >/dev/null 2>&1\n'
           printf 'else echo "no k0s/k3s found - an etcd snapshot has to be taken with etcdctl manually" >&2; exit 1; fi\n'
           printf 'tar -cf - -C "$(dirname "$F")" "$(basename "$F")" 2>/dev/null | $GZ > "$F.tar.gz" && rm -rf "$F"; F="$F.tar.gz"\n' ;;
      grafana) printf 'F="$OUT/grafana-$TS.db"\n'
           # the standard ONLINE SQLite backup (.backup / Connection.backup): the snapshot is
           # taken under the engine's own lock, so Grafana does not have to be stopped. A plain
           # cp will not do - a live database is being written and the file may come out torn.
           printf 'DB=%q\n' "$(grafana_db_path)"
           printf 'if command -v sqlite3 >/dev/null 2>&1; then sqlite3 "$DB" ".backup $F" >/dev/null 2>&1\n'
           printf 'else python3 -c %s "$DB" "$F" >/dev/null 2>&1; fi\n' \
                  "'import sqlite3,sys; s=sqlite3.connect(sys.argv[1]); d=sqlite3.connect(sys.argv[2]); s.backup(d); d.close(); s.close()'"
           printf '$GZF "$F" 2>/dev/null; F="$F.gz"\n' ;;
      neo4j) printf 'F="$OUT/neo4j-$TS.tar.gz"\n'
           # Neo4j Community cannot do an online dump: neo4j-admin refuses to work on a live
           # database ("The database is in use"), and a hot backup exists only in Enterprise. So
           # the database is stopped for the duration of the dump and ALWAYS brought back up -
           # even if the dump failed (otherwise a single failure would leave the service down
           # until morning).
           #
           # The dump is taken by a THROWAWAY container from the same image with
           # --volumes-from: the container itself is stopped at that moment while its data stays
           # reachable through its volumes. --entrypoint neo4j-admin is mandatory: the image's
           # normal entrypoint drops privileges to the neo4j user, which then cannot write into
           # our directory (verified: AccessDeniedException on /kvdump).
           #
           # ALL databases are taken ("*"): users and roles live in system, and without it a
           # restore yields data with no access rights.
           printf 'if [ -n "$CONT" ]; then\n'
           printf '  IMG=$(docker inspect -f "{{.Config.Image}}" "$CONT" 2>/dev/null)\n'
           printf '  WASUP=$(docker inspect -f "{{.State.Running}}" "$CONT" 2>/dev/null)\n'
           printf '  [ "$WASUP" = "true" ] && docker stop "$CONT" >/dev/null 2>&1\n'
           printf '  docker run --rm --user root --entrypoint neo4j-admin --volumes-from "$CONT" \\\n'
           printf '    -v "$OUT":/kvdump "$IMG" database dump "*" --to-path=/kvdump >/dev/null 2>&1\n'
           printf '  rc2=$?\n'
           printf '  [ "$WASUP" = "true" ] && docker start "$CONT" >/dev/null 2>&1\n'
           printf 'else\n'
           printf '  WASUP=$(systemctl is-active neo4j 2>/dev/null)\n'
           printf '  [ "$WASUP" = "active" ] && systemctl stop neo4j >/dev/null 2>&1\n'
           printf '  neo4j-admin database dump "*" --to-path="$OUT" >/dev/null 2>&1; rc2=$?\n'
           printf '  [ "$WASUP" = "active" ] && systemctl start neo4j >/dev/null 2>&1\n'
           printf 'fi\n'
           # each database produces its own .dump - the run is packed into a single archive
           printf 'if [ "$rc2" = "0" ] && ls "$OUT"/*.dump >/dev/null 2>&1; then\n'
           printf '  tar -cf - -C "$OUT" $(cd "$OUT" && ls *.dump) 2>/dev/null | $GZ > "$F" && rm -f "$OUT"/*.dump\n'
           # else false: rc below is read from $?, and without an explicit failure a broken
           # dump would look successful - the if branch would simply not run and return 0
           printf 'else false; fi\n' ;;
      ch)  printf 'F="$OUT/clickhouse-$TS.sql.gz"\n'
           # the schema, read from the server's metadata files: no login and no password (see
           # ch_schema). The data is not dumped.
           declare -f ch_schema
           printf 'if [ -n "$KT" ]; then ch_schema KEX\nelif [ -n "$CONT" ]; then ch_schema docker exec "$CONT"\nelse ch_schema\nfi | $GZ > "$F"\n' ;;
    esac
    printf 'rc=$?\n'
    # Two finishing modes. MULTI (pg): a run is the subdirectory $FINAL/<TS> holding a set of
    # files - each is checked with gzip -t, the finished subdirectory is published as is (it was
    # written straight into $FINAL/$TS, not into .partial) and rotation happens per RUN.
    # Single-file engines behave as before: one $F, an atomic move out of .partial, rotation by
    # file.
    fin_multi='if [ -n "$MULTI" ]; then
  if [ -z "$(ls -A "$RUN" 2>/dev/null)" ]; then rm -rf "$OUT" "$RUN"; echo "pg dump: no file was produced" >&2; exit 1; fi
  for gz in "$RUN"/*.gz; do gzip -t "$gz" 2>/dev/null || { rm -rf "$RUN"; echo "pg dump is corrupt: $(basename "$gz")" >&2; exit 1; }; done
  chmod 0700 "$RUN"; chmod 0600 "$RUN"/*.gz; rm -rf "$OUT"
  mv -f "$RUN" "$FINAL/$TS"   # the run is published in a single move
  ls -1dt "$FINAL"/*/ 2>/dev/null | tail -n +$((KEEP+1)) | xargs -r rm -rf
  echo "kervax-dump: pg -> $FINAL/$TS ($(ls -1 "$FINAL/$TS"/*.gz 2>/dev/null | wc -l) files)"
  exit 0
fi
'
    printf '%s' "$fin_multi"
    printf 'if [ $rc -ne 0 ] || [ ! -s "$F" ]; then rm -rf "$OUT"; echo "%s dump failed (rc=$rc)" >&2; exit 1; fi\n' "$engine"
    # gzip -t catches exactly a truncation: the file is there and not empty but cannot be decompressed
    printf 'case "$F" in *.gz) gzip -t "$F" 2>/dev/null || { rm -rf "$OUT"; echo "%s dump is corrupt (write interrupted)" >&2; exit 1; } ;; esac\n' "$engine"
    printf 'chmod 0600 "$F"\n'
    # publication: the finished file is moved in one go and the temporary directory is removed
    printf 'mv -f "$F" "$FINAL/"; F="$FINAL/$(basename "$F")"; rm -rf "$OUT"; OUT="$FINAL"\n'
    # rotation: only the last KEEP are kept, otherwise the history eats the local disk
    printf 'ls -1t "$OUT"/*.gz 2>/dev/null | tail -n +$((KEEP+1)) | xargs -r rm -f\n'
    printf 'echo "kervax-dump: %s → $F"\n' "$engine"
  } > "$f"
  chmod 0700 "$f"; chown root:root "$f"
  # slot metadata: get-config reads it from here rather than parsing the generated script.
  # dir is configurable, so it can no longer be derived from a fixed DUMP_DIR_BASE.
  printf 'dir=%s\nkeep=%s\nminfree=%s\n' "$out" "$keep" "$minfree" > "$DUMPS_D/$slot.meta"
  chmod 0644 "$DUMPS_D/$slot.meta"
  local trial_note=" - the first dump will be taken with the next scheduled backup"
  systemctl cat "$PROV_SERVICE" >/dev/null 2>&1 || trial_note=" - the first dump will be taken on the next timer run"
  # A dump is useless if restic does not pick it up. In include mode the dump directory has to
  # be listed explicitly, otherwise the dumps would silently pile up locally and go nowhere.
  local added=""
  local script; script="$(find_script || true)"
  if [ "$(runner_kind)" = unit ]; then
    # the old runner: its paths live in the unit, the panel does not edit them - only warn
    script=""
    unit_covers "$dir_base" || added=" WARNING: $dir_base is not in the paths of the backup unit (restic in its ExecStart) - the dumps will not reach the backup; move the backup to the panel runner (adopt) or add the directory to the unit"
  fi
  if [ -n "$script" ]; then
    local cur_mode inc
    cur_mode="$(sed -n 's/^INCLUDE_MODE="\(.*\)".*/\1/p' "$script" | head -1)"
    if [ "$cur_mode" = include ]; then
      inc="$(sed -n 's/^INCLUDES_STR="\(.*\)"$/\1/p' "$script" | head -1)"
      # line format: "/etc" "/var/www". The value is built in a SEPARATE variable and only
      # then handed to sed - otherwise the quote escaping inside the sed command itself drifts
      # and the runner receives a path like \"/backup\" (verified: restic then looks for a
      # non-existent path).
      if ! printf '%s' "$inc" | grep -qF "\"$dir_base\""; then
        local newinc esc
        newinc="${inc:+$inc }\"$dir_base\""
        esc="$(printf '%s' "$newinc" | sed 's/[|&\\]/\\&/g')"   # sed metacharacters only
        sed -i "s|^INCLUDES_STR=\".*\"|INCLUDES_STR=\"$esc\"|" "$script"
        added=" ($dir_base was added to the backup list)"
      fi
    else
      # exclude mode: make sure the dump directory is not thrown out by an exclusion
      local exc; exc="$(sed -n 's/^EXCLUDES_STR="\(.*\)"$/\1/p' "$script" | head -1)"
      case "$exc" in
        *"--exclude=$dir_base"*|*"--exclude=$dir_req "*|*"--exclude=$dir_req") added=" WARNING: $dir_base is on the exclusion list - the dumps will not reach the backup!" ;;
      esac
    fi
  fi
  refresh_config
  # we report whatever actually triggers it: on a node without a file backup, promising "before
  # every backup" would be a lie, since its own timer runs there
  local when="before every backup"
  systemctl cat "$PROV_SERVICE" >/dev/null 2>&1 || when="daily, on its own timer (this node has no file backup - the copy is local only)"
  echo "OK $engine dumps enabled -> $out ($when, keeping $keep, space threshold ${minfree}%)$added$trial_note"
}

# Disable the dump of ONE engine. Both the script and the accumulated files are removed:
# otherwise restic would keep carrying the same stale dump into the backup forever. No history
# is lost - previous dumps already sit in restic snapshots on the backup server.
# The ExecStartPre drop-in is left alone: run-dumps.sh on an empty directory simply exits 0, and
# re-enabling needs no extra work.
cmd_dump_remove() {
  local engine="$1" container="${2:-}"
  case "$engine" in
    pg|mysql|ch|redis|rabbitmq|k8s|grafana|neo4j) ;;
    *) echo "unknown engine: $engine" >&2; return 2 ;;
  esac
  case "$container" in ''|*[!A-Za-z0-9._-]*) container="" ;; esac
  local slot="$engine"
  [ -n "$container" ] && slot="$engine@$container"
  local f="$DUMPS_D/$slot.sh"
  [ -f "$f" ] || { echo "$slot dumps were not enabled anyway" >&2; return 2; }
  # the dump directory comes from .meta: it may have been configured non-standard. With no meta
  # (an older slot) the old DUMP_DIR_BASE scheme applies.
  local out="$DUMP_DIR_BASE/$engine"; [ -n "$container" ] && out="$DUMP_DIR_BASE/$engine/$container"
  local base="$DUMP_DIR_BASE"
  if [ -f "$DUMPS_D/$slot.meta" ]; then
    out="$(sed -n 's/^dir=//p' "$DUMPS_D/$slot.meta" | head -1)"
    base="$(dirname "$(dirname "$out")")"; [ -z "$container" ] && base="$(dirname "$out")"
  fi
  # Only a directory the helper itself lays out is removed: <base>/<engine>[/<container>] with
  # a base that is not a system directory. 0.42 and older trusted dir= from .meta, and a dump
  # set up on /var/lib turned dump-remove into rm -rf /var/lib/mysql.
  local want="$base/$engine"; [ -n "$container" ] && want="$base/$engine/$container"
  local keepfiles=""
  case "$out" in /*) ;; *) keepfiles=1 ;; esac
  case "$out" in *..*|*[!A-Za-z0-9._/-]*) keepfiles=1 ;; esac
  [ "$out" = "$want" ] || keepfiles=1
  dump_sys_dir "$base" && keepfiles=1
  [ -z "$keepfiles" ] && dump_sys_dir "$(realpath -m -- "$base")" && keepfiles=1
  rm -f "$f" "$DUMPS_D/$slot.meta" "$DUMPS_D/$slot.skip"
  if [ -n "$keepfiles" ]; then
    refresh_config
    echo "OK $slot dumps disabled; the files in $out were left in place: it is not a dump directory this helper lays out"
    return 0
  fi
  rm -rf --one-file-system "${out:?}"
  # the engine directory is removed only if no dumps of another container remain in it
  rmdir "$(dirname "$out")" 2>/dev/null || true
  refresh_config
  echo "OK $slot dumps disabled, local files removed (the history stays in restic)"
}

# which dumps are enabled - the panel shows this under Coverage
cmd_dump_status() {
  local j="" e f n sz
  for f in "$DUMPS_D"/*.sh; do
    [ -f "$f" ] || continue
    e="$(basename "$f" .sh)"
    n=$(find "$DUMP_DIR_BASE/$e" -maxdepth 1 -type f -name '*.gz' 2>/dev/null | wc -l)
    sz=$(du -sb "$DUMP_DIR_BASE/$e" 2>/dev/null | cut -f1); [ -z "$sz" ] && sz=0
    j="${j:+$j,}{\"engine\":\"$(json_escape "$e")\",\"files\":$n,\"size_bytes\":$sz}"
  done
  printf '[%s]\n' "$j"
}

cmd_get_config() {
  local script timer mode="" sched="" inc="" exc=""
  script="$(find_script || true)"; timer="$(find_timer || true)"
  if [ -n "$script" ]; then
    mode="$(sed -n 's/^INCLUDE_MODE="\(.*\)".*/\1/p' "$script" | head -1)"
    # only the list of the ACTIVE mode is read: on nodes provisioned by an older helper both
    # are filled in, and without this the panel would show the stale list of the other mode
    if [ "$mode" = include ]; then
      inc="$(sed -n 's/^INCLUDES_STR="\(.*\)"$/\1/p' "$script" | head -1)"
    else
      exc="$(sed -n 's/^EXCLUDES_STR="\(.*\)"$/\1/p' "$script" | head -1)"
    fi
  fi
  [ -n "$timer" ] && sched="$(systemctl cat "$timer" 2>/dev/null | sed -n 's/^OnCalendar=.* \([0-9]\{1,2\}:[0-9]\{2\}\):00$/\1/p' | head -1)"
  local ex_json="" in_json="" p
  for p in $(printf '%s\n' "$exc" | grep -oE -- '--exclude=[^ ]+' | sed 's/^--exclude=//'); do
    ex_json="${ex_json:+$ex_json,}\"$(json_escape "$p")\""; done
  for p in $(printf '%s\n' "$inc" | grep -oE '"[^"]+"' | tr -d '"'); do
    in_json="${in_json:+$in_json,}\"$(json_escape "$p")\""; done
  # the backup destination comes from the env, WITHOUT the password or htpasswd (the config file is world-readable!)
  local repo_masked=""
  if [ -f "$PROV_ENV" ]; then
    local url; url="$(sed -n 's/^RESTIC_REPOSITORY=//p' "$PROV_ENV" | head -1)"
    repo_masked="$(printf '%s' "$url" | sed -E 's#(rest:[a-z]+://)[^@]*@#\1#')"
  fi
  # The state of ENABLED dumps - a state, not a one-off command reply: the panel has to show
  # "dumps are running, N files, this much space, the last one at this time", otherwise the card
  # looks exactly the same after enabling as before it.
  # A slot is either "engine" or "engine@container": the panel shows the state of EACH database
  # separately, otherwise a second postgres would look covered by the first one's dump
  local dumps_json="" slot de dcont ddir dn dsz dts dkeep dminfree skipped skip_ts skip_free enabled_ts
  for slot in "$DUMPS_D"/*.sh; do
    [ -f "$slot" ] || continue
    slot="$(basename "$slot" .sh)"
    de="${slot%%@*}"; dcont=""
    case "$slot" in *@*) dcont="${slot#*@}" ;; esac
    enabled_ts=$(stat -c %Y "$DUMPS_D/$slot.sh" 2>/dev/null || echo 0)  # when the dump was enabled
    # dir/keep/minfree come from .meta (dir is configurable and cannot be derived from
    # DUMP_DIR_BASE). Older slots without .meta (before this version) fall back to the defaults
    # and the old path scheme.
    ddir="$DUMP_DIR_BASE/$de"; [ -n "$dcont" ] && ddir="$DUMP_DIR_BASE/$de/$dcont"
    dkeep="$DUMP_KEEP"; dminfree=10
    if [ -f "$DUMPS_D/$slot.meta" ]; then
      ddir="$(sed -n 's/^dir=//p' "$DUMPS_D/$slot.meta" | head -1)"
      dkeep="$(sed -n 's/^keep=//p' "$DUMPS_D/$slot.meta" | head -1)"
      dminfree="$(sed -n 's/^minfree=//p' "$DUMPS_D/$slot.meta" | head -1)"
    fi
    dn=$(find "$ddir" -type f -name "*.gz" ! -path "*/.partial-*" 2>/dev/null | wc -l)
    dsz=$(du -sb "$ddir" 2>/dev/null | cut -f1); [ -z "$dsz" ] && dsz=0
    dts=$(find "$ddir" -type f -name "*.gz" ! -path "*/.partial-*" -printf '%T@\n' 2>/dev/null | sort -rn | head -1 | cut -d. -f1)
    [ -z "$dts" ] && dts=0
    # the out-of-space skip marker (written by the dump script itself): "ts|free_pct|need_mb"
    skipped=false; skip_ts=0; skip_free=0
    if [ -f "$DUMPS_D/$slot.skip" ]; then
      skipped=true
      skip_ts="$(cut -d'|' -f1 "$DUMPS_D/$slot.skip")"; [ -z "$skip_ts" ] && skip_ts=0
      skip_free="$(cut -d'|' -f2 "$DUMPS_D/$slot.skip")"; [ -z "$skip_free" ] && skip_free=0
    fi
    dumps_json="${dumps_json:+$dumps_json,}{\"engine\":\"$(json_escape "$de")\",\"container\":\"$(json_escape "$dcont")\",\"files\":$dn,\"size_bytes\":$dsz,\"last_ts\":$dts,\"keep\":${dkeep:-2},\"min_free_pct\":${dminfree:-10},\"dir\":\"$(json_escape "$ddir")\",\"skipped\":$skipped,\"skip_ts\":$skip_ts,\"skip_free_pct\":$skip_free,\"enabled_ts\":${enabled_ts:-0}}"
  done
  # helper_version tells the panel that the helper on the node is outdated (it needs reinstalling)
  printf '{"manageable":true,"helper_version":%s,"mode":"%s","schedule":"%s","includes":[%s],"excludes":[%s],"repo_dest":"%s","dumps":[%s]}\n' \
    "$HELPER_VER" "${mode:-exclude}" "${sched:-}" "$in_json" "$ex_json" "$(json_escape "$repo_masked")" "$dumps_json"
}

# get-creds returns the data needed for a restore (repo URL plus password). A secret: only on
# an explicit panel request, through the spool (res 0770, removed at once). NEVER into the config file.
# to-https <tls_port> <cacert_b64> moves the panel backup from rest:http to the TLS rest-server of
# the same backup server (the second rest-server with --tls over the same data and htpasswd). The
# https address is built HERE from the node's own env (the panel never sees the login and password):
# the same login, host and repository, only the scheme and the port change. First the repository is
# read over https with the certificate (restic snapshots); only when that works are the env, the
# certificate and the runner switched. A failed check changes nothing, the backup stays on http.
# The previous env is kept next to it as .http-bak (0600) for a manual way back.
cmd_to_https() {
  local port="$1" cacert_b64="$2"
  [[ "$port" =~ ^[0-9]{2,5}$ ]] || { echo "bad port" >&2; return 2; }
  [ -n "$cacert_b64" ] && [ "$cacert_b64" != "-" ] || { echo "no certificate of the backup server" >&2; return 2; }
  [ -f "$PROV_ENV" ] || { echo "env not found (the backup was not configured by this panel)" >&2; return 2; }
  [ -f "$PROV_SCRIPT" ] || { echo "the backup script $PROV_SCRIPT not found" >&2; return 2; }
  [ -x "$RESTIC_BIN" ] || { echo "restic not found ($RESTIC_BIN)" >&2; return 2; }
  local url pass
  url="$(sed -n 's/^RESTIC_REPOSITORY=//p' "$PROV_ENV" | head -1)"
  pass="$(sed -n 's/^RESTIC_PASSWORD=//p' "$PROV_ENV" | head -1)"
  case "$url" in
    rest:https://*) echo "OK already https"; return 0 ;;
    rest:http://*) ;;
    *) echo "the repository is not rest:http, nothing to move" >&2; return 2 ;;
  esac
  # rest:http://login:pass@host:port/repo/ -> rest:https://login:pass@host:<tls_port>/repo/
  local rest="${url#rest:http://}" hp path ui="" host
  hp="${rest%%/*}"; path="${rest#"$hp"}"
  case "$hp" in *@*) ui="${hp%@*}@"; hp="${hp##*@}" ;; esac
  case "$hp" in \[*) host="${hp%%]*}]" ;; *) host="${hp%%:*}" ;; esac
  [ -n "$host" ] || { echo "could not read the host from the repository address" >&2; return 2; }
  local new="rest:https://${ui}${host}:${port}${path}"
  local ca out n
  # the certificate is written into the restic directory: it has to be root's first (0.42 left it to bx231)
  backup_perms_maybe
  ca="$(mktemp "$RESTIC_BIN_DIR/.backup-ca.XXXXXX")" || { echo "mktemp failed" >&2; return 2; }
  if ! printf '%s' "$cacert_b64" | base64 -d > "$ca" 2>/dev/null || ! grep -q 'BEGIN CERTIFICATE' "$ca"; then
    rm -f "$ca"; echo "bad certificate" >&2; return 2
  fi
  chmod 0644 "$ca"
  # the check: the snapshots are read over https with the certificate. No lock, no cache - read only
  if ! out="$(RESTIC_REPOSITORY="$new" RESTIC_PASSWORD="$pass" timeout 150 \
              "$RESTIC_BIN" --cacert "$ca" --no-cache --no-lock snapshots --json 2>&1)"; then
    rm -f "$ca"
    # restic repeats the address in its errors: the login and password are cut out
    echo "the check over https failed, the backup stays on http: $(printf '%s' "$out" | sed -E 's#//[^@/ ]*@#//#g' | tr '\n' ' ' | cut -c1-300)" >&2
    return 2
  fi
  n="$(printf '%s' "$out" | grep -o '"short_id"' | wc -l | tr -d ' ')"
  # the switch: env (the RESTIC_REPOSITORY line plus RESTIC_CACERT), the certificate, the runner.
  # The previous runner and certificate are kept until the check below passes
  umask 077
  cp -p "$PROV_ENV" "$PROV_ENV.http-bak"
  NEW_URL="$new" awk '/^RESTIC_REPOSITORY=/ { print "RESTIC_REPOSITORY=" ENVIRON["NEW_URL"]; next } { print }' \
    "$PROV_ENV" > "$PROV_ENV.tmp" && chown root:root "$PROV_ENV.tmp" && chmod 0600 "$PROV_ENV.tmp" \
    && mv -f "$PROV_ENV.tmp" "$PROV_ENV" && env_cacert_set \
    || { umask 022; rm -f "$PROV_ENV.tmp" "$ca"; mv -f "$PROV_ENV.http-bak" "$PROV_ENV"; echo "could not write the env" >&2; return 2; }
  umask 022
  local prev_ca=""
  [ -f "$PROV_CACERT" ] && { prev_ca="$PROV_CACERT.pre-https"; cp -p "$PROV_CACERT" "$prev_ca"; }
  mv -f "$ca" "$PROV_CACERT"
  cp -p "$PROV_SCRIPT" "$PROV_SCRIPT.kervax-pre-https.bak"
  # the panel's runner keeps restic in RESTIC= and gets --cacert there too; a runner without that
  # line (the ansible one, restic in BACKUP_CMD) is left as is - RESTIC_CACERT in the env covers it
  local line; line="$(printf 'RESTIC=%q' "$RESTIC_BIN --cacert $PROV_CACERT")"
  if LINE="$line" awk '/^RESTIC=/ { print ENVIRON["LINE"]; next } { print }' "$PROV_SCRIPT" > "$PROV_SCRIPT.tmp"; then
    chmod 0700 "$PROV_SCRIPT.tmp"; chown "$PROV_USER:$PROV_USER" "$PROV_SCRIPT.tmp" 2>/dev/null || true
    mv -f "$PROV_SCRIPT.tmp" "$PROV_SCRIPT"
  else
    rm -f "$PROV_SCRIPT.tmp"
  fi
  # the check the way the night run goes: the service's user and env files, no --cacert of its own.
  # The read with --cacert above proves the server, this one proves the backup job. Fails - all back
  if ! out="$(unit_restic_check 2>&1)"; then
    mv -f "$PROV_ENV.http-bak" "$PROV_ENV"
    mv -f "$PROV_SCRIPT.kervax-pre-https.bak" "$PROV_SCRIPT"
    if [ -n "$prev_ca" ]; then mv -f "$prev_ca" "$PROV_CACERT"; else rm -f "$PROV_CACERT"; fi
    refresh_config
    echo "the backup job would not trust the backup server over https (checked as $PROV_SERVICE runs), the backup stays on http: $(printf '%s' "$out" | grep -a -v 'retrying after' | sed -E 's#//[^@/ ]*@#//#g' | tr '\n' ' ' | cut -c1-300)" >&2
    return 2
  fi
  rm -f "$prev_ca"
  refresh_config
  echo "OK the backup goes over https :$port, snapshots read over https: $n, the backup job trusts the certificate; the previous env is in $PROV_ENV.http-bak"
}

# RESTIC_CACERT in the env makes every restic run of the backup trust the backup server certificate:
# restic reads it itself, so it works for any runner - the panel's one with RESTIC=... and the
# ansible one with the restic path in BACKUP_CMD. 0.40 edited only RESTIC= and left such runners
# without the certificate: the switch said OK and the night run failed on x509.
env_cacert_set() {
  local tmp="$PROV_ENV.tmp"
  ( umask 077; { grep -v '^RESTIC_CACERT=' "$PROV_ENV"; echo "RESTIC_CACERT=$PROV_CACERT"; } > "$tmp" ) \
    && chown root:root "$tmp" && chmod 0600 "$tmp" && mv -f "$tmp" "$PROV_ENV" || { rm -f "$tmp"; return 1; }
}

# restic as the backup service runs it: a transient unit with the service's User and EnvironmentFile,
# reading the repository config (no lock, no cache). 150 s at most: on a certificate error restic
# retries for a quarter of an hour.
unit_restic_check() {
  local svc user f props=()
  svc="$(find_timer)" || true
  svc="${svc:-$PROV_TIMER}"; svc="${svc%.timer}.service"
  user="$(systemctl show -p User --value "$svc" 2>/dev/null)" || true
  [ -n "$user" ] && props+=(-p "User=$user")
  while read -r f _; do
    [ -n "$f" ] && props+=(-p "EnvironmentFile=$f")
  done < <(systemctl show -p EnvironmentFiles --value "$svc" 2>/dev/null || true)
  # a unit without EnvironmentFile: the runner reads the env itself
  printf '%s\n' "${props[@]}" | grep -q '^EnvironmentFile=' || props+=(-p "EnvironmentFile=$PROV_ENV")
  timeout 180 systemd-run --wait --pipe --collect -q -p RuntimeMaxSec=150 "${props[@]}" -- \
    "$RESTIC_BIN" --no-cache --no-lock cat config < /dev/null > /dev/null
}

