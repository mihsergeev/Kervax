#!/bin/sh
# Панель работает НЕ от root. Контейнер стартует от root только затем, чтобы
# выровнять владельца смонтированного тома, и сразу сбрасывает привилегии.
#
# Почему не просто USER в Dockerfile: ./data на существующих установках создан
# прошлым образом, который работал от root. С одним лишь USER такой контейнер
# поднялся бы и упал на первой же записи (бэкап, heartbeat, логотип) — уже после
# того, как обновление сочли успешным. Поэтому права подгоняем сами, один раз.
set -eu

DATA="${KERVAX_DATA_DIR:-/data}"
APP_UID=10001

if [ "$(id -u)" = "0" ]; then
    mkdir -p "$DATA"
    # chown -R по каталогу с сотнями бэкапов не бесплатен, а нужен ровно один
    # раз — поэтому только когда владелец действительно не тот.
    if [ "$(stat -c %u "$DATA")" != "$APP_UID" ]; then
        echo "entrypoint: подгоняю владельца $DATA под kervax ($APP_UID)"
        # postgres — НЕ НАШ каталог. compose кладёт кластер базы в ./data/postgres,
        # то есть внутрь этого же тома, и принадлежит он пользователю postgres
        # (uid 70 в alpine-образе). Забрать его себе — значит уронить базу:
        # postgres отказывается стартовать, когда PGDATA принадлежит чужому.
        find "$DATA" -mindepth 1 -maxdepth 1 -name postgres -prune -o \
             -exec chown -R "$APP_UID:$APP_UID" {} +
        chown "$APP_UID:$APP_UID" "$DATA"
    fi
    exec gosu kervax "$@"
fi

# Уже не root (например, в compose задан user:) — просто запускаемся.
exec "$@"
