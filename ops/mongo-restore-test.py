#!/usr/bin/env python3
"""Fully restore a local mongodump archive into a disposable, offline MongoDB.

The source database is never contacted. No database names, records, credentials or
raw MongoDB diagnostics are printed. See README.md for limits and expectations.
"""
from __future__ import annotations

import argparse
import gzip
import hashlib
import json
import os
import re
import signal
import stat
import subprocess
import sys
import time
import uuid
import zlib


INVENTORY_KEYS = {"databases", "collections", "documents", "indexes", "users", "roles", "sha256"}
# This fixed program is sent on stdin; neither archive nor expectation data is JS.
INVENTORY_JS = r"""
const crypto = require('crypto');
const connection = new Mongo('mongodb://127.0.0.1:27017/?directConnection=true');
const hash = crypto.createHash('sha256');
const result = {databases:0, collections:0, documents:0, indexes:0, users:0, roles:0};
function add(value) { hash.update(EJSON.stringify(value, {relaxed:false})); hash.update('\n'); }
const names = connection.getDB('admin').runCommand({listDatabases:1,nameOnly:true});
if (names.ok !== 1) throw new Error('inventory');
for (const entry of names.databases.sort((a,b) => a.name.localeCompare(b.name))) {
  if (entry.name === 'local') continue;
  const database = connection.getDB(entry.name);
  let infos = database.getCollectionInfos().sort((a,b) => a.name.localeCompare(b.name));
  // Full-instance mongodump excludes local, admin.system.keys and runtime-only
  // config namespaces. Do not fingerprint state generated by this fresh mongod.
  if (entry.name === 'config') {
    const included = new Set(['chunks','collections','databases','settings','shards','tags','version']);
    infos = infos.filter(info => included.has(info.name));
  }
  if (entry.name === 'admin') infos = infos.filter(info => info.name !== 'system.keys');
  if (!infos.length) continue;
  result.databases++;
  add(['database', entry.name]);
  for (const info of infos) {
    // Authorization data is checked with showCredentials:false below.
    if (info.name === 'system.users' || info.name === 'system.roles' || info.name === 'system.version') continue;
    result.collections++;
    add(['collection', info.name, info.type, info.options]);
    if (info.type === 'view') continue;
    const collection = database.getCollection(info.name);
    const valid = database.runCommand({validate:info.name, full:true});
    if (valid.ok !== 1 || valid.valid !== true) throw new Error('validation');
    const indexes = collection.getIndexes().sort((a,b) => a.name.localeCompare(b.name));
    result.indexes += indexes.length;
    add(['indexes', indexes]);
    const cursor = collection.find().sort({_id:1}).batchSize(100);
    while (cursor.hasNext()) { add(cursor.next()); result.documents++; }
  }
}
// Accounts/roles can belong to a database with no collections and therefore not
// appear in listDatabases. Enumerate them independently, without credentials.
const admin = connection.getDB('admin');
const users = admin.runCommand({usersInfo:{forAllDBs:true},showCredentials:false,showCustomData:false});
const roleNames = admin.getCollection('system.roles').find({}, {role:1,db:1,_id:0}).toArray();
const roles = roleNames.length ? admin.runCommand({rolesInfo:roleNames,showPrivileges:true,
  showAuthenticationRestrictions:true}) : {ok:1,roles:[]};
if (users.ok !== 1 || roles.ok !== 1) throw new Error('authorization inventory');
result.users = users.users.length;
result.roles = roles.roles.length;
function accountOrder(a,b) { return (a.db+'\0'+(a.user || a.role)).localeCompare(b.db+'\0'+(b.user || b.role)); }
add(['users', users.users.map(u => ({user:u.user,db:u.db,roles:u.roles.sort(accountOrder),
  mechanisms:u.mechanisms ? u.mechanisms.sort() : []})).sort(accountOrder)]);
add(['roles', roles.roles.sort(accountOrder)]);
result.sha256 = hash.digest('hex');
print(JSON.stringify({inventory:result, version:connection.getDB('admin').version()}));
"""
PING_JS = "if (db.getSiblingDB('admin').runCommand({ping:1}).ok !== 1) quit(1);"


class Failure(Exception):
    """An intentionally non-sensitive failure reason."""


def positive(value: str) -> int:
    number = int(value)
    if not 1 <= number <= 1_048_576:
        raise argparse.ArgumentTypeError("value must be between 1 and 1048576")
    return number


def inventory(value) -> dict:
    if not isinstance(value, dict) or set(value) != INVENTORY_KEYS:
        raise Failure("invalid expectations")
    if any(type(value[k]) is not int or value[k] < 0 for k in INVENTORY_KEYS - {"sha256"}):
        raise Failure("invalid expectations")
    if not isinstance(value["sha256"], str) or not re.fullmatch(r"[0-9a-f]{64}", value["sha256"]):
        raise Failure("invalid expectations")
    return value


def open_input(path: str):
    try:
        fd = os.open(path, os.O_RDONLY | getattr(os, "O_NOFOLLOW", 0) | getattr(os, "O_NONBLOCK", 0))
        if not stat.S_ISREG(os.fstat(fd).st_mode):
            os.close(fd)
            raise Failure("input must be a regular file")
        return os.fdopen(fd, "rb")
    except OSError:
        raise Failure("cannot open regular input file") from None


def expectations(path: str | None) -> dict | None:
    if path is None:
        return None
    with open_input(path) as stream:
        raw = stream.read(65537)
    if len(raw) > 65536:
        raise Failure("expectations too large")
    try:
        value = json.loads(raw)
        return inventory(value.get("inventory") if isinstance(value, dict) and "inventory" in value else value)
    except (ValueError, UnicodeError):
        raise Failure("invalid expectations") from None


def private_report(path: str, report: dict) -> None:
    # Never follow a symlink or overwrite a prior result, archive or other file.
    try:
        fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        with os.fdopen(fd, "w", encoding="utf-8") as stream:
            json.dump(report, stream, sort_keys=True)
            stream.write("\n")
    except OSError:
        raise Failure("cannot create new private report") from None


def archive_hash(stream, deadline: float) -> str:
    digest = hashlib.sha256()
    while chunk := stream.read(1024 * 1024):
        digest.update(chunk)
        if time.monotonic() >= deadline:
            raise Failure("time limit exceeded")
    return digest.hexdigest()


class Sandbox:
    def __init__(self, deadline: float):
        self.deadline = deadline
        self.token = uuid.uuid4().hex
        self.name = "kervax-mongo-restore-" + self.token
        self.created = False

    def run(self, args, *, stdin=None, data=None, capture=True, timeout=None):
        remaining = self.deadline - time.monotonic()
        if remaining <= 0:
            raise Failure("time limit exceeded")
        try:
            return subprocess.run(["docker", *args], stdin=stdin, input=data,
                                  stdout=subprocess.PIPE if capture else subprocess.DEVNULL,
                                  stderr=subprocess.DEVNULL, timeout=min(remaining, timeout or remaining),
                                  check=False)
        except (OSError, subprocess.TimeoutExpired):
            raise Failure("Docker command failed or timed out") from None

    def shell(self, script: str):
        return self.run(["exec", "-i", "--env", "HOME=/tmp", self.name,
                         "mongosh", "--quiet", "--norc", "--file", "/dev/stdin"], data=script.encode())

    def close(self):
        if not self.created:
            return
        requested = []
        def defer(signum, _frame):
            requested.append(signum)
        previous = {signum: signal.signal(signum, defer) for signum in (signal.SIGINT, signal.SIGTERM)}
        try:
            self.remove()
        finally:
            for signum, handler in previous.items():
                signal.signal(signum, handler)
        if requested:
            raise Failure("verification interrupted during cleanup")

    def remove(self):
        if self.created:
            # Check ownership, then remove the immutable id, never a reused name.
            try:
                check = subprocess.run(["docker", "inspect", "--format",
                                        '{{.Id}} {{index .Config.Labels "kervax.restore.token"}}', self.name],
                                       stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, timeout=10)
                if check.returncode:
                    absent = subprocess.run(["docker", "container", "ls", "--all", "--quiet", "--no-trunc",
                                             "--filter", "name=^/" + self.name + "$"],
                                            stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, timeout=10)
                    if absent.returncode or absent.stdout.strip():
                        raise Failure("sandbox cleanup could not be confirmed")
                    return  # create failed before creating a container
                fields = check.stdout.decode().split()
                if len(fields) != 2 or fields[1] != self.token or not re.fullmatch(r"[0-9a-f]{64}", fields[0]):
                    raise Failure("sandbox ownership could not be confirmed")
                result = subprocess.run(["docker", "rm", "--force", "--volumes", fields[0]],
                                        stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=30)
                if result.returncode:
                    raise Failure("sandbox cleanup failed")
            except (OSError, subprocess.TimeoutExpired):
                raise Failure("sandbox cleanup failed") from None


def perform(args, report: dict) -> None:
    expected = expectations(args.expect)
    deadline = time.monotonic() + args.timeout
    box = Sandbox(deadline)
    with open_input(args.archive) as archive:
        start = os.fstat(archive.fileno())
        sha = archive_hash(archive, deadline)
        report["archive_sha256"] = sha
        archive.seek(0)
        try:
            with gzip.GzipFile(fileobj=archive) as compressed:
                total = 0
                while chunk := compressed.read(1024 * 1024):
                    total += len(chunk)
                    if total > args.storage_mib * 1024 * 1024:
                        raise Failure("unpacked archive exceeds storage limit")
                    if time.monotonic() >= deadline:
                        raise Failure("time limit exceeded")
        except (OSError, EOFError, zlib.error):
            raise Failure("corrupt gzip archive") from None
        archive.seek(0)
        try:
            image = box.run(["image", "inspect", args.image, "--format", "{{.Id}}"])
            if image.returncode or not re.fullmatch(rb"sha256:[0-9a-f]{64}\s*", image.stdout):
                raise Failure("image must already be available locally")
            image_id = image.stdout.decode().strip()
            report["image_id"] = image_id
            create = ["create", "--name", box.name, "--network", "none", "--user", "999:999",
                      "--label", "kervax.restore.token=" + box.token,
                      "--cap-drop", "ALL", "--security-opt", "no-new-privileges", "--read-only",
                      "--memory", f"{args.memory_mib}m", "--memory-swap", f"{args.memory_mib}m",
                      "--cpus", "1", "--pids-limit", "128", "--log-driver", "none",
                      "--tmpfs", "/tmp:rw,noexec,nosuid,nodev,size=67108864",
                      "--tmpfs", f"/data/db:rw,nosuid,nodev,uid=999,gid=999,size={args.storage_mib * 1024 * 1024}",
                      "--tmpfs", "/data/configdb:rw,nosuid,nodev,uid=999,gid=999,size=16777216",
                      image_id, "mongod", "--bind_ip", "127.0.0.1", "--port", "27017",
                      "--nounixsocket", "--noauth", "--wiredTigerCacheSizeGB", "0.25"]
            # Mark before create: a timeout can occur after the daemon created it.
            box.created = True
            if box.run(create, capture=False).returncode or box.run(["start", box.name], capture=False).returncode:
                raise Failure("cannot start isolated MongoDB")
            while True:
                ping = box.shell(PING_JS)
                if ping.returncode == 0:
                    break
                if deadline - time.monotonic() <= 1:
                    raise Failure("MongoDB readiness timed out")
                time.sleep(0.25)
            tool = box.run(["exec", box.name, "mongorestore", "--version"])
            if tool.returncode:
                raise Failure("mongorestore unavailable")
            match = re.search(rb"mongorestore version: ([0-9.]+)", tool.stdout)
            if not match:
                raise Failure("mongorestore version unavailable")
            report["tools_version"] = match.group(1).decode()
            command = ["exec", "-i", box.name, "mongorestore", "--host", "127.0.0.1", "--port", "27017",
                       "--gzip", "--archive", "--objcheck", "--stopOnError", "--numParallelCollections=1",
                       "--numInsertionWorkersPerCollection=1"]
            if args.mode == "replica":
                command.append("--oplogReplay")
            if box.run(command, stdin=archive, capture=False).returncode:
                raise Failure("full archive restore failed")
            # Reading the gzip header or an empty prefix never reaches this status.
            report["restore_ok"] = True
            checked = box.shell(INVENTORY_JS)
            if checked.returncode or len(checked.stdout) > 65536:
                raise Failure("restored database validation failed")
            try:
                observed = json.loads(checked.stdout)
                report["inventory"] = inventory(observed["inventory"])
                version = observed["version"]
                if not isinstance(version, str) or not re.fullmatch(r"[0-9.]+(?:-[a-zA-Z0-9.-]+)?", version):
                    raise ValueError()
                report["mongo_version"] = version
            except (ValueError, KeyError, TypeError):
                raise Failure("invalid database validation response") from None
            # Prove the report belongs to the complete unchanged input descriptor.
            archive.seek(0)
            end = os.fstat(archive.fileno())
            same_file = all(getattr(start, key) == getattr(end, key) for key in
                            ("st_dev", "st_ino", "st_size", "st_mtime_ns", "st_ctime_ns"))
            if not same_file or archive_hash(archive, deadline) != sha:
                raise Failure("archive changed during verification")
            report["validation_ok"] = True
            if expected is not None:
                report["expectations_match"] = report["inventory"] == expected
                if not report["expectations_match"]:
                    raise Failure("restored data differs from expectations")
            report["ok"] = True
        finally:
            box.close()


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("archive", help="local gzip-compressed full mongodump archive")
    parser.add_argument("--image", required=True, help="locally installed source-compatible MongoDB image")
    parser.add_argument("--mode", choices=("standalone", "replica"), required=True)
    parser.add_argument("--quiesced", action="store_true", help="confirm writes were stopped for standalone dump")
    parser.add_argument("--expect", help="prior report or inventory JSON to compare with")
    parser.add_argument("--report", help="new private JSON result file (never overwritten)")
    parser.add_argument("--timeout", type=positive, default=600, help="total time budget in seconds")
    parser.add_argument("--memory-mib", type=positive, default=2048)
    parser.add_argument("--storage-mib", type=positive, default=1024, help="temporary in-memory data limit")
    args = parser.parse_args(argv)
    report = {"schema": 1, "ok": False, "restore_ok": False, "validation_ok": False,
              "expectations_match": None, "mode": args.mode}
    def interrupted(_signum, _frame):
        raise Failure("verification interrupted")
    signal.signal(signal.SIGTERM, interrupted)
    try:
        if args.mode == "standalone" and not args.quiesced:
            raise Failure("standalone requires confirmed write quiescence")
        if not re.fullmatch(r"[a-zA-Z0-9][a-zA-Z0-9._:/@-]*", args.image):
            raise Failure("invalid image reference")
        if args.memory_mib < 512 or args.storage_mib < 64:
            raise Failure("memory must be at least 512 MiB and storage at least 64 MiB")
        perform(args, report)
    except KeyboardInterrupt:
        report["ok"] = False
        report["error"] = "verification interrupted"
    except Failure as exc:
        report["ok"] = False
        report["error"] = str(exc)
    except (OSError, ValueError):
        report["ok"] = False
        report["error"] = "verification could not read or process local input"
    if args.report:
        try:
            private_report(args.report, report)
        except Failure as exc:
            report["ok"] = False
            report["error"] = str(exc)
    print(json.dumps(report, sort_keys=True))
    return 0 if report["ok"] else 1


if __name__ == "__main__":
    sys.exit(main())
