// Действия с сервером пишутся семейством (docker_restart, kube_logs, backup_run_now): новое
// действие без своей подписи хотя бы скажет, к чему относится
const FAMILY: [string, string][] = [
  ['docker_', 'контейнер'],
  ['kube_', 'Kubernetes'],
  ['backup_', 'бэкап'],
  ['vault_', 'сейф бэкапов'],
  ['agent_', 'агент'],
]

export function actLabel(code: string, t: T, target = ''): string {
  // очистка диска пишет и просмотр без удаления, и разбор "на что ушло место" (объект fix:mode)
  if (code === 'backup_disk_fix') {
    if (target.startsWith('analyze:')) return t('посмотрел, на что ушло место')
    if (target.split(':')[1] === 'preview') return t('посмотрел, что можно освободить')
  }
  if (ACT[code]) return t(ACT[code])
  const f = FAMILY.find(([p]) => code.startsWith(p))
  return f ? `${t(f[1])}: ${code.slice(f[0].length)}` : code
}
