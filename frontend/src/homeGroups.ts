// Группы "Требует действий" на главной: подпись (что за проблема, без имени сервера) и что значит
// "до нового" у заглушки этой группы. Общие для главной (ActGroup.tsx) и подписи заглушки в карточке
// и в "Заглушено" (mutes.tsx muteKindLabel)
type T = (k: string, p?: Record<string, string | number>) => string

// Заглушка группы до нового: home:<группа>@<отпечаток> (backend app/home_mute.py), у ОС - osupd:<вид>@
export const HOME_MUTE = 'home:'
// у этих групп нет состояния, кроме "есть": ключ без отпечатка, пункт вернется, если починили и
// сломалось снова, или руками
const PLAIN = new Set(['d-acc', 'k-acc', 'onb', 'bs-setup', 'gre-need'])

export function grpLabel(grp: string, t: T): string {
  const fixed: Record<string, string> = {
    'access-s': t('учетки с доступом, в которые давно не входят - проверьте, нужны ли они'),
    'access-w': t('слабые SSH-ключи - замените на ed25519'),
    'os-eol': t('поддержка ОС кончилась или скоро кончится'),
    'os-reboot': t('ждут перезагрузки после обновления ядра или библиотек'),
    'os-reboot-soft': t('обновлен только dbus - перезагрузить при случае'),
    'os-security': t('не установлены обновления безопасности'),
    'os-apt': t('список пакетов давно не обновлялся'),
    'ssh-ssh_password': t('SSH пускает по паролю'),
    'noboot-u': t('после перезагрузки не запустятся юниты: работают, но не включены'),
    'noboot-d': t('после перезагрузки не поднимутся контейнеры без restart policy'),
    dbdump: t('базы без отдельного дампа'),
    'd-acc': t('Docker без доступа - включите read-only proxy'),
    'k-acc': t('Kubernetes без доступа - запустите kube-setup'),
    'd-old': t('устарел образ внешнего прокси - обновите'),
    'k-noagent': t('ноды кластера без агента'),
    // пункта больше нет, подпись для оставшихся заглушек
    'wear-plan': t('диски дойдут до 90% износа за полгода - запланируйте замену'),
    'bs-restic': t('на сервере бэкапов старый restic - обновите'),
    'bs-setup': t('бэкап-сервер без статистики - запустите backupserver-setup'),
    'bk-http': t('бэкап идет по http без шифрования - переведите на https'),
    onb: t('новые серверы: проверьте, что нашлось при подключении, и закройте подключение в карточке'),
    dockrisk: t('у контейнеров ключи от хоста - взлом приложения в них даст root на сервере'),
    'sw-eol': t('ПО без поддержки - обновите'),
    'sw-soon': t('скоро кончится поддержка ПО - запланируйте обновление'),
    'gre-need': t('соединение до панели режут после ~16кб - включите GRE до панели'),
  }
  return fixed[grp] ?? grp
}

// Подсказка у 🔕 и "заглушить выбранные": когда пункт вернется сам
export function grpMuteTip(grp: string, t: T): string {
  if (PLAIN.has(grp)) return t('Заглушить: пункт вернется, если его поправят и он появится снова, или раньше руками - здесь или в карточке')
  const when: Record<string, string> = {
    'os-reboot': t('если обновится новое ядро или пакет или сервер перезагрузится и снова попросит перезагрузку'),
    'os-reboot-soft': t('если обновится новое ядро или пакет или сервер перезагрузится и снова попросит перезагрузку'),
    'os-eol': t('при смене версии ОС или когда сменится срок: кончится обычная поддержка, подключат Ubuntu Pro, подойдет конец ESM'),
    'os-security': t('если сменится причина: автообновления выключат, удалят или они перестанут запускаться'),
    'os-apt': t('если после следующего apt update список снова застареет'),
    'd-old': t('если устареет другой прокси или сменится образ'),
    'k-noagent': t('если появится еще нода без агента'),
    'wear-plan': t('если к замене подойдет еще диск'),
    'bs-restic': t('если сменится версия restic'),
    dbdump: t('если появится еще база без дампа'),
    'bk-http': t('если бэкап пойдет по http на другой адрес'),
    'sw-eol': t('если без поддержки окажется еще ПО или версия'),
    'sw-soon': t('если поддержка кончается еще у какого-то ПО или версии'),
    dockrisk: t('если ключи от хоста появятся у другого контейнера или изменятся'),
    'noboot-d': t('если появятся еще такие контейнеры'),
    'noboot-u': t('если появятся еще такие юниты'),
    'access-s': t('если появятся еще такие учетки'),
    'access-w': t('если появятся еще такие учетки'),
    'ssh-ssh_password': t('если по паролю станут пускать и root'),
  }
  return `${t('Заглушить до нового: пункт вернется сам')} ${when[grp] ?? t('если появится новое')}`
}

// Подпись под галками: что будет с заглушенными
export function grpMuteNote(grp: string, t: T): string {
  return PLAIN.has(grp) ? t('вернуть можно здесь или в карточке') : t('вернутся сами, если появится новое')
}

// Подпись заглушки группы в карточке и в "Заглушено": home:<группа>@<отпечаток>
export function homeMuteLabel(k: string, t: T): string | null {
  if (!k.startsWith(HOME_MUTE)) return null
  const [grp, sig] = k.slice(HOME_MUTE.length).split('@')
  return `${t('Требует действий')}: ${grpLabel(grp, t)}${sig ? ` (${t('до нового')})` : ''}`
}
